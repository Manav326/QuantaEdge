-- Course release is shared metadata around the existing shared curriculum content graph.
-- It does not clone learner data or the program/subject/chapter/lesson/question rows.
CREATE TABLE institution_course_release (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  source_institution_id bigint NOT NULL REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  program_id bigint NOT NULL REFERENCES curriculum_program(id) ON DELETE RESTRICT,
  release_version integer NOT NULL CHECK (release_version > 0),
  release_state varchar(24) NOT NULL DEFAULT 'DRAFT'
    CHECK (release_state IN (
      'DRAFT','IN_QUALITY_REVIEW','QUALITY_APPROVED','SHAREABLE',
      'LEGACY_MIGRATED','WITHDRAWN','REJECTED'
    )),
  content_fingerprint char(32) NOT NULL CHECK (content_fingerprint ~ '^[0-9a-f]{32}$'),
  submitted_by_institution_admin_id bigint REFERENCES institution_admin_account(id) ON DELETE SET NULL,
  submitted_at timestamptz,
  quality_reviewed_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  quality_reviewed_at timestamptz,
  quality_review_notes text,
  origin_approved_by_admin_id bigint REFERENCES institution_admin_account(id) ON DELETE SET NULL,
  origin_approved_at timestamptz,
  shareable_at timestamptz,
  withdrawn_by_admin_id bigint REFERENCES institution_admin_account(id) ON DELETE SET NULL,
  withdrawn_at timestamptz,
  legacy_migration boolean NOT NULL DEFAULT false,
  legacy_migration_note text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(source_institution_id,program_id,release_version),
  UNIQUE(id,program_id),
  CHECK (release_state NOT IN ('QUALITY_APPROVED','SHAREABLE')
      OR (quality_reviewed_by_staff_id IS NOT NULL AND quality_reviewed_at IS NOT NULL)),
  CHECK (release_state <> 'SHAREABLE'
      OR (origin_approved_by_admin_id IS NOT NULL AND origin_approved_at IS NOT NULL AND shareable_at IS NOT NULL)),
  CHECK (release_state <> 'IN_QUALITY_REVIEW' OR submitted_at IS NOT NULL)
);
CREATE INDEX idx_institution_course_release_shareable
  ON institution_course_release(release_state,source_institution_id,program_id,release_version DESC);
CREATE INDEX idx_institution_course_release_source
  ON institution_course_release(source_institution_id,created_at DESC,id DESC);

-- An assignment is an HRMS control-plane action. It does not publish a marketplace offer.
CREATE TABLE institution_course_assignment (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institution_id bigint NOT NULL REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  course_release_id bigint NOT NULL REFERENCES institution_course_release(id) ON DELETE RESTRICT,
  status varchar(12) NOT NULL DEFAULT 'ASSIGNED' CHECK (status IN ('ASSIGNED','REVOKED')),
  assignment_source varchar(48) NOT NULL DEFAULT 'HRMS'
    CHECK (assignment_source IN ('HRMS','LEGACY_ENTITLEMENT_MIGRATION','LEGACY_QUANTAEDGE_CATALOG')),
  assigned_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  assigned_at timestamptz NOT NULL DEFAULT now(),
  revoked_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  revoked_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(institution_id,course_release_id),
  UNIQUE(institution_id,id),
  CHECK ((status='REVOKED' AND revoked_at IS NOT NULL) OR (status='ASSIGNED' AND revoked_at IS NULL))
);
CREATE INDEX idx_institution_course_assignment_active
  ON institution_course_assignment(institution_id,status,course_release_id);

-- Each institution has its own approval/publication/price lifecycle for an assignment.
CREATE TABLE institution_marketplace_offer (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  institution_id bigint NOT NULL REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  assignment_id bigint NOT NULL,
  course_release_id bigint NOT NULL,
  course_id bigint NOT NULL,
  title_override varchar(200),
  description text,
  price_paise bigint NOT NULL CHECK (price_paise >= 0),
  currency varchar(3) NOT NULL DEFAULT 'INR' CHECK (currency ~ '^[A-Z]{3}$'),
  status varchar(16) NOT NULL DEFAULT 'DRAFT'
    CHECK (status IN ('DRAFT','IN_REVIEW','APPROVED','PUBLISHED','REJECTED','ARCHIVED')),
  submitted_by_admin_id bigint REFERENCES institution_admin_account(id) ON DELETE SET NULL,
  submitted_at timestamptz,
  approved_by_admin_id bigint REFERENCES institution_admin_account(id) ON DELETE SET NULL,
  approved_at timestamptz,
  published_by_admin_id bigint REFERENCES institution_admin_account(id) ON DELETE SET NULL,
  published_at timestamptz,
  rejected_by_admin_id bigint REFERENCES institution_admin_account(id) ON DELETE SET NULL,
  rejected_at timestamptz,
  rejection_reason varchar(1000),
  legacy_migration boolean NOT NULL DEFAULT false,
  legacy_migration_note text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY (institution_id,assignment_id)
    REFERENCES institution_course_assignment(institution_id,id) ON DELETE RESTRICT,
  FOREIGN KEY (course_release_id,course_id)
    REFERENCES institution_course_release(id,program_id) ON DELETE RESTRICT,
  UNIQUE(institution_id,assignment_id),
  UNIQUE(institution_id,id,course_id),
  CHECK (title_override IS NULL OR length(btrim(title_override)) > 0),
  CHECK (status NOT IN ('APPROVED','PUBLISHED') OR approved_at IS NOT NULL OR legacy_migration),
  CHECK (status <> 'PUBLISHED' OR published_at IS NOT NULL OR legacy_migration),
  CHECK ((status='IN_REVIEW' AND submitted_at IS NOT NULL) OR status<>'IN_REVIEW'),
  CHECK ((status='REJECTED' AND rejected_at IS NOT NULL) OR status<>'REJECTED')
);
CREATE INDEX idx_institution_marketplace_offer_discovery
  ON institution_marketplace_offer(institution_id,status,updated_at DESC,id DESC);
CREATE INDEX idx_institution_marketplace_offer_course
  ON institution_marketplace_offer(institution_id,course_id,status);

