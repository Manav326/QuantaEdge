-- V115: unified verified identities, account credentials and irreversible course ownership.
-- Existing account/student primary keys and existing payment records remain intact.
ALTER TABLE user_account ALTER COLUMN mobile_e164 DROP NOT NULL;

ALTER TABLE user_account
  ADD COLUMN email varchar(320),
  ADD COLUMN email_verified_at timestamptz,
  ADD COLUMN google_subject varchar(255),
  ADD COLUMN google_picture_url text,
  ADD COLUMN google_given_name varchar(120),
  ADD COLUMN google_family_name varchar(120),
  ADD COLUMN google_locale varchar(24),
  ADD COLUMN mobile_verified_at timestamptz,
  ADD COLUMN username varchar(32),
  ADD COLUMN username_changed_at timestamptz,
  ADD COLUMN preferred_locale varchar(32) NOT NULL DEFAULT 'hinglish';

-- All currently provisioned end-user mobiles were accepted through the OTP signup flow.
-- Keep this separate from Gmail verification; no email is marked verified by this backfill.
UPDATE user_account
SET mobile_verified_at = created_at
WHERE mobile_e164 IS NOT NULL AND mobile_verified_at IS NULL;

CREATE UNIQUE INDEX uq_user_account_verified_email
  ON user_account(lower(email))
  WHERE email IS NOT NULL;

CREATE UNIQUE INDEX uq_user_account_google_subject
  ON user_account(google_subject)
  WHERE google_subject IS NOT NULL;

CREATE UNIQUE INDEX uq_user_account_username
  ON user_account(lower(username))
  WHERE username IS NOT NULL;

ALTER TABLE user_account
  ADD CONSTRAINT ck_user_account_email_format
    CHECK (email IS NULL OR (length(email) <= 320 AND email = btrim(email))),
  ADD CONSTRAINT ck_user_account_username_format
    CHECK (username IS NULL OR username ~ '^[a-z0-9][a-z0-9._-]{2,31}$'),
  ADD CONSTRAINT ck_user_account_verified_gmail
    CHECK (email_verified_at IS NULL OR
      (email IS NOT NULL AND lower(email) ~ '^[^@[:space:]]+@gmail[.]com$'
       AND google_subject IS NOT NULL));

-- Mobile-only and Google-Gmail signups both use the existing one-time-code ledger.
-- Discover and replace the historical purpose check instead of piling up conflicting checks.
DO $purpose_check$
DECLARE c record;
BEGIN
  FOR c IN
    SELECT conname FROM pg_constraint
    WHERE conrelid='public.otp_challenge'::regclass AND contype='c'
      AND pg_get_constraintdef(oid) ILIKE '%purpose%'
  LOOP
    EXECUTE format('ALTER TABLE public.otp_challenge DROP CONSTRAINT %I', c.conname);
  END LOOP;
END;
$purpose_check$;

ALTER TABLE otp_challenge
  ADD CONSTRAINT otp_challenge_purpose_supported
  CHECK (purpose IN ('LOGIN','SIGNUP','STAFF_LOGIN','PASSWORD_RESET','LEARNER_TRANSITION','ACCOUNT_SIGNUP'));

-- Existing student purchase rows remain the historical ledger. The normalized entitlement
-- defines the current, exclusive holder and is what makes parent-to-child transfer auditable.
ALTER TABLE course_payment_order
  ALTER COLUMN student_id DROP NOT NULL,
  ADD COLUMN purchaser_user_id bigint REFERENCES user_account(id) ON DELETE RESTRICT,
  ADD COLUMN target_student_id bigint REFERENCES student(id) ON DELETE RESTRICT,
  ADD COLUMN recipient_type varchar(16) NOT NULL DEFAULT 'STUDENT'
    CHECK (recipient_type IN ('STUDENT','PARENT','CHILD'));

ALTER TABLE course_purchase
  ALTER COLUMN student_id DROP NOT NULL,
  ADD COLUMN purchaser_user_id bigint REFERENCES user_account(id) ON DELETE RESTRICT;

CREATE INDEX idx_course_payment_order_purchaser
  ON course_payment_order(purchaser_user_id, created_at DESC)
  WHERE purchaser_user_id IS NOT NULL;

CREATE UNIQUE INDEX uq_course_payment_order_purchaser_open
  ON course_payment_order(purchaser_user_id, course_id, client_request_key)
  WHERE purchaser_user_id IS NOT NULL;

CREATE TABLE course_entitlement (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id bigint NOT NULL REFERENCES curriculum_program(id) ON DELETE RESTRICT,
  source_purchase_id bigint UNIQUE REFERENCES course_purchase(id) ON DELETE RESTRICT,
  holder_user_id bigint REFERENCES user_account(id) ON DELETE RESTRICT,
  holder_student_id bigint REFERENCES student(id) ON DELETE RESTRICT,
  granted_by_user_id bigint REFERENCES user_account(id) ON DELETE SET NULL,
  transfer_count integer NOT NULL DEFAULT 0 CHECK (transfer_count BETWEEN 0 AND 1),
  transferred_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((holder_user_id IS NOT NULL)::integer + (holder_student_id IS NOT NULL)::integer = 1),
  CHECK ((transfer_count = 0 AND transferred_at IS NULL) OR
         (transfer_count = 1 AND transferred_at IS NOT NULL))
);

CREATE UNIQUE INDEX uq_course_entitlement_user_course
  ON course_entitlement(holder_user_id, course_id)
  WHERE holder_user_id IS NOT NULL;

CREATE UNIQUE INDEX uq_course_entitlement_student_course
  ON course_entitlement(holder_student_id, course_id)
  WHERE holder_student_id IS NOT NULL;

-- Every historical paid purchase already belongs to its student. Preserve that ownership.
INSERT INTO course_entitlement(course_id, source_purchase_id, holder_student_id, created_at, updated_at)
SELECT cp.course_id, cp.id, cp.student_id, cp.purchased_at, cp.purchased_at
FROM course_purchase cp
WHERE cp.student_id IS NOT NULL
ON CONFLICT (source_purchase_id) DO NOTHING;

CREATE TABLE parent_course_purchase_request (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guardian_user_id bigint NOT NULL REFERENCES user_account(id) ON DELETE RESTRICT,
  student_id bigint NOT NULL REFERENCES student(id) ON DELETE RESTRICT,
  course_id bigint NOT NULL REFERENCES curriculum_program(id) ON DELETE RESTRICT,
  status varchar(16) NOT NULL DEFAULT 'PENDING'
    CHECK (status IN ('PENDING','PURCHASED','DECLINED','CANCELLED')),
  requested_at timestamptz NOT NULL DEFAULT now(),
  resolved_at timestamptz,
  resolved_by_user_id bigint REFERENCES user_account(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(student_id, course_id, status)
);

CREATE INDEX idx_parent_course_request_guardian
  ON parent_course_purchase_request(guardian_user_id, status, requested_at DESC);

CREATE INDEX idx_parent_course_request_student
  ON parent_course_purchase_request(student_id, status, requested_at DESC);

CREATE TABLE course_entitlement_transfer_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entitlement_id bigint NOT NULL REFERENCES course_entitlement(id) ON DELETE RESTRICT,
  course_id bigint NOT NULL REFERENCES curriculum_program(id) ON DELETE RESTRICT,
  from_user_id bigint NOT NULL REFERENCES user_account(id) ON DELETE RESTRICT,
  to_student_id bigint NOT NULL REFERENCES student(id) ON DELETE RESTRICT,
  transferred_at timestamptz NOT NULL DEFAULT now(),
  transfer_number integer NOT NULL CHECK (transfer_number = 1),
  UNIQUE(entitlement_id),
  UNIQUE(course_id, from_user_id, to_student_id, transfer_number)
);

