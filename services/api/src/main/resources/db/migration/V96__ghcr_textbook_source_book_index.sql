-- V96: allow full-book page text indexed directly from the durable class-wise GHCR cache.
-- The original PDF remains in GHCR; source-page text is stored independently and review-gated.
create table textbook_source_book (
  id bigint generated by default as identity primary key,
  registry_book_id varchar(240) not null,
  source_sha256 varchar(64) not null,
  source_title varchar(500) not null,
  source_url varchar(1000) not null,
  edition varchar(160) not null default 'edition not recorded',
  class_id bigint not null references curriculum_class(id) on delete restrict,
  subject_id bigint not null references curriculum_subject(id) on delete restrict,
  language varchar(2) not null check (language in ('hi','en')),
  total_pages integer not null check (total_pages between 1 and 2000),
  status varchar(20) not null default 'DRAFT'
    check (status in ('DRAFT','APPROVED','ARCHIVED')),
  imported_pages integer not null default 0 check (imported_pages >= 0),
  imported_by_staff_id bigint references staff_account(id) on delete set null,
  imported_at timestamptz not null default now(),
  approved_by_staff_id bigint references staff_account(id) on delete set null,
  approved_at timestamptz,
  updated_at timestamptz not null default now(),
  unique(registry_book_id, source_sha256, language)
);

alter table textbook_extracted_page
  alter column pdf_asset_id drop not null,
  add column source_book_id bigint references textbook_source_book(id) on delete cascade;

alter table textbook_extracted_page
  add constraint ck_textbook_extracted_page_has_source
  check (pdf_asset_id is not null or source_book_id is not null);

create unique index uq_textbook_extracted_page_source_book_page
  on textbook_extracted_page(source_book_id, page_no)
  where source_book_id is not null;

create index idx_textbook_source_book_scope
  on textbook_source_book(class_id, subject_id, language, status);

insert into app_metadata(key,value)
values ('schema','ghcr-textbook-source-book-index-v96')
on conflict(key) do update set value=excluded.value;
