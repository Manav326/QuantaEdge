-- Immutable, checksum-verifiable PDFs generated from a saved payout-batch/recipient snapshot.
-- A settlement statement is operational payout advice, not a fiscal document.
CREATE TABLE finance_payout_statement_document (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  document_number varchar(120) NOT NULL UNIQUE,
  batch_id bigint NOT NULL REFERENCES finance_payout_batch(id) ON DELETE RESTRICT,
  payout_id bigint REFERENCES finance_payout(id) ON DELETE RESTRICT,
  document_type varchar(24) NOT NULL CHECK(document_type IN ('BATCH_SUMMARY','RECIPIENT_STATEMENT')),
  revision integer NOT NULL CHECK(revision>0),
  snapshot_json jsonb NOT NULL CHECK(jsonb_typeof(snapshot_json)='object'),
  storage_key varchar(64) NOT NULL CHECK(storage_key ~ '^[0-9a-fA-F-]{36}\.pdf$'),
  sha256 char(64) NOT NULL CHECK(sha256 ~ '^[0-9a-f]{64}$'),
  byte_length bigint NOT NULL CHECK(byte_length>0 AND byte_length<=26214400),
  generated_by_staff_id bigint NOT NULL REFERENCES staff_account(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK((document_type='BATCH_SUMMARY' AND payout_id IS NULL)
     OR (document_type='RECIPIENT_STATEMENT' AND payout_id IS NOT NULL))
);
CREATE UNIQUE INDEX uq_finance_payout_statement_batch_revision
  ON finance_payout_statement_document(batch_id,revision)
  WHERE document_type='BATCH_SUMMARY';
CREATE UNIQUE INDEX uq_finance_payout_statement_recipient_revision
  ON finance_payout_statement_document(batch_id,payout_id,revision)
  WHERE document_type='RECIPIENT_STATEMENT';
CREATE INDEX idx_finance_payout_statement_batch_history
  ON finance_payout_statement_document(batch_id,created_at DESC,id DESC);
CREATE INDEX idx_finance_payout_statement_recipient_history
  ON finance_payout_statement_document(payout_id,created_at DESC,id DESC)
  WHERE payout_id IS NOT NULL;

CREATE TABLE finance_payout_statement_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  statement_document_id bigint NOT NULL REFERENCES finance_payout_statement_document(id) ON DELETE RESTRICT,
  event_type varchar(24) NOT NULL CHECK(event_type IN ('GENERATED','DOWNLOADED')),
  idempotency_key varchar(180) NOT NULL UNIQUE,
  actor_staff_id bigint NOT NULL REFERENCES staff_account(id) ON DELETE RESTRICT,
  details jsonb NOT NULL DEFAULT '{}'::jsonb CHECK(jsonb_typeof(details)='object'),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_finance_payout_statement_event_history
  ON finance_payout_statement_event(statement_document_id,created_at,id);
CREATE TRIGGER trg_finance_payout_statement_document_immutable
BEFORE UPDATE OR DELETE ON finance_payout_statement_document
FOR EACH ROW EXECUTE FUNCTION reject_billing_financial_mutation();
CREATE TRIGGER trg_finance_payout_statement_event_immutable
BEFORE UPDATE OR DELETE ON finance_payout_statement_event
FOR EACH ROW EXECUTE FUNCTION reject_billing_financial_mutation();

