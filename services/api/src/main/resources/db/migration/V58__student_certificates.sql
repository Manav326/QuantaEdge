-- V58: durable, verifiable student certificates with issuance/revocation audit.
CREATE TABLE student_certificate (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  certificate_number varchar(40) NOT NULL UNIQUE
    CHECK (certificate_number ~ '^QE-[0-9]{4}-[A-F0-9]{16}$'),
  student_id bigint NOT NULL REFERENCES student(id) ON DELETE RESTRICT,
  achievement_key varchar(180) NOT NULL,
  achievement_type varchar(32) NOT NULL CHECK (achievement_type IN ('SUBJECT_COMPLETION','ASSESSMENT_PASS')),
  class_code varchar(30) NOT NULL REFERENCES curriculum_class(code) ON DELETE RESTRICT,
  subject_id bigint REFERENCES curriculum_subject(id) ON DELETE RESTRICT,
  assessment_attempt_id bigint REFERENCES student_assessment_attempt(id) ON DELETE RESTRICT,
  template_id varchar(16) NOT NULL CHECK (template_id IN ('CLASSIC','MODERN','ACADEMIC')),
  language varchar(5) NOT NULL CHECK (language IN ('hi','en')),
  recipient_name varchar(120) NOT NULL,
  achievement_title varchar(240) NOT NULL,
  achievement_summary varchar(600) NOT NULL,
  achievement_snapshot jsonb NOT NULL,
  status varchar(12) NOT NULL DEFAULT 'ISSUED' CHECK (status IN ('ISSUED','REVOKED')),
  issued_at timestamptz NOT NULL DEFAULT now(),
  revoked_at timestamptz,
  revoked_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  revocation_reason varchar(500),
  pdf_storage_key varchar(80) NOT NULL UNIQUE,
  png_storage_key varchar(80) NOT NULL UNIQUE,
  pdf_sha256 char(64) NOT NULL CHECK (pdf_sha256 ~ '^[a-f0-9]{64}$'),
  png_sha256 char(64) NOT NULL CHECK (png_sha256 ~ '^[a-f0-9]{64}$'),
  pdf_size_bytes bigint NOT NULL CHECK (pdf_size_bytes > 0),
  png_size_bytes bigint NOT NULL CHECK (png_size_bytes > 0),
  UNIQUE(student_id, achievement_key),
  CHECK (
    (achievement_type = 'SUBJECT_COMPLETION' AND subject_id IS NOT NULL AND assessment_attempt_id IS NULL)
    OR
    (achievement_type = 'ASSESSMENT_PASS' AND subject_id IS NOT NULL AND assessment_attempt_id IS NOT NULL)
  ),
  CHECK (
    (status = 'ISSUED' AND revoked_at IS NULL AND revoked_by_staff_id IS NULL AND revocation_reason IS NULL)
    OR
    (status = 'REVOKED' AND revoked_at IS NOT NULL AND revocation_reason IS NOT NULL)
  )
);
CREATE INDEX idx_student_certificate_student_issued ON student_certificate(student_id, issued_at DESC, id DESC);
CREATE INDEX idx_student_certificate_status_issued ON student_certificate(status, issued_at DESC, id DESC);
CREATE INDEX idx_student_certificate_attempt ON student_certificate(assessment_attempt_id) WHERE assessment_attempt_id IS NOT NULL;

CREATE TABLE certificate_audit_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  certificate_id bigint NOT NULL REFERENCES student_certificate(id) ON DELETE RESTRICT,
  actor_student_id bigint REFERENCES student(id) ON DELETE SET NULL,
  actor_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  actor_role varchar(16) NOT NULL CHECK (actor_role IN ('STUDENT','ADMIN','SYSTEM')),
  action varchar(24) NOT NULL CHECK (action IN ('ISSUED','REVOCATION_REQUESTED','REVOKED')),
  detail jsonb NOT NULL DEFAULT '{}'::jsonb,
  occurred_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_certificate_audit_certificate_time ON certificate_audit_log(certificate_id, occurred_at DESC, id DESC);

INSERT INTO app_metadata(key, value)
VALUES ('schema', 'student-certificates-v58')
ON CONFLICT (key) DO UPDATE SET value = excluded.value;
