-- V139: tenant/course-scoped publication assignments for shared learning-document bytes.
-- The PDF asset and immutable source document metadata may be reused; visibility/publication
-- belongs to a particular institution + course, never just to a legacy class/subject.
ALTER TABLE learning_document
  ADD CONSTRAINT uq_learning_document_id_subject UNIQUE (id, subject_id);

CREATE TABLE learning_document_course_assignment (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institution_id bigint NOT NULL REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  course_id bigint NOT NULL,
  learning_document_id bigint NOT NULL,
  subject_id bigint NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'DRAFT'
    CHECK (status IN ('DRAFT','PUBLISHED','ARCHIVED')),
  created_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  published_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  published_at timestamptz,
  CONSTRAINT fk_learning_document_course_assignment_course_subject
    FOREIGN KEY (course_id, subject_id)
    REFERENCES curriculum_program_subject(program_id, subject_id) ON DELETE RESTRICT,
  CONSTRAINT fk_learning_document_course_assignment_document_subject
    FOREIGN KEY (learning_document_id, subject_id)
    REFERENCES learning_document(id, subject_id) ON DELETE RESTRICT,
  UNIQUE (institution_id, course_id, learning_document_id)
);

CREATE INDEX idx_learning_document_course_assignment_scope
  ON learning_document_course_assignment(institution_id, course_id, status, subject_id, learning_document_id);

-- Backfill documents produced by the old course-scoped ingestion workflow to the exact job's
-- institution and course first. Do not fan those rows out merely because another course maps
-- the same canonical subject.
WITH job_documents AS (
  SELECT DISTINCT ch.learning_document_id AS document_id, j.institution_id, j.course_id, j.subject_id,
         j.reviewed_by_staff_id AS reviewer_id, j.reviewed_at
  FROM source_ingestion_chapter ch
  JOIN source_ingestion_job j ON j.id=ch.job_id
  WHERE ch.learning_document_id IS NOT NULL
    AND j.institution_id IS NOT NULL AND j.course_id IS NOT NULL
  UNION
  SELECT DISTINCT d.id AS document_id, j.institution_id, j.course_id, d.subject_id,
         j.reviewed_by_staff_id AS reviewer_id, j.reviewed_at
  FROM learning_document d
  JOIN source_ingestion_job j ON j.book_asset_id=d.pdf_asset_id AND j.subject_id=d.subject_id
    AND j.status='APPROVED'
  WHERE d.scope='SUBJECT_BOOK'
    AND j.institution_id IS NOT NULL AND j.course_id IS NOT NULL
)
INSERT INTO learning_document_course_assignment(
  institution_id,course_id,learning_document_id,subject_id,status,
  created_by_staff_id,published_by_staff_id,created_at,updated_at,published_at
)
SELECT jd.institution_id,jd.course_id,d.id,d.subject_id,d.status,
       d.created_by_staff_id,
       CASE WHEN d.status='PUBLISHED' THEN jd.reviewer_id ELSE NULL END,
       d.created_at,d.updated_at,
       CASE WHEN d.status='PUBLISHED' THEN COALESCE(jd.reviewed_at,d.published_at) ELSE NULL END
FROM job_documents jd
JOIN learning_document d ON d.id=jd.document_id AND d.subject_id=jd.subject_id
JOIN institution_course_assignment a ON a.institution_id=jd.institution_id AND a.status='ASSIGNED'
JOIN institution_course_release r ON r.id=a.course_release_id AND r.program_id=jd.course_id
ON CONFLICT (institution_id,course_id,learning_document_id) DO NOTHING;

-- Remaining documents came from the old global deployment and are mapped only to its
-- explicit legacy destination, QuantaEdge. Never fan this legacy content out to other tenants.
-- New course-scoped ingestion rows are excluded from this backfill path.
INSERT INTO learning_document_course_assignment(
  institution_id,course_id,learning_document_id,subject_id,status,
  created_by_staff_id,published_by_staff_id,created_at,updated_at,published_at
)
SELECT DISTINCT a.institution_id,r.program_id,d.id,d.subject_id,d.status,
       d.created_by_staff_id,d.published_by_staff_id,d.created_at,d.updated_at,d.published_at
FROM learning_document d
JOIN curriculum_subject s ON s.id=d.subject_id AND s.active=true
JOIN curriculum_program_subject cps ON cps.subject_id=s.id AND cps.class_id=s.class_id
JOIN curriculum_program p ON p.id=cps.program_id AND p.status='ACTIVE' AND p.code<>'GENERAL'
JOIN institution_course_assignment a ON a.status='ASSIGNED'
JOIN institution_tenant tenant ON tenant.id=a.institution_id AND tenant.status='ACTIVE'
  AND tenant.tenant_code='QUANTA-EDGE'
JOIN institution_course_release r ON r.id=a.course_release_id AND r.program_id=p.id
WHERE (s.program_id=p.id OR (s.program_id IS NULL AND p.class_id=s.class_id))
  AND NOT EXISTS (
    SELECT 1 FROM learning_document_course_assignment existing
    WHERE existing.institution_id=a.institution_id AND existing.course_id=p.id
      AND existing.learning_document_id=d.id
  )
  AND NOT EXISTS (
    SELECT 1 FROM source_ingestion_chapter ch
    JOIN source_ingestion_job j ON j.id=ch.job_id
    WHERE ch.learning_document_id=d.id
      AND j.institution_id IS NOT NULL AND j.course_id IS NOT NULL
  )
  AND NOT EXISTS (
    SELECT 1 FROM source_ingestion_job j
    WHERE d.scope='SUBJECT_BOOK' AND j.book_asset_id=d.pdf_asset_id
      AND j.subject_id=d.subject_id AND j.status='APPROVED'
      AND j.institution_id IS NOT NULL AND j.course_id IS NOT NULL
  )
ON CONFLICT (institution_id,course_id,learning_document_id) DO NOTHING;

