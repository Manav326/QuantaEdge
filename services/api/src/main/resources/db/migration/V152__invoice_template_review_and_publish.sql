-- V152: separate invoice template review approvals from publishing.
-- The draft invoice definition stays unpublished while review is pending; publication remains a
-- separate operation. Review events are immutable for a clear audit trail.
CREATE TABLE invoice_template_version_review (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  template_version_id bigint NOT NULL UNIQUE
    REFERENCES invoice_template_version(id) ON DELETE RESTRICT,
  review_status varchar(20) NOT NULL
    CHECK (review_status IN ('PENDING_APPROVAL','APPROVED','REJECTED')),
  submitted_by_staff_id bigint NOT NULL REFERENCES staff_account(id) ON DELETE RESTRICT,
  submitted_at timestamptz NOT NULL DEFAULT now(),
  approved_by_staff_id bigint REFERENCES staff_account(id) ON DELETE RESTRICT,
  approved_at timestamptz,
  design_definition_snapshot jsonb NOT NULL
    CHECK (jsonb_typeof(design_definition_snapshot)='object'),
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (
    (review_status='PENDING_APPROVAL' AND approved_by_staff_id IS NULL AND approved_at IS NULL)
    OR
    (review_status IN ('APPROVED','REJECTED') AND approved_by_staff_id IS NOT NULL AND approved_at IS NOT NULL)
  )
);
CREATE INDEX idx_invoice_template_review_status
  ON invoice_template_version_review(review_status,submitted_at DESC);

CREATE TABLE invoice_template_version_review_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  review_id bigint NOT NULL REFERENCES invoice_template_version_review(id) ON DELETE RESTRICT,
  event_type varchar(24) NOT NULL CHECK (event_type IN ('SUBMITTED','APPROVED','REJECTED')),
  actor_staff_id bigint NOT NULL REFERENCES staff_account(id) ON DELETE RESTRICT,
  design_sha256 char(64) CHECK (design_sha256 IS NULL OR design_sha256 ~ '^[0-9a-f]{64}$'),
  details jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(details)='object'),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_invoice_template_review_event_history
  ON invoice_template_version_review_event(review_id,created_at,id);
CREATE TRIGGER trg_invoice_template_review_event_immutable
BEFORE UPDATE OR DELETE ON invoice_template_version_review_event
FOR EACH ROW EXECUTE FUNCTION reject_billing_financial_mutation();

INSERT INTO app_metadata(key,value)
