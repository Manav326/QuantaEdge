-- V116: durable identity audit and family-checkout uniqueness guards.
CREATE TABLE account_identity_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint REFERENCES user_account(id) ON DELETE SET NULL,
  actor_student_id bigint REFERENCES student(id) ON DELETE SET NULL,
  event_type varchar(48) NOT NULL,
  details jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_account_identity_audit_user
  ON account_identity_audit(user_id, created_at DESC, id DESC);

ALTER TABLE user_account
  ADD CONSTRAINT ck_user_account_mobile_verification
  CHECK (mobile_verified_at IS NULL OR mobile_e164 IS NOT NULL);

ALTER TABLE course_payment_order
  ADD CONSTRAINT ck_course_payment_recipient
  CHECK (
    (recipient_type='STUDENT' AND student_id IS NOT NULL) OR
    (recipient_type='PARENT' AND student_id IS NULL AND target_student_id IS NULL) OR
    (recipient_type='CHILD' AND student_id IS NOT NULL AND target_student_id=student_id)
  );

CREATE UNIQUE INDEX uq_course_payment_order_purchaser_open
  ON course_payment_order(purchaser_user_id, course_id)
  WHERE purchaser_user_id IS NOT NULL AND status IN ('CREATING','PENDING');

CREATE UNIQUE INDEX uq_course_purchase_parent_course
  ON course_purchase(purchaser_user_id, course_id)
  WHERE purchaser_user_id IS NOT NULL AND student_id IS NULL;

