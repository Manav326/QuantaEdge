  ON course_enrollment_access_event(course_identity_id,institution_id,created_at DESC,id DESC);

-- India Standard Time calendar arithmetic avoids relying on the database session timezone and is consistent
-- for every institution sharing the same logical course.
CREATE OR REPLACE FUNCTION qe_calculate_course_expiry(
  p_enrolled_at timestamptz,
  p_policy_mode varchar,
  p_calendar_years integer,
  p_calendar_months integer,
  p_calendar_days integer,
  p_fixed_days integer
) RETURNS timestamptz
LANGUAGE plpgsql
IMMUTABLE
AS $$
BEGIN
  IF p_enrolled_at IS NULL THEN
    RAISE EXCEPTION 'Enrollment timestamp is required for expiry calculation.';
  END IF;
  IF p_policy_mode='FIXED_DAYS' THEN
    IF p_fixed_days IS NULL OR p_fixed_days < 1 OR p_fixed_days > 36500 THEN
      RAISE EXCEPTION 'Fixed-day duration must be between 1 and 36500.';
    END IF;
    RETURN ((p_enrolled_at AT TIME ZONE 'Asia/Kolkata') + make_interval(days => p_fixed_days)) AT TIME ZONE 'Asia/Kolkata';
  END IF;
  IF p_policy_mode='CALENDAR_DURATION' THEN
    IF p_calendar_years IS NULL OR p_calendar_months IS NULL OR p_calendar_days IS NULL
      OR p_calendar_years < 0 OR p_calendar_months < 0 OR p_calendar_days < 0
      OR (p_calendar_years + p_calendar_months + p_calendar_days) < 1 THEN
      RAISE EXCEPTION 'Calendar duration must contain at least one year, month, or day.';
    END IF;
    RETURN ((p_enrolled_at AT TIME ZONE 'Asia/Kolkata')
      + make_interval(years => p_calendar_years, months => p_calendar_months, days => p_calendar_days))
      AT TIME ZONE 'Asia/Kolkata';
  END IF;
  RAISE EXCEPTION 'Unsupported course expiry policy mode: %',p_policy_mode;
END;
$$;

-- Every enrollment write path (student, parent, payment fulfilment, imports and reactivation)
-- passes through the same trigger, so the global policy cannot be skipped by a different UI/API.
CREATE OR REPLACE FUNCTION qe_snapshot_course_expiry_policy()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_activating boolean := false;
  v_has_policy boolean := false;
  v_policy course_expiry_policy%ROWTYPE;
BEGIN
  SELECT p.course_identity_id INTO NEW.course_identity_id
  FROM curriculum_program p
  WHERE p.id=NEW.program_id;

  IF TG_OP='INSERT' THEN
    v_activating := NEW.status='ACTIVE';
  ELSE
    v_activating := OLD.status<>'ACTIVE' AND NEW.status='ACTIVE';
  END IF;

  IF v_activating THEN
    IF NEW.course_identity_id IS NOT NULL THEN
      -- Serialize first enrolment/reactivation against policy configuration for this identity.
      PERFORM 1 FROM institution_course_identity
        WHERE id=NEW.course_identity_id FOR SHARE;
      SELECT * INTO v_policy
      FROM course_expiry_policy
      WHERE course_identity_id=NEW.course_identity_id;
      v_has_policy := FOUND;
    END IF;

    IF v_has_policy THEN
      NEW.course_expiry_policy_version_snapshot := v_policy.policy_version;
      NEW.course_expiry_mode_snapshot := v_policy.policy_mode;
      NEW.course_expiry_years_snapshot := v_policy.calendar_years;
      NEW.course_expiry_months_snapshot := v_policy.calendar_months;
      NEW.course_expiry_days_snapshot := v_policy.calendar_days;
      NEW.course_expiry_fixed_days_snapshot := v_policy.fixed_days;
      NEW.course_expires_at := qe_calculate_course_expiry(
        NEW.enrolled_at,v_policy.policy_mode,v_policy.calendar_years,
        v_policy.calendar_months,v_policy.calendar_days,v_policy.fixed_days);
    ELSE
      NEW.course_expiry_policy_version_snapshot := NULL;
      NEW.course_expiry_mode_snapshot := NULL;
      NEW.course_expiry_years_snapshot := NULL;
      NEW.course_expiry_months_snapshot := NULL;
      NEW.course_expiry_days_snapshot := NULL;
      NEW.course_expiry_fixed_days_snapshot := NULL;
      -- Keep any explicit HRMS expiry already saved on a reactivated legacy enrollment.
      -- New rows have no expiry by default, so this preserves grandfathering without inventing one.
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_student_program_enrollment_expiry_snapshot
BEFORE INSERT OR UPDATE ON student_program_enrollment
FOR EACH ROW EXECUTE FUNCTION qe_snapshot_course_expiry_policy();

-- Shared predicate for learner-facing APIs that must check the actual enrollment before serving
-- protected content. It intentionally requires an ACTIVE row and checks both manual and timed
-- access restrictions; it does not alter purchase, payment, certificate, or learning-history data.
CREATE OR REPLACE FUNCTION qe_course_enrollment_access_allowed(
  p_student_id bigint,
  p_institution_id bigint,
  p_program_id bigint
) RETURNS boolean
LANGUAGE sql
STABLE
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM student_program_enrollment e
    JOIN curriculum_program enrolled_program ON enrolled_program.id=e.program_id
    JOIN curriculum_program requested_program ON requested_program.id=p_program_id
    WHERE e.student_id=p_student_id
      AND e.institution_id=p_institution_id
      AND e.status='ACTIVE'
      AND e.course_access_blocked=false
      AND (e.course_expires_at IS NULL OR e.course_expires_at>statement_timestamp())
      AND (
        e.program_id=p_program_id
        OR (enrolled_program.course_identity_id IS NOT NULL
            AND enrolled_program.course_identity_id=requested_program.course_identity_id)
        OR qe_same_logical_course(e.program_id,p_program_id)
      )
  );
$$;

