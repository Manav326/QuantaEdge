-- Employee-submitted attendance corrections are reviewable requests; they never mutate attendance directly.
create table hr_attendance_correction_request (
  id bigint generated by default as identity primary key,
  public_id uuid not null unique default gen_random_uuid(),
  attendance_record_id bigint not null references hr_attendance_record(id) on delete restrict,
  employee_id bigint not null references hr_employee(id) on delete restrict,
  work_date date not null,
  requested_status varchar(16) not null check (requested_status in ('PRESENT','ABSENT','HALF_DAY','REMOTE','ON_LEAVE','HOLIDAY')),
  requested_check_in_at timestamptz,
  requested_check_out_at timestamptz,
  requested_notes varchar(500),
  reason varchar(1000) not null check (length(trim(reason))>0),
  request_status varchar(16) not null default 'PENDING'
    check (request_status in ('PENDING','APPROVED','REJECTED','CANCELLED')),
  review_note varchar(1000),
  requested_by_staff_id bigint not null references staff_account(id) on delete restrict,
  reviewed_by_staff_id bigint references staff_account(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((requested_check_out_at is null or requested_check_in_at is not null)
    and (requested_check_in_at is null or requested_check_out_at is null or requested_check_out_at>requested_check_in_at)),
  check ((requested_status not in ('ABSENT','ON_LEAVE','HOLIDAY'))
    or (requested_check_in_at is null and requested_check_out_at is null)),
  check ((request_status in ('PENDING','CANCELLED') and reviewed_at is null)
    or (request_status in ('APPROVED','REJECTED') and reviewed_at is not null))
);
create unique index uq_hr_attendance_correction_pending_record
  on hr_attendance_correction_request(attendance_record_id) where request_status='PENDING';
create index idx_hr_attendance_correction_request_employee
  on hr_attendance_correction_request(employee_id,created_at desc,id desc);
create index idx_hr_attendance_correction_request_pending
  on hr_attendance_correction_request(request_status,created_at) where request_status='PENDING';
insert into staff_permission_catalog(permission_key,display_name,description) values
 ('HR_ATTENDANCE_CORRECTION_REVIEW','Review employee attendance corrections','Approve or reject employee attendance correction requests and apply approved changes with an audit history.')
on conflict(permission_key) do update set display_name=excluded.display_name,description=excluded.description;
