-- Candidate book associations are stored, but never marked MAPPED/COVERED by automation.
insert into chapter_source(
  chapter_id,source_id,source_chapter_no,source_chapter_title,source_locator,coverage_type,coverage_status,notes
)
select ch.id,src.id,null,null,null,'CURRICULUM_CANDIDATE','NEEDS_REVIEW',
  'Candidate book selected by class and subject only. Verify the actual downloaded edition, chapter title and page range before marking MAPPED.'
from curriculum_chapter ch
join curriculum_subject s on s.id=ch.subject_id
join curriculum_class c on c.id=s.class_id
join content_source src on src.source_kind='STATE_TEXTBOOK'
 and src.edition='UNVERIFIED'
 and (
   (c.code='6' and s.code='maths' and src.title like 'Bihar SCERT Class 6 Mathematics%') or
   (c.code='7' and s.code='maths' and src.title like 'Bihar SCERT Class 7 Mathematics%') or
   (c.code='8' and s.code='maths' and src.title like 'Bihar SCERT Class 8 Mathematics%') or
   (c.code='6' and s.code='science' and src.title like 'Bihar SCERT Class 6 Science%') or
   (c.code='7' and s.code='science' and src.title like 'Bihar SCERT Class 7 Science%') or
   (c.code='8' and s.code='science' and src.title like 'Bihar SCERT Class 8 Science%')
 )
where c.code in ('6','7','8') and s.code in ('maths','science')
  and ch.active=true and ch.content_status='PUBLISHED'
on conflict(chapter_id,source_id,coverage_type) do update set
  coverage_status='NEEDS_REVIEW',
  notes='Candidate book selected by class and subject only. Verify exact edition, chapter title and page range.';

-- Add a conservative question-type plan per active chapter. These are targets, not
-- question rows. The admin inventory reports actual created/reviewed questions separately.
insert into chapter_assessment_requirement(chapter_id,question_type,minimum_count,required,rationale)
select ch.id, r.question_type, r.minimum_count,
  case
    when r.question_type in ('MCQ','TRUE_FALSE','INPUT','MATCH','ORDER','CASE_BASED','SHORT_ANSWER','LONG_ANSWER') then true
    when r.question_type='ASSERTION_REASON' then s.code='science'
    when r.question_type='NUMERICAL' then s.code='maths'
    when r.question_type='DIAGRAM' then (
      s.code='science' or ch.code in (
        'geometry-basics','elementary-shapes','data-handling','symmetry','practical-geometry',
        'lines-angles','triangles','congruence','perimeter-area','solid-shapes','quadrilaterals',
        'squares-roots','cubes-roots','mensuration','algebraic-identities','graphs','factorisation'
      )
    )
    else false
  end,
  r.rationale
from curriculum_chapter ch
join curriculum_subject s on s.id=ch.subject_id
join curriculum_class c on c.id=s.class_id
cross join (values
  ('MCQ',1,'Core multiple-choice check using this chapter’s real concept.'),
  ('TRUE_FALSE',1,'Use only a statement that can be unambiguously justified.'),
  ('INPUT',1,'Short answer/input response; add a verified answer key or rubric.'),
  ('MATCH',1,'Use only when the chapter has meaningful pairs to match.'),
  ('ORDER',1,'Use only when the concept has a meaningful sequence or process.'),
  ('ASSERTION_REASON',1,'Causal-reasoning item; required for Science.'),
  ('CASE_BASED',1,'An original age-appropriate context tied to the actual chapter concept.'),
  ('SHORT_ANSWER',1,'Original short response assessed against a rubric.'),
  ('LONG_ANSWER',1,'Original structured response assessed against a rubric.'),
  ('NUMERICAL',1,'Numerical problem; required for Mathematics.'),
  ('DIAGRAM',1,'Diagram/label task only where the chapter benefits from a visual representation.'),
  ('MAP',1,'Optional; only create where spatial/map context genuinely fits.'),
  ('SOURCE_BASED',1,'Optional until the exact source/edition and rights are reviewed.')
) as r(question_type,minimum_count,rationale)
where c.code in ('6','7','8') and s.code in ('maths','science')
  and ch.active=true and ch.content_status='PUBLISHED'
on conflict(chapter_id,question_type) do update set
  minimum_count=excluded.minimum_count,required=excluded.required,rationale=excluded.rationale;

