-- V91: throttle repeated HRMS password guesses without storing submitted usernames or passwords.
create table if not exists hrms_login_failure (
  id bigint generated by default as identity primary key,
  identifier_hash varchar(64) not null,
  attempted_at timestamptz not null default now()
);

create index if not exists idx_hrms_login_failure_recent
  on hrms_login_failure(identifier_hash, attempted_at desc);
