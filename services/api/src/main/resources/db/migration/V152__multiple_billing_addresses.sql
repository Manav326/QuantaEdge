-- V152: account-owned billing address book. Order snapshots remain self-contained and immutable.
CREATE TABLE billing_customer_address (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_account_id bigint NOT NULL REFERENCES user_account(id) ON DELETE RESTRICT,
  label varchar(80) NOT NULL DEFAULT 'Billing address' CHECK (length(btrim(label)) > 0),
  billing_type varchar(16) NOT NULL DEFAULT 'INDIVIDUAL'
    CHECK (billing_type IN ('INDIVIDUAL','BUSINESS')),
  legal_name varchar(240) NOT NULL CHECK (length(btrim(legal_name)) > 0),
  gstin varchar(15) CHECK (gstin IS NULL OR gstin ~ '^[0-9A-Z]{15}$'),
  gst_state_code char(2) CHECK (gst_state_code IS NULL OR gst_state_code ~ '^[0-9]{2}$'),
  billing_address jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(billing_address) = 'object'),
  contact_email varchar(320),
  contact_phone varchar(40),
  is_default boolean NOT NULL DEFAULT false,
  active boolean NOT NULL DEFAULT true,
  version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz,
  CHECK (gstin IS NULL OR (gst_state_code IS NOT NULL AND left(gstin,2)=gst_state_code)),
  CHECK (active OR (NOT is_default AND deleted_at IS NOT NULL))
);

CREATE UNIQUE INDEX uq_billing_customer_address_default
  ON billing_customer_address(user_account_id) WHERE active=true AND is_default=true;
CREATE INDEX idx_billing_customer_address_owner
  ON billing_customer_address(user_account_id,active,is_default DESC,lower(label),id);

-- Preserve current customer data when upgrading from the single-profile model.
INSERT INTO billing_customer_address(
  user_account_id,label,billing_type,legal_name,gstin,gst_state_code,billing_address,
  contact_email,contact_phone,is_default,active,version,created_at,updated_at
)
SELECT p.user_account_id,'Billing address',p.billing_type,p.legal_name,p.gstin,p.gst_state_code,
  p.billing_address,p.contact_email,p.contact_phone,true,true,p.version,p.created_at,p.updated_at
FROM billing_customer_profile p
WHERE NOT EXISTS (
  SELECT 1 FROM billing_customer_address a WHERE a.user_account_id=p.user_account_id AND a.active=true
);

CREATE TABLE billing_customer_address_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  address_id bigint NOT NULL REFERENCES billing_customer_address(id) ON DELETE RESTRICT,
  user_account_id bigint NOT NULL REFERENCES user_account(id) ON DELETE RESTRICT,
  event_type varchar(24) NOT NULL CHECK (event_type IN ('CREATED','UPDATED','DEFAULT_CHANGED','DEACTIVATED')),
  address_version bigint NOT NULL CHECK (address_version > 0),
  actor_user_account_id bigint NOT NULL REFERENCES user_account(id) ON DELETE RESTRICT,
  changed_fields jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(changed_fields)='array'),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_billing_customer_address_event_history
  ON billing_customer_address_event(user_account_id,created_at DESC,id DESC);

CREATE OR REPLACE FUNCTION reject_billing_customer_address_event_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'Billing address history is append-only'
    USING ERRCODE='23514';
END;
$$;
CREATE TRIGGER trg_billing_customer_address_event_immutable
BEFORE UPDATE OR DELETE ON billing_customer_address_event
FOR EACH ROW EXECUTE FUNCTION reject_billing_customer_address_event_mutation();

