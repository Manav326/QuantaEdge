-- V95: durable extracted textbook pages and resumable extraction state.
-- Extraction is separate from publication: page text remains private until a reviewer approves its source.
create table textbook_extraction_job (
  id bigint generated by default as identity primary key,
  pdf_asset_id bigint not null unique references learning_pdf_asset(id) on delete cascade,
  source_sha256 varchar(64) not null,
  status varchar(20) not null default 'PENDING'
    check (status in ('PENDING','RUNNING','COMPLETE','PARTIAL','FAILED')),
  total_pages integer not null default 0 check (total_pages between 0 and 2000),
  processed_pages integer not null default 0 check (processed_pages >= 0),
  extracted_pages integer not null default 0 check (extracted_pages >= 0),
  ocr_pages integer not null default 0 check (ocr_pages >= 0),
  failed_pages integer not null default 0 check (failed_pages >= 0),
  last_error varchar(1200),
  requested_by_staff_id bigint references staff_account(id) on delete set null,
  requested_at timestamptz not null default now(),
  started_at timestamptz,
  finished_at timestamptz,
  updated_at timestamptz not null default now()
);

create index idx_textbook_extraction_job_status
  on textbook_extraction_job(status, updated_at desc);

create table textbook_extracted_page (
  id bigint generated by default as identity primary key,
  pdf_asset_id bigint not null references learning_pdf_asset(id) on delete cascade,
  learning_document_id bigint references learning_document(id) on delete set null,
  source_ingestion_job_id bigint references source_ingestion_job(id) on delete set null,
  class_id bigint references curriculum_class(id) on delete set null,
  subject_id bigint not null references curriculum_subject(id) on delete restrict,
  chapter_id bigint references curriculum_chapter(id) on delete set null,
  language varchar(2) not null check (language in ('hi','en')),
  page_no integer not null check (page_no between 1 and 2000),
  source_sha256 varchar(64) not null,
  extracted_text text not null default '',
  extraction_method varchar(16) not null
    check (extraction_method in ('PDF_TEXT','OCR','EMPTY','FAILED')),
  quality_status varchar(20) not null default 'OCR_REQUIRED'
    check (quality_status in ('READY','LOW_TEXT','OCR_REQUIRED','FAILED')),
  extraction_error varchar(1200),
  extracted_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(pdf_asset_id, page_no)
);

create index idx_textbook_extracted_page_scope
  on textbook_extracted_page(class_id, subject_id, language, chapter_id, page_no);

-- Simple dictionary preserves Unicode tokenization without requiring a separate search service.
create index idx_textbook_extracted_page_search
  on textbook_extracted_page using gin (to_tsvector('simple', coalesce(extracted_text,'')));

create index idx_textbook_extracted_page_asset_hash
  on textbook_extracted_page(pdf_asset_id, source_sha256, page_no);

insert into app_metadata(key,value)
values ('schema','textbook-extracted-page-index-v95')
on conflict(key) do update set value=excluded.value;
