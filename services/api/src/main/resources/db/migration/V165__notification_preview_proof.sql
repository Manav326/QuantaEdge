-- V165: short-lived, single-use server-issued proofs for reviewed notification campaigns.
-- The plaintext preview token is returned once to the sender; only its SHA-256 hash is stored.
CREATE TABLE notification_preview_token (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token_hash char(64) NOT NULL UNIQUE CHECK (token_hash ~ '^[0-9a-f]{64}$'),
  sender_workspace varchar(32) NOT NULL,
  sender_staff_id bigint REFERENCES staff_account(id) ON DELETE CASCADE,
  sender_institution_admin_id bigint REFERENCES institution_admin_account(id) ON DELETE CASCADE,
  sender_institution_id bigint REFERENCES institution_tenant(id) ON DELETE CASCADE,
  request_fingerprint char(64) NOT NULL CHECK (request_fingerprint ~ '^[0-9a-f]{64}$'),
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  consumed_at timestamptz,
  CHECK (expires_at > created_at)
);

CREATE INDEX idx_notification_preview_token_expiry
  ON notification_preview_token(expires_at);
CREATE INDEX idx_notification_preview_token_consumed
  ON notification_preview_token(consumed_at,created_at)
  WHERE consumed_at IS NOT NULL;

INSERT INTO app_metadata(key,value)
VALUES ('schema','notification-preview-proof-v165')
ON CONFLICT(key) DO UPDATE SET value=excluded.value;
