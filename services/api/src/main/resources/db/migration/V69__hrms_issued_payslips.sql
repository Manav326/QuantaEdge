-- Immutable payslip snapshots are issued only when a payroll run is approved.
create table hr_payslip (
  id bigint generated by default as identity primary key,
  public_id uuid not null unique default gen_random_uuid(),
  run_id bigint not null references hr_payroll_run(id) on delete restrict,
  employee_id bigint not null references hr_employee(id) on delete restrict,
  version_no integer not null default 1 check (version_no > 0),
  snapshot jsonb not null,
  checksum char(64) not null check (checksum ~ '^[0-9a-f]{64}$'),
  issued_by_staff_id bigint references staff_account(id) on delete set null,
  issued_at timestamptz not null default now(),
  unique(run_id,employee_id,version_no)
);
create index idx_hr_payslip_employee_issued on hr_payslip(employee_id,issued_at desc,id desc);
create index idx_hr_payslip_run on hr_payslip(run_id,employee_id);
