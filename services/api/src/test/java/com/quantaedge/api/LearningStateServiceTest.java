package com.quantaedge.api;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.atLeastOnce;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.ArgumentCaptor;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.jdbc.core.JdbcTemplate;

@ExtendWith(MockitoExtension.class)
class LearningStateServiceTest {
  @Mock private JdbcTemplate jdbc;

  private LearningStateService service;

  @BeforeEach
  void setUp() {
    service = new LearningStateService(jdbc);
    when(jdbc.queryForObject(anyString(), eq(Long.class), any(Object[].class))).thenReturn(1L);
    when(jdbc.queryForList(anyString(), any(Object[].class))).thenAnswer(invocation -> {
      String sql = invocation.getArgument(0);
      if (sql.contains("jsonb_array_elements(ps.topic_selections)")) {
        return List.of(Map.of("lesson_id", 9L));
      }
      return List.of(Map.of("question_id", 42L));
    });
  }

  @Test
  void practiceAnswerProgressSyncAvoidsJsonbOperatorBeingParsedAsBindParameter() {
    // Every question type uses this same persistence path. Keep this answer ungraded so
    // the test exercises the shared session/progress writes without requiring mastery data.
    service.recordAttempt(7L, 42L, 9L, "written response", false, null, 5L);

    ArgumentCaptor<String> sql = ArgumentCaptor.forClass(String.class);
    verify(jdbc, atLeastOnce()).queryForList(sql.capture(), any(Object[].class));

    String sourceLessonQuery = sql.getAllValues().stream()
        .filter(statement -> statement.contains("jsonb_array_elements(ps.topic_selections)"))
        .findFirst()
        .orElseThrow(() -> new AssertionError("Expected the practice session source-lesson query."));

    assertTrue(sourceLessonQuery.contains("jsonb_exists(item, 'sourceLessonId')"));
    assertFalse(sourceLessonQuery.contains("item ? 'sourceLessonId'"));

    // Course-scoped lessons must save progress through the active course enrolment,
    // even when the source curriculum class differs from the learner's school class.
    assertTrue(sql.getAllValues().stream().anyMatch(statement ->
        statement.contains("student_program_enrollment")
            && statement.contains("s.program_id is null and c.code=st.class_code")
            && statement.contains("s.program_id is not null")));

    verify(jdbc).update(
        org.mockito.ArgumentMatchers.contains("insert into student_question_attempt"),
        any(), any(), any(), any(), any(), any(), any());
  }

  @Test
  void courseScopedAnswerInsertBindsTenantAndCourseWithMatchingPlaceholderCount() {
    // This code path deliberately enforces tenant/course entitlement before the insert.
    when(jdbc.queryForObject(anyString(), eq(Boolean.class), any(Object[].class))).thenReturn(true);
    service.recordAttempt(7L, 42L, 9L, "A", false, null, null,
        "LESSON_INLINE", 17L, 88L);

    ArgumentCaptor<String> sql = ArgumentCaptor.forClass(String.class);
    ArgumentCaptor<Object[]> args = ArgumentCaptor.forClass(Object[].class);
    verify(jdbc, atLeastOnce()).update(sql.capture(), (Object[]) args.capture());

    int insertIndex = -1;
    for (int index = 0; index < sql.getAllValues().size(); index++) {
      if (sql.getAllValues().get(index).contains("insert into student_question_attempt")) {
        insertIndex = index;
        break;
      }
    }
    assertTrue(insertIndex >= 0, "Expected a course-scoped student answer insert.");
    String insertSql = sql.getAllValues().get(insertIndex);
    Object[] bound = args.getAllValues().get(insertIndex);
    assertTrue(insertSql.contains("student_id,institution_id,course_id,question_id,selected_option,answer_text,correct,answered_at,practice_session_id,activity_kind"));
    assertTrue(insertSql.contains("values(?,?,?,?,?,?,?,now(),?,?)"));
    assertEquals(9, bound.length, "answered_at is generated by the database; all other columns are bound.");
    assertEquals(7L, bound[0]);
    assertEquals(17L, bound[1]);
    assertEquals(88L, bound[2]);
    assertEquals(42L, bound[3]);
    assertEquals("A", bound[4]);
    assertEquals("A", bound[5]);
    assertTrue(bound[6] == null, "Unknown grading stays null rather than false.");
    assertTrue(bound[7] == null, "Inline lesson answers have no practice session ID.");
    assertEquals("LESSON_INLINE", bound[8]);
  }
}
