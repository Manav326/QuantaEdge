-- V158: provider-confirmed refunds, immutable credit-note links, and append-only adjustment events.
-- A refund that has an uncertain provider outcome continues to reserve refundable balance.
CREATE TABLE course_payment_refund (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  course_payment_order_id bigint NOT NULL REFERENCES course_payment_order(id) ON DELETE RESTRICT,
  request_idempotency_key varchar(180) NOT NULL UNIQUE,
  provider_idempotency_key varchar(80) NOT NULL UNIQUE,
  provider_payment_id varchar(80) NOT NULL,
  provider_refund_id varchar(80),
  requested_amount_paise bigint NOT NULL CHECK (requested_amount_paise >= 100),
  currency char(3) NOT NULL CHECK (currency='INR'),
  reason varchar(500) NOT NULL CHECK (length(btrim(reason)) BETWEEN 10 AND 500),
  status varchar(32) NOT NULL DEFAULT 'PROCESSING'
    CHECK (status IN ('PROCESSING','PENDING','PROCESSED','FAILED','RECONCILIATION_REQUIRED')),
  provider_status varchar(24),
  provider_response_snapshot jsonb NOT NULL DEFAULT '{}'::jsonb
    CHECK (jsonb_typeof(provider_response_snapshot)='object'),
  credit_note_document_id bigint UNIQUE REFERENCES fiscal_document(id) ON DELETE RESTRICT,
  requested_by_staff_id bigint NOT NULL REFERENCES staff_account(id) ON DELETE RESTRICT,
  requested_at timestamptz NOT NULL DEFAULT now(),
  settled_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (status NOT IN ('PENDING','PROCESSED') OR provider_refund_id IS NOT NULL),
  CHECK (status<>'PROCESSED' OR (credit_note_document_id IS NOT NULL AND settled_at IS NOT NULL
    AND provider_status='processed')),
  CHECK (status<>'FAILED' OR provider_status IS NOT NULL)
);
CREATE UNIQUE INDEX uq_course_payment_refund_provider_id
  ON course_payment_refund(provider_refund_id) WHERE provider_refund_id IS NOT NULL;
CREATE INDEX idx_course_payment_refund_order_status
  ON course_payment_refund(course_payment_order_id,status,requested_at,id);

-- Monetary inputs are immutable after the provider request is prepared.
CREATE OR REPLACE FUNCTION protect_course_payment_refund_facts()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF ROW(NEW.course_payment_order_id,NEW.request_idempotency_key,NEW.provider_idempotency_key,
      NEW.provider_payment_id,NEW.requested_amount_paise,NEW.currency,NEW.reason,
      NEW.requested_by_staff_id,NEW.requested_at)
    IS DISTINCT FROM
    ROW(OLD.course_payment_order_id,OLD.request_idempotency_key,OLD.provider_idempotency_key,
      OLD.provider_payment_id,OLD.requested_amount_paise,OLD.currency,OLD.reason,
      OLD.requested_by_staff_id,OLD.requested_at) THEN
    RAISE EXCEPTION 'Refund request facts are immutable after submission'
      USING ERRCODE='23514';
  END IF;
  IF OLD.status='PROCESSED' AND NEW.status<>'PROCESSED' THEN
    RAISE EXCEPTION 'A processed refund cannot be reverted'
      USING ERRCODE='23514';
  END IF;
  IF OLD.status='FAILED' AND NEW.status<>'FAILED' THEN
    RAISE EXCEPTION 'A failed refund request cannot be reactivated; submit a new request'
      USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER trg_course_payment_refund_protect_facts
BEFORE UPDATE ON course_payment_refund
FOR EACH ROW EXECUTE FUNCTION protect_course_payment_refund_facts();

CREATE TABLE course_payment_refund_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  refund_id bigint NOT NULL REFERENCES course_payment_refund(id) ON DELETE RESTRICT,
  event_type varchar(32) NOT NULL CHECK (event_type IN (
    'REQUESTED','PROVIDER_PENDING','PROVIDER_PROCESSED','PROVIDER_FAILED',
    'RECONCILIATION_REQUIRED','CREDIT_NOTE_ISSUED','ALLOCATIONS_REVERSED')),
  idempotency_key varchar(180) NOT NULL UNIQUE,
  actor_staff_id bigint REFERENCES staff_account(id) ON DELETE RESTRICT,
  details jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(details)='object'),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_course_payment_refund_event_history
  ON course_payment_refund_event(refund_id,created_at,id);
CREATE TRIGGER trg_course_payment_refund_event_immutable
BEFORE UPDATE OR DELETE ON course_payment_refund_event
FOR EACH ROW EXECUTE FUNCTION reject_billing_financial_mutation();

