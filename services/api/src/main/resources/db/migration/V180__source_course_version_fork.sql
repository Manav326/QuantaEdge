-- V180: safely fork released course graphs so source edits never mutate a live release.
-- A fork receives new program/subject/chapter/lesson/question/assessment identities. Learner attempts,
-- purchases, invoices, entitlements and certificates remain attached to the original program/version.
-- Generic resources/documents/assets are immutable reusable resources; the fork copies assignments
-- and version-specific assessment/test-pack relationships rather than mutating shared media rows.

CREATE TABLE institution_course_version_artifact_map (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_identity_id bigint NOT NULL REFERENCES institution_course_identity(id) ON DELETE RESTRICT,
  source_program_id bigint NOT NULL REFERENCES curriculum_program(id) ON DELETE RESTRICT,
  version_program_id bigint NOT NULL REFERENCES curriculum_program(id) ON DELETE RESTRICT,
  source_artifact_id varchar(120) NOT NULL,
  version_artifact_id varchar(120) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(version_program_id,source_artifact_id),
  UNIQUE(version_program_id,version_artifact_id)
);
CREATE INDEX idx_course_version_artifact_lookup
  ON institution_course_version_artifact_map(version_program_id,source_artifact_id);

CREATE OR REPLACE FUNCTION qe_course_version_entity_id(
  p_version_program_id bigint,p_entity_type text,p_source_entity_id bigint
) RETURNS bigint
LANGUAGE sql STABLE AS $$
  SELECT m.version_entity_id
  FROM institution_course_version_entity_map m
  WHERE m.version_program_id=p_version_program_id
    AND m.entity_type=p_entity_type
    AND m.source_entity_id=p_source_entity_id
  LIMIT 1
$$;

CREATE OR REPLACE FUNCTION qe_remap_course_artifact_json(
  p_json jsonb,p_version_program_id bigint
) RETURNS jsonb
LANGUAGE plpgsql STABLE AS $$
DECLARE
  v_result jsonb;
  v_item jsonb;
  v_key text;
  v_value jsonb;
  v_old_id text;
  v_new_id text;
BEGIN
  IF p_json IS NULL THEN RETURN NULL; END IF;
  IF jsonb_typeof(p_json)='object' THEN
    v_result := '{}'::jsonb;
    FOR v_key,v_value IN SELECT key,value FROM jsonb_each(p_json)
    LOOP
      IF jsonb_typeof(v_value)='string' THEN
        v_old_id := v_value #>> '{}';
        SELECT m.version_artifact_id INTO v_new_id
        FROM institution_course_version_artifact_map m
        WHERE m.version_program_id=p_version_program_id
          AND m.source_artifact_id=v_old_id;
        IF v_new_id IS NOT NULL THEN
          v_result := v_result || jsonb_build_object(v_key,v_new_id);
        ELSE
          v_result := v_result || jsonb_build_object(v_key,v_value);
        END IF;
      ELSE
        v_result := v_result || jsonb_build_object(
          v_key,qe_remap_course_artifact_json(v_value,p_version_program_id));
      END IF;
    END LOOP;
    RETURN v_result;
  ELSIF jsonb_typeof(p_json)='array' THEN
    v_result := '[]'::jsonb;
    FOR v_item IN SELECT value FROM jsonb_array_elements(p_json)
    LOOP
      v_result := v_result || jsonb_build_array(
        qe_remap_course_artifact_json(v_item,p_version_program_id));
    END LOOP;
    RETURN v_result;
  END IF;
  RETURN p_json;
END
$$;

CREATE OR REPLACE FUNCTION qe_clone_course_version_row(
  p_table_name text,
  p_source_row jsonb,
  p_source_program_id bigint,
  p_version_program_id bigint,
  p_course_identity_id bigint,
  p_content_version_no integer,
  p_entity_type text,
  p_actor_staff_id bigint,
  p_actor_institution_admin_id bigint
) RETURNS bigint
LANGUAGE plpgsql
AS $$
DECLARE
  v_row jsonb := p_source_row - 'id';
  v_columns text;
  v_select_columns text;
  v_has_id boolean;
  v_source_id bigint;
  v_new_id bigint;
  v_key text;
  v_value jsonb;
  v_entity_type text;
  v_old_id bigint;
  v_mapped_id bigint;
  v_artifact_id text;
  v_mapped_artifact_id text;
BEGIN
  IF p_source_row ? 'id' AND jsonb_typeof(p_source_row->'id')='number' THEN
    v_source_id := (p_source_row->>'id')::bigint;
  END IF;

  -- Course references are always rebound to the new graph. Curriculum subjects that were
  -- previously class-shared become course-owned in the new version.
  IF p_table_name='curriculum_subject' THEN
    v_row := v_row || jsonb_build_object('program_id',p_version_program_id);
  ELSE
    IF v_row ? 'program_id' AND v_row->>'program_id'=p_source_program_id::text THEN
      v_row := v_row || jsonb_build_object('program_id',p_version_program_id);
    END IF;
  END IF;
  IF v_row ? 'course_id' AND v_row->>'course_id'=p_source_program_id::text THEN
    v_row := v_row || jsonb_build_object('course_id',p_version_program_id);
  END IF;

  FOR v_key,v_value IN SELECT key,value FROM jsonb_each(v_row)
  LOOP
    v_entity_type := CASE v_key
      WHEN 'subject_id' THEN 'SUBJECT'
      WHEN 'chapter_id' THEN 'CHAPTER'
      WHEN 'objective_id' THEN 'OBJECTIVE'
      WHEN 'concept_id' THEN 'CONCEPT'
      WHEN 'lesson_id' THEN 'LESSON'
      WHEN 'block_id' THEN 'LESSON_BLOCK'
      WHEN 'question_id' THEN 'QUESTION'
      WHEN 'source_question_id' THEN 'QUESTION'
      WHEN 'assessment_id' THEN 'ASSESSMENT'
      WHEN 'assessment_question_id' THEN 'ASSESSMENT_QUESTION'
      WHEN 'pack_id' THEN 'ASSESSMENT_PACK'
      WHEN 'resource_id' THEN 'LEARNING_RESOURCE'
      WHEN 'learning_document_id' THEN 'LEARNING_DOCUMENT'
      WHEN 'source_book_id' THEN 'SOURCE_BOOK'
      ELSE NULL END;

    IF v_entity_type IS NOT NULL AND v_value IS NOT NULL AND v_value<>'null'::jsonb THEN
      IF jsonb_typeof(v_value)<>'number' THEN
        RAISE EXCEPTION 'COURSE_VERSION_FORK_INVALID_REFERENCE: %.% is not numeric',p_table_name,v_key
          USING ERRCODE='23514';
      END IF;
      v_old_id := (v_value #>> '{}')::bigint;
      v_mapped_id := qe_course_version_entity_id(p_version_program_id,v_entity_type,v_old_id);
      IF v_mapped_id IS NULL THEN
        IF v_key='source_question_id' THEN
          -- A snapshot may have originated from an external bank. The immutable question snapshot
          -- remains authoritative, so do not make the new version depend on another course graph.
          v_row := v_row || jsonb_build_object(v_key,NULL);
        ELSIF v_key IN ('resource_id','learning_document_id') THEN
          RAISE EXCEPTION 'COURSE_VERSION_FORK_RESOURCE_MAP_MISSING: %.% references unmapped entity %',
            p_table_name,v_key,v_old_id USING ERRCODE='23514';
        ELSE
          RAISE EXCEPTION 'COURSE_VERSION_FORK_PARENT_MAP_MISSING: %.% references unmapped entity %',
            p_table_name,v_key,v_old_id USING ERRCODE='23514';
        END IF;
      ELSE
        v_row := v_row || jsonb_build_object(v_key,v_mapped_id);
      END IF;
    ELSIF v_key='artifact_id' AND v_value IS NOT NULL AND v_value<>'null'::jsonb THEN
      v_artifact_id := v_value #>> '{}';
      SELECT m.version_artifact_id INTO v_mapped_artifact_id
      FROM institution_course_version_artifact_map m
      WHERE m.version_program_id=p_version_program_id
        AND m.source_artifact_id=v_artifact_id;
      IF v_mapped_artifact_id IS NOT NULL THEN
        v_row := v_row || jsonb_build_object(v_key,v_mapped_artifact_id);
      END IF;
    END IF;
  END LOOP;

  -- Shared file/document rows are deliberately referenced rather than overwritten. Their new
  -- chapter/lesson/resource associations are separate rows; any new file upload creates a new
  -- resource row/storage key through the normal resource upload path.
  IF v_row ? 'public_id' THEN v_row := v_row || jsonb_build_object('public_id',gen_random_uuid()); END IF;
  IF v_row ? 'created_at' THEN v_row := v_row || jsonb_build_object('created_at',now()); END IF;
  IF v_row ? 'updated_at' THEN v_row := v_row || jsonb_build_object('updated_at',now()); END IF;
  IF v_row ? 'created_by_staff_id' THEN
    v_row := v_row || jsonb_build_object('created_by_staff_id',p_actor_staff_id);
  END IF;
  IF v_row ? 'updated_by_staff_id' THEN
    v_row := v_row || jsonb_build_object('updated_by_staff_id',p_actor_staff_id);
  END IF;
  IF v_row ? 'created_by_institution_admin_id' THEN
    v_row := v_row || jsonb_build_object('created_by_institution_admin_id',p_actor_institution_admin_id);
  END IF;
  IF v_row ? 'status' AND p_table_name IN ('assessment','course_assessment_pack') THEN
    v_row := v_row || jsonb_build_object('status','DRAFT');
  END IF;
  IF v_row ? 'published_by_staff_id' AND p_table_name IN ('assessment','course_assessment_pack') THEN
    v_row := v_row || jsonb_build_object('published_by_staff_id',NULL);
  END IF;
  IF v_row ? 'published_at' AND p_table_name IN ('assessment','course_assessment_pack') THEN
    v_row := v_row || jsonb_build_object('published_at',NULL);
  END IF;
  IF v_row ? 'is_current' AND p_table_name='assessment' THEN
    v_row := v_row || jsonb_build_object('is_current',true);
  END IF;
  IF v_row ? 'generation_version' AND p_table_name='assessment' THEN
    v_row := v_row || jsonb_build_object('generation_version',1);
  END IF;
  IF p_table_name='lesson_block' AND v_row ? 'content' THEN
    v_row := v_row || jsonb_build_object(
      'content',qe_remap_course_artifact_json(v_row->'content',p_version_program_id));
  END IF;

  SELECT string_agg(format('%I',column_name),', ' ORDER BY ordinal_position),
         string_agg(format('r.%I',column_name),', ' ORDER BY ordinal_position),
         (SELECT EXISTS(SELECT 1 FROM information_schema.columns c2
           WHERE c2.table_schema='public' AND c2.table_name=p_table_name AND c2.column_name='id'))
  INTO v_columns,v_select_columns,v_has_id
  FROM information_schema.columns
  WHERE table_schema='public' AND table_name=p_table_name
    AND column_name<>'id' AND is_generated='NEVER';

  IF v_columns IS NULL THEN
    RAISE EXCEPTION 'COURSE_VERSION_FORK_UNKNOWN_TABLE: %',p_table_name USING ERRCODE='23514';
  END IF;

  IF coalesce(v_has_id,false) THEN
    EXECUTE format(
      'INSERT INTO public.%I (%s) SELECT %s FROM jsonb_populate_record(NULL::public.%I,$1) AS r RETURNING id',
      p_table_name,v_columns,v_select_columns,p_table_name)
      USING v_row INTO v_new_id;
  ELSE
    EXECUTE format(
      'INSERT INTO public.%I (%s) SELECT %s FROM jsonb_populate_record(NULL::public.%I,$1) AS r',
      p_table_name,v_columns,v_select_columns,p_table_name)
      USING v_row;
    v_new_id := NULL;
  END IF;

  IF p_entity_type IS NOT NULL AND v_source_id IS NOT NULL AND v_new_id IS NOT NULL THEN
    INSERT INTO institution_course_version_entity_map(
      course_identity_id,source_program_id,version_program_id,entity_type,source_entity_id,version_entity_id
    ) VALUES (
      p_course_identity_id,p_source_program_id,p_version_program_id,p_entity_type,v_source_id,v_new_id
    );
  END IF;
  RETURN v_new_id;
END
$$;

CREATE OR REPLACE FUNCTION qe_clone_course_table_rows(
  p_scope text,
  p_source_program_id bigint,
  p_version_program_id bigint,
  p_course_identity_id bigint,
  p_content_version_no integer,
  p_actor_staff_id bigint,
  p_actor_institution_admin_id bigint
) RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
  v_table_name text;
  v_entity_type text;
  v_query text;
  v_row jsonb;
BEGIN
  CASE p_scope
    WHEN 'SUBJECTS' THEN
      v_table_name:='curriculum_subject'; v_entity_type:='SUBJECT';
      v_query := 'SELECT to_jsonb(t) FROM public.curriculum_subject t
        WHERE t.program_id=$1 OR EXISTS(
          SELECT 1 FROM curriculum_program_subject ps WHERE ps.program_id=$1 AND ps.subject_id=t.id)
        ORDER BY t.id';
    WHEN 'PROGRAM_SUBJECTS' THEN
      v_table_name:='curriculum_program_subject'; v_entity_type:=NULL;
      v_query := 'SELECT to_jsonb(t) FROM public.curriculum_program_subject t
        WHERE t.program_id=$1 ORDER BY t.subject_id';
    WHEN 'CHAPTERS' THEN
      v_table_name:='curriculum_chapter'; v_entity_type:='CHAPTER';
      v_query := 'SELECT to_jsonb(t) FROM public.curriculum_chapter t
        WHERE t.subject_id IN (SELECT source_entity_id FROM institution_course_version_entity_map
          WHERE version_program_id=$2 AND entity_type=''SUBJECT'') ORDER BY t.id';
    WHEN 'OBJECTIVES' THEN
      v_table_name:='learning_objective'; v_entity_type:='OBJECTIVE';
      v_query := 'SELECT to_jsonb(t) FROM public.learning_objective t
        WHERE t.chapter_id IN (SELECT source_entity_id FROM institution_course_version_entity_map
          WHERE version_program_id=$2 AND entity_type=''CHAPTER'') ORDER BY t.id';
    WHEN 'CONCEPTS' THEN
      v_table_name:='chapter_concept'; v_entity_type:='CONCEPT';
      v_query := 'SELECT to_jsonb(t) FROM public.chapter_concept t
        WHERE t.chapter_id IN (SELECT source_entity_id FROM institution_course_version_entity_map
          WHERE version_program_id=$2 AND entity_type=''CHAPTER'') ORDER BY t.id';
    WHEN 'BOOKS' THEN
      v_table_name:='textbook_source_book'; v_entity_type:='SOURCE_BOOK';
      v_query := 'SELECT to_jsonb(t) FROM public.textbook_source_book t
        WHERE t.program_id=$1 OR t.subject_id IN (SELECT source_entity_id FROM institution_course_version_entity_map
          WHERE version_program_id=$2 AND entity_type=''SUBJECT'') ORDER BY t.id';
    WHEN 'PAGES' THEN
      v_table_name:='textbook_extracted_page'; v_entity_type:='SOURCE_PAGE';
      v_query := 'SELECT to_jsonb(t) FROM public.textbook_extracted_page t
        WHERE t.source_book_id IN (SELECT source_entity_id FROM institution_course_version_entity_map
          WHERE version_program_id=$2 AND entity_type=''SOURCE_BOOK'') ORDER BY t.id';
    WHEN 'CHAPTER_SOURCES' THEN
      v_table_name:='chapter_source'; v_entity_type:=NULL;
      v_query := 'SELECT to_jsonb(t) FROM public.chapter_source t
        WHERE t.chapter_id IN (SELECT source_entity_id FROM institution_course_version_entity_map
          WHERE version_program_id=$2 AND entity_type=''CHAPTER'') ORDER BY t.id';
    WHEN 'REQUIREMENTS' THEN
      v_table_name:='lesson_requirement'; v_entity_type:=NULL;
      v_query := 'SELECT to_jsonb(t) FROM public.lesson_requirement t
        WHERE t.chapter_id IN (SELECT source_entity_id FROM institution_course_version_entity_map
          WHERE version_program_id=$2 AND entity_type=''CHAPTER'') ORDER BY t.id';
    WHEN 'ARTIFACT_SCOPES' THEN
      v_table_name:='learning_resource_artifact_scope'; v_entity_type:=NULL;
      v_query := 'SELECT to_jsonb(t) FROM public.learning_resource_artifact_scope t
        WHERE t.chapter_id IN (SELECT source_entity_id FROM institution_course_version_entity_map
          WHERE version_program_id=$2 AND entity_type=''CHAPTER'') ORDER BY t.artifact_id';
    WHEN 'LESSONS' THEN
      v_table_name:='lesson'; v_entity_type:='LESSON';
      v_query := 'SELECT to_jsonb(t) FROM public.lesson t
        WHERE t.chapter_id IN (SELECT source_entity_id FROM institution_course_version_entity_map
          WHERE version_program_id=$2 AND entity_type=''CHAPTER'')
          OR t.objective_id IN (SELECT source_entity_id FROM institution_course_version_entity_map
            WHERE version_program_id=$2 AND entity_type=''OBJECTIVE'')
        ORDER BY t.id';
    WHEN 'LESSON_BLOCKS' THEN
      v_table_name:='lesson_block'; v_entity_type:='LESSON_BLOCK';
      v_query := 'SELECT to_jsonb(t) FROM public.lesson_block t
        WHERE t.lesson_id IN (SELECT source_entity_id FROM institution_course_version_entity_map
          WHERE version_program_id=$2 AND entity_type=''LESSON'') ORDER BY t.id';
    WHEN 'QUESTIONS' THEN
      v_table_name:='question'; v_entity_type:='QUESTION';
      v_query := 'SELECT to_jsonb(t) FROM public.question t
        WHERE t.lesson_id IN (SELECT source_entity_id FROM institution_course_version_entity_map
          WHERE version_program_id=$2 AND entity_type=''LESSON'')
          OR t.objective_id IN (SELECT source_entity_id FROM institution_course_version_entity_map
            WHERE version_program_id=$2 AND entity_type=''OBJECTIVE'')
          OR t.concept_id IN (SELECT source_entity_id FROM institution_course_version_entity_map
            WHERE version_program_id=$2 AND entity_type=''CONCEPT'')
        ORDER BY t.id';
    WHEN 'QUESTION_OPTIONS' THEN
      v_table_name:='question_option'; v_entity_type:='QUESTION_OPTION';
      v_query := 'SELECT to_jsonb(t) FROM public.question_option t
        WHERE t.question_id IN (SELECT source_entity_id FROM institution_course_version_entity_map
          WHERE version_program_id=$2 AND entity_type=''QUESTION'') ORDER BY t.id';
    WHEN 'PROGRAM_TRANSLATIONS' THEN
      v_table_name:='curriculum_program_translation'; v_entity_type:=NULL;
      v_query := 'SELECT to_jsonb(t) FROM public.curriculum_program_translation t WHERE t.program_id=$1 ORDER BY t.id';
    WHEN 'SUBJECT_TRANSLATIONS' THEN
      v_table_name:='curriculum_subject_translation'; v_entity_type:=NULL;
      v_query := 'SELECT to_jsonb(t) FROM public.curriculum_subject_translation t
        WHERE t.subject_id IN (SELECT source_entity_id FROM institution_course_version_entity_map
          WHERE version_program_id=$2 AND entity_type=''SUBJECT'') ORDER BY t.id';
    WHEN 'CHAPTER_TRANSLATIONS' THEN
      v_table_name:='curriculum_chapter_translation'; v_entity_type:=NULL;
      v_query := 'SELECT to_jsonb(t) FROM public.curriculum_chapter_translation t
        WHERE t.chapter_id IN (SELECT source_entity_id FROM institution_course_version_entity_map
          WHERE version_program_id=$2 AND entity_type=''CHAPTER'') ORDER BY t.id';
    WHEN 'OBJECTIVE_TRANSLATIONS' THEN
      v_table_name:='learning_objective_translation'; v_entity_type:=NULL;
      v_query := 'SELECT to_jsonb(t) FROM public.learning_objective_translation t
        WHERE t.objective_id IN (SELECT source_entity_id FROM institution_course_version_entity_map
          WHERE version_program_id=$2 AND entity_type=''OBJECTIVE'') ORDER BY t.id';
    WHEN 'LESSON_TRANSLATIONS' THEN
      v_table_name:='lesson_translation'; v_entity_type:=NULL;
      v_query := 'SELECT to_jsonb(t) FROM public.lesson_translation t
        WHERE t.lesson_id IN (SELECT source_entity_id FROM institution_course_version_entity_map
          WHERE version_program_id=$2 AND entity_type=''LESSON'') ORDER BY t.id';
    WHEN 'BLOCK_TRANSLATIONS' THEN
      v_table_name:='lesson_block_translation'; v_entity_type:=NULL;
      v_query := 'SELECT to_jsonb(t) FROM public.lesson_block_translation t
        WHERE t.block_id IN (SELECT source_entity_id FROM institution_course_version_entity_map
          WHERE version_program_id=$2 AND entity_type=''LESSON_BLOCK'') ORDER BY t.id';
    WHEN 'QUESTION_TRANSLATIONS' THEN
      v_table_name:='question_translation'; v_entity_type:=NULL;
      v_query := 'SELECT to_jsonb(t) FROM public.question_translation t
        WHERE t.question_id IN (SELECT source_entity_id FROM institution_course_version_entity_map
          WHERE version_program_id=$2 AND entity_type=''QUESTION'') ORDER BY t.id';
    WHEN 'ASSESSMENTS' THEN
      v_table_name:='assessment'; v_entity_type:='ASSESSMENT';
      v_query := 'SELECT to_jsonb(t) FROM public.assessment t WHERE t.course_id=$1 ORDER BY t.id';
    WHEN 'ASSESSMENT_QUESTIONS' THEN
      v_table_name:='assessment_question'; v_entity_type:='ASSESSMENT_QUESTION';
      v_query := 'SELECT to_jsonb(t) FROM public.assessment_question t
        WHERE t.assessment_id IN (SELECT source_entity_id FROM institution_course_version_entity_map
          WHERE version_program_id=$2 AND entity_type=''ASSESSMENT'') ORDER BY t.id';
    WHEN 'ASSESSMENT_TRANSLATIONS' THEN
      v_table_name:='assessment_translation'; v_entity_type:=NULL;
      v_query := 'SELECT to_jsonb(t) FROM public.assessment_translation t
        WHERE t.assessment_id IN (SELECT source_entity_id FROM institution_course_version_entity_map
          WHERE version_program_id=$2 AND entity_type=''ASSESSMENT'') ORDER BY t.id';
    WHEN 'ASSESSMENT_QUESTION_TRANSLATIONS' THEN
      v_table_name:='assessment_question_translation'; v_entity_type:=NULL;
      v_query := 'SELECT to_jsonb(t) FROM public.assessment_question_translation t
        WHERE t.assessment_question_id IN (SELECT source_entity_id FROM institution_course_version_entity_map
          WHERE version_program_id=$2 AND entity_type=''ASSESSMENT_QUESTION'') ORDER BY t.id';
    WHEN 'DOCUMENT_ASSIGNMENTS' THEN
      v_table_name:='learning_document_course_assignment'; v_entity_type:=NULL;
      v_query := 'SELECT to_jsonb(t) FROM public.learning_document_course_assignment t WHERE t.course_id=$1 ORDER BY t.id';
    WHEN 'RESOURCE_ASSIGNMENTS' THEN
      v_table_name:='learning_resource_assignment'; v_entity_type:='RESOURCE_ASSIGNMENT';
      v_query := 'SELECT to_jsonb(t) FROM public.learning_resource_assignment t
        WHERE t.chapter_id IN (SELECT source_entity_id FROM institution_course_version_entity_map
          WHERE version_program_id=$2 AND entity_type=''CHAPTER'') ORDER BY t.id';
    WHEN 'ASSESSMENT_PACKS' THEN
      v_table_name:='course_assessment_pack'; v_entity_type:='ASSESSMENT_PACK';
      v_query := 'SELECT to_jsonb(t) FROM public.course_assessment_pack t WHERE t.course_id=$1 ORDER BY t.id';
    WHEN 'ASSESSMENT_PACK_ITEMS' THEN
      v_table_name:='course_assessment_pack_item'; v_entity_type:='ASSESSMENT_PACK_ITEM';
      v_query := 'SELECT to_jsonb(t) FROM public.course_assessment_pack_item t
        WHERE t.pack_id IN (SELECT source_entity_id FROM institution_course_version_entity_map
          WHERE version_program_id=$2 AND entity_type=''ASSESSMENT_PACK'') ORDER BY t.id';
    WHEN 'ASSESSMENT_PACK_RESOURCES' THEN
      v_table_name:='course_assessment_pack_resource'; v_entity_type:=NULL;
      v_query := 'SELECT to_jsonb(t) FROM public.course_assessment_pack_resource t
        WHERE t.pack_id IN (SELECT source_entity_id FROM institution_course_version_entity_map
          WHERE version_program_id=$2 AND entity_type=''ASSESSMENT_PACK'') ORDER BY t.id';
    ELSE
      RAISE EXCEPTION 'COURSE_VERSION_FORK_UNKNOWN_SCOPE: %',p_scope USING ERRCODE='23514';
  END CASE;

  FOR v_row IN EXECUTE v_query USING p_source_program_id,p_version_program_id
  LOOP
    PERFORM qe_clone_course_version_row(
      v_table_name,v_row,p_source_program_id,p_version_program_id,p_course_identity_id,
      p_content_version_no,v_entity_type,p_actor_staff_id,p_actor_institution_admin_id);
  END LOOP;
END
$$;

CREATE OR REPLACE FUNCTION qe_fork_course_version(
  p_source_program_id bigint,
  p_institution_id bigint,
  p_actor_staff_id bigint,
  p_actor_institution_admin_id bigint
) RETURNS TABLE(new_program_id bigint,content_version_no integer,release_id bigint,assignment_id bigint)
LANGUAGE plpgsql
AS $$
DECLARE
  v_source curriculum_program%ROWTYPE;
  v_identity institution_course_identity%ROWTYPE;
  v_latest_version integer;
  v_new_program_id bigint;
  v_version integer;
  v_code text;
  v_release_id bigint;
  v_assignment_id bigint;
  v_fingerprint text;
  v_row jsonb;
  v_artifact record;
  v_new_artifact_id text;
  v_resource_id bigint;
  v_document_id bigint;
BEGIN
  SELECT p.* INTO v_source
  FROM curriculum_program p
  WHERE p.id=p_source_program_id AND p.code<>'GENERAL' AND p.status='ACTIVE'
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'COURSE_VERSION_SOURCE_NOT_FOUND: the source course is inactive or missing'
      USING ERRCODE='P0002';
  END IF;

  IF v_source.course_identity_id IS NULL THEN
    RAISE EXCEPTION 'COURSE_VERSION_IDENTITY_REQUIRED: this legacy course needs HRMS/source-owner reconciliation before it can be versioned'
      USING ERRCODE='23514';
  END IF;

  SELECT i.* INTO v_identity
  FROM institution_course_identity i
  WHERE i.id=v_source.course_identity_id AND i.source_institution_id=p_institution_id
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'COURSE_VERSION_SOURCE_OWNERSHIP: only the HRMS-bound source institution may create a draft version'
      USING ERRCODE='42501';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM institution_course_release r
    WHERE r.program_id=p_source_program_id AND r.source_institution_id=p_institution_id
      AND r.release_state IN ('SHAREABLE','WITHDRAWN','LEGACY_MIGRATED')
  ) THEN
    RAISE EXCEPTION 'COURSE_VERSION_RELEASE_REQUIRED: edit an unsubmitted draft in place or release the course before creating a new version'
      USING ERRCODE='23514';
  END IF;

  IF EXISTS (
    SELECT 1 FROM curriculum_program p
    JOIN institution_course_release r ON r.program_id=p.id
    WHERE p.course_identity_id=v_identity.id
      AND p.content_version_no>v_source.content_version_no
      AND r.release_state IN ('DRAFT','IN_QUALITY_REVIEW','QUALITY_APPROVED')
  ) THEN
    RAISE EXCEPTION 'COURSE_VERSION_DRAFT_EXISTS: open the existing draft version rather than forking another copy'
      USING ERRCODE='23505';
  END IF;

  v_latest_version := coalesce((
    SELECT max(p.content_version_no) FROM curriculum_program p
    WHERE p.course_identity_id=v_identity.id
  ),v_source.content_version_no);
  v_version := v_latest_version+1;
  v_code := left(v_source.code,45)||'_V'||v_version;

  INSERT INTO curriculum_program(
    class_id,code,display_name,stream_code,curriculum_version,status,notes,public_id_prefix,
    course_type_code,course_identity_id,content_version_no,supersedes_program_id
  ) VALUES (
    v_source.class_id,v_code,v_source.display_name,v_source.stream_code,v_source.curriculum_version,
    'ACTIVE',v_source.notes,v_source.public_id_prefix,v_source.course_type_code,
    v_identity.id,v_version,p_source_program_id
  ) RETURNING id INTO v_new_program_id;
  IF v_new_program_id IS NULL THEN
    RAISE EXCEPTION 'COURSE_VERSION_CREATE_FAILED: new course graph was not created';
  END IF;

  -- Generic resource/documents are immutable reusable media; map them to themselves and clone
  -- only the version-specific assignment rows that connect those resources to the new graph.
  INSERT INTO institution_course_version_entity_map(
    course_identity_id,source_program_id,version_program_id,entity_type,source_entity_id,version_entity_id
  )
  SELECT v_identity.id,p_source_program_id,v_new_program_id,'LEARNING_RESOURCE',r.id,r.id
  FROM learning_resource r
  WHERE EXISTS (
    SELECT 1 FROM learning_resource_assignment a
    WHERE a.resource_id=r.id
      AND a.chapter_id IN (
        SELECT ch.id FROM curriculum_chapter ch
        JOIN curriculum_program_subject ps ON ps.subject_id=ch.subject_id
        WHERE ps.program_id=p_source_program_id
      )
  ) OR EXISTS (
    SELECT 1 FROM course_assessment_pack_resource pr
    JOIN course_assessment_pack pack ON pack.id=pr.pack_id AND pack.course_id=p_source_program_id
    WHERE pr.resource_id=r.id
  )
  ON CONFLICT(version_program_id,entity_type,source_entity_id) DO NOTHING;

  INSERT INTO institution_course_version_entity_map(
    course_identity_id,source_program_id,version_program_id,entity_type,source_entity_id,version_entity_id
  )
  SELECT v_identity.id,p_source_program_id,v_new_program_id,'LEARNING_DOCUMENT',d.id,d.id
  FROM learning_document d
  WHERE EXISTS (
    SELECT 1 FROM learning_document_course_assignment a
    WHERE a.learning_document_id=d.id AND a.course_id=p_source_program_id
  ) OR EXISTS (
    SELECT 1 FROM learning_resource r
    JOIN institution_course_version_entity_map rm
      ON rm.version_program_id=v_new_program_id AND rm.entity_type='LEARNING_RESOURCE'
       AND rm.source_entity_id=r.id
    WHERE r.learning_document_id=d.id
  )
  ON CONFLICT(version_program_id,entity_type,source_entity_id) DO NOTHING;

  PERFORM qe_clone_course_table_rows('SUBJECTS',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);
  PERFORM qe_clone_course_table_rows('PROGRAM_SUBJECTS',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);
  PERFORM qe_clone_course_table_rows('CHAPTERS',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);
  PERFORM qe_clone_course_table_rows('OBJECTIVES',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);
  PERFORM qe_clone_course_table_rows('CONCEPTS',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);
  -- Structured-artifact links have stable external IDs. Build a new version-scoped ID and then
  -- rewrite matching references in lesson-block JSON and resource assignments before cloning them.
  FOR v_artifact IN
    SELECT s.artifact_id,s.chapter_id
    FROM learning_resource_artifact_scope s
    WHERE s.chapter_id IN (SELECT source_entity_id FROM institution_course_version_entity_map
      WHERE version_program_id=v_new_program_id AND entity_type='CHAPTER')
    ORDER BY s.artifact_id
  LOOP
    v_new_artifact_id := left(v_artifact.artifact_id,85)||'-cv'||v_version||'-'||v_new_program_id;
    INSERT INTO institution_course_version_artifact_map(
      course_identity_id,source_program_id,version_program_id,source_artifact_id,version_artifact_id
    ) VALUES(v_identity.id,p_source_program_id,v_new_program_id,v_artifact.artifact_id,v_new_artifact_id);
  END LOOP;
  PERFORM qe_clone_course_table_rows('ARTIFACT_SCOPES',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);

  PERFORM qe_clone_course_table_rows('BOOKS',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);
  PERFORM qe_clone_course_table_rows('PAGES',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);
  PERFORM qe_clone_course_table_rows('CHAPTER_SOURCES',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);
  PERFORM qe_clone_course_table_rows('REQUIREMENTS',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);
  PERFORM qe_clone_course_table_rows('LESSONS',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);
  PERFORM qe_clone_course_table_rows('LESSON_BLOCKS',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);
  PERFORM qe_clone_course_table_rows('QUESTIONS',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);
  PERFORM qe_clone_course_table_rows('QUESTION_OPTIONS',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);
  PERFORM qe_clone_course_table_rows('PROGRAM_TRANSLATIONS',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);
  PERFORM qe_clone_course_table_rows('SUBJECT_TRANSLATIONS',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);
  PERFORM qe_clone_course_table_rows('CHAPTER_TRANSLATIONS',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);
  PERFORM qe_clone_course_table_rows('OBJECTIVE_TRANSLATIONS',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);
  PERFORM qe_clone_course_table_rows('LESSON_TRANSLATIONS',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);
  PERFORM qe_clone_course_table_rows('BLOCK_TRANSLATIONS',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);
  PERFORM qe_clone_course_table_rows('QUESTION_TRANSLATIONS',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);
  PERFORM qe_clone_course_table_rows('ASSESSMENTS',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);
  PERFORM qe_clone_course_table_rows('ASSESSMENT_QUESTIONS',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);
  PERFORM qe_clone_course_table_rows('ASSESSMENT_TRANSLATIONS',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);
  PERFORM qe_clone_course_table_rows('ASSESSMENT_QUESTION_TRANSLATIONS',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);
  PERFORM qe_clone_course_table_rows('DOCUMENT_ASSIGNMENTS',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);
  PERFORM qe_clone_course_table_rows('RESOURCE_ASSIGNMENTS',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);
  PERFORM qe_clone_course_table_rows('ASSESSMENT_PACKS',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);
  PERFORM qe_clone_course_table_rows('ASSESSMENT_PACK_ITEMS',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);
  PERFORM qe_clone_course_table_rows('ASSESSMENT_PACK_RESOURCES',p_source_program_id,v_new_program_id,v_identity.id,v_version,p_actor_staff_id,p_actor_institution_admin_id);

  v_fingerprint := course_content_fingerprint(v_new_program_id);
  INSERT INTO institution_course_release(
    source_institution_id,program_id,release_version,release_state,content_fingerprint,
    legacy_migration,created_at,updated_at
  ) VALUES(p_institution_id,v_new_program_id,1,'DRAFT',coalesce(v_fingerprint,''),false,now(),now())
  RETURNING id INTO v_release_id;

  INSERT INTO institution_course_assignment(
    institution_id,course_release_id,status,assignment_source,assigned_at,created_at,updated_at
  ) VALUES(p_institution_id,v_release_id,'ASSIGNED','ORIGIN',now(),now(),now())
  RETURNING id INTO v_assignment_id;

  INSERT INTO institution_course_version_event(
    course_identity_id,source_program_id,version_program_id,content_version_no,event_type,
    actor_staff_id,actor_institution_admin_id,details
  ) VALUES (
    v_identity.id,p_source_program_id,v_new_program_id,v_version,'DRAFT_VERSION_CREATED',
    p_actor_staff_id,p_actor_institution_admin_id,
    jsonb_build_object('sourceProgramId',p_source_program_id,'versionProgramId',v_new_program_id,
      'releaseId',v_release_id,'releaseState','DRAFT','contentFingerprint',v_fingerprint)
  );

  RETURN QUERY SELECT v_new_program_id,v_version,v_release_id,v_assignment_id;
END
$$;

