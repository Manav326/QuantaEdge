-- V217: one shared expiry policy per logical course identity, per-enrollment access controls,
-- and immutable audit history. Existing enrollments are deliberately grandfathered: no expiry
-- is backfilled and configuring a policy affects only future/reactivated enrollments.

-- Existing course identities are grandfathered. Source-course registration explicitly marks
-- newly registered identities as requiring an HRMS expiry policy before Marketplace offer setup.
ALTER TABLE institution_course_identity
  ADD COLUMN course_expiry_policy_required boolean NOT NULL DEFAULT false;
ALTER TABLE student_program_enrollment
  ADD COLUMN course_identity_id bigint REFERENCES institution_course_identity(id) ON DELETE RESTRICT,
  ADD COLUMN course_expires_at timestamptz,
  ADD COLUMN course_access_blocked boolean NOT NULL DEFAULT false,
  ADD COLUMN course_access_blocked_at timestamptz,
  ADD COLUMN course_access_blocked_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  ADD COLUMN course_expiry_policy_version_snapshot bigint,
  ADD COLUMN course_expiry_mode_snapshot varchar(24),
  ADD COLUMN course_expiry_years_snapshot integer,
  ADD COLUMN course_expiry_months_snapshot integer,
  ADD COLUMN course_expiry_days_snapshot integer,
  ADD COLUMN course_expiry_fixed_days_snapshot integer,
  ADD CONSTRAINT ck_student_enrollment_expiry_snapshot_mode
    CHECK (course_expiry_mode_snapshot IS NULL
      OR course_expiry_mode_snapshot IN ('CALENDAR_DURATION','FIXED_DAYS')),
  ADD CONSTRAINT ck_student_enrollment_expiry_snapshot_values
    CHECK (
      (course_expiry_mode_snapshot IS NULL
        AND course_expiry_policy_version_snapshot IS NULL
        AND course_expiry_years_snapshot IS NULL
        AND course_expiry_months_snapshot IS NULL
        AND course_expiry_days_snapshot IS NULL
        AND course_expiry_fixed_days_snapshot IS NULL)
      OR
      (course_expiry_mode_snapshot='CALENDAR_DURATION'
        AND course_expiry_policy_version_snapshot IS NOT NULL
        AND course_expiry_policy_version_snapshot > 0
        AND course_expiry_years_snapshot IS NOT NULL AND course_expiry_years_snapshot >= 0
        AND course_expiry_months_snapshot IS NOT NULL AND course_expiry_months_snapshot >= 0
        AND course_expiry_days_snapshot IS NOT NULL AND course_expiry_days_snapshot >= 0
        AND (course_expiry_years_snapshot + course_expiry_months_snapshot
             + course_expiry_days_snapshot) > 0
        AND course_expiry_fixed_days_snapshot IS NULL)
      OR
      (course_expiry_mode_snapshot='FIXED_DAYS'
        AND course_expiry_policy_version_snapshot IS NOT NULL
        AND course_expiry_policy_version_snapshot > 0
        AND course_expiry_years_snapshot IS NULL
        AND course_expiry_months_snapshot IS NULL
        AND course_expiry_days_snapshot IS NULL
        AND course_expiry_fixed_days_snapshot > 0)
    ),
  ADD CONSTRAINT ck_student_enrollment_access_block_consistent
    CHECK (
      (course_access_blocked=false AND course_access_blocked_at IS NULL
        AND course_access_blocked_by_staff_id IS NULL)
      OR
      (course_access_blocked=true AND course_access_blocked_at IS NOT NULL)
    );

