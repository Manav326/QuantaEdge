-- V178: idempotency/audit registry for atomic nested course-definition JSON imports.
-- Course structure remains in the canonical curriculum tables; the manifest preserves the exact
-- package identity and checksum without duplicating learner progress or historical attempts.
CREATE TABLE course_package_import (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institution_id bigint NOT NULL REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  package_id varchar(120) NOT NULL CHECK (package_id ~ '^[a-z0-9][a-z0-9._-]{2,119}$'),
  package_version varchar(40) NOT NULL CHECK (package_version ~ '^[A-Za-z0-9][A-Za-z0-9._+-]{0,39}$'),
  content_sha256 char(64) NOT NULL CHECK (content_sha256 ~ '^[0-9a-f]{64}$'),
  package_snapshot jsonb NOT NULL CHECK (jsonb_typeof(package_snapshot)='object'),
  course_id bigint NOT NULL REFERENCES curriculum_program(id) ON DELETE RESTRICT,
  course_release_id bigint NOT NULL REFERENCES institution_course_release(id) ON DELETE RESTRICT,
  imported_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  imported_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(institution_id,package_id,package_version),
  UNIQUE(course_release_id)
);
CREATE INDEX idx_course_package_import_institution_time
  ON course_package_import(institution_id,imported_at DESC,id DESC);
CREATE INDEX idx_course_package_import_course
  ON course_package_import(course_id,imported_at DESC,id DESC);

COMMENT ON TABLE course_package_import IS
  'Idempotent record of a validated nested course-package import. Identity is scoped to the source institution; JSON cannot set institution identity or lifecycle/approval state.';
COMMENT ON COLUMN course_package_import.package_snapshot IS
  'Exact versioned source package retained for provenance and later schema migration/reconciliation; contains no generated server IDs, secrets or publication authority.';

INSERT INTO app_metadata(key,value)
