  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recorded_class_id bigint NOT NULL REFERENCES recorded_class(id) ON DELETE CASCADE,
  language varchar(5) NOT NULL CHECK (language IN ('hi','en')),
  asset_type varchar(24) NOT NULL
    CHECK (asset_type IN ('SUBTITLES_VTT','TRANSCRIPT','DUBBED_AUDIO','AUDIO_DESCRIPTION')),
  storage_key varchar(240) NOT NULL UNIQUE,
  media_type varchar(100) NOT NULL,
  file_size_bytes bigint NOT NULL CHECK (file_size_bytes BETWEEN 1 AND 524288000),
  sha256 varchar(64) NOT NULL CHECK (length(sha256) = 64),
  status varchar(20) NOT NULL DEFAULT 'DRAFT'
    CHECK (status IN ('DRAFT','PUBLISHED','ARCHIVED')),
  created_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  published_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  published_at timestamptz,
  UNIQUE(recorded_class_id, language, asset_type, sha256)
);
CREATE INDEX idx_recorded_class_language_assets
  ON recorded_class_language_asset(recorded_class_id, language, status);

