-- Audit requirements are contracts, not claims that the chapters already satisfy them.
insert into lesson_requirement(chapter_id,requirement_code,description,min_count,required)
select ch.id,r.code,r.description,r.min_count,r.required
from curriculum_chapter ch
cross join (values
  ('PREREQUISITE','A prerequisite or prior-knowledge bridge is present.',1,true),
  ('EXPLANATION','An original, clear teaching explanation is present.',1,true),
  ('WORKED_EXAMPLE','At least one worked example is present.',1,true),
  ('GUIDED_PRACTICE','At least one guided practice activity is present.',1,true),
  ('INDEPENDENT_PRACTICE','At least one independent practice activity is present.',1,true),
  ('RECAP','A concise recap or summary is present.',1,true),
  ('VISUAL_OR_NOT_REQUIRED','A useful visual is present, or a reviewer records why it is not needed.',0,false),
  ('NCERT_OR_TEXTBOOK_MAPPING','The chapter has a verified textbook/source mapping.',1,true),
  ('BOARD_FORMAT_COVERAGE','At least one board-style assessment format is present.',1,true),
  ('SOURCE_TAGGED_QUESTIONS','Source provenance is recorded when third-party questions are used.',1,true)
) as r(code,description,min_count,required)
where ch.active=true and ch.content_status='PUBLISHED'
on conflict(chapter_id,requirement_code) do update set
  description=excluded.description,min_count=excluded.min_count,required=excluded.required;

-- These are generic lesson shells, not completed lessons. Keep them editable in
-- admin, but unpublished until real, reviewed teaching blocks and assessments exist.
update lesson
set status='DRAFT'
where active=true and code ~ '-(foundation|guided-practice|mastery)$';

update question q
set active=false,review_status='REJECTED',
    review_notes='Generated template question disabled; replace with reviewed, original practice.'
where q.active=true
  and q.lesson_id in (
    select l.id from lesson l
    where l.code ~ '-(foundation|guided-practice|mastery)$'
  );

