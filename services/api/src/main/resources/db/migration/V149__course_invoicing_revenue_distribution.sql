-- Issued documents, financial snapshots and ledger events are append-only. Use compensating
-- adjustment records instead of mutating/deleting a historical monetary or document fact.
CREATE OR REPLACE FUNCTION reject_billing_financial_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION '% is append-only; create an adjustment or a new version instead', TG_TABLE_NAME
    USING ERRCODE='23514';
END;
$$;

CREATE TRIGGER trg_fiscal_document_immutable
BEFORE UPDATE OR DELETE ON fiscal_document
FOR EACH ROW EXECUTE FUNCTION reject_billing_financial_mutation();
