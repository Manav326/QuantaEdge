-- V216: audited, additive repairs for historical course-sale remainder allocations.
-- The original order snapshot and allocation ledger remain immutable. Corrections are
-- separately evidenced and reviewed, and only an approved repair can create a new allocation.
CREATE TABLE course_revenue_distribution_repair (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  course_payment_order_id bigint NOT NULL REFERENCES course_payment_order(id) ON DELETE RESTRICT,
  repair_type varchar(48) NOT NULL CHECK (repair_type='MISSING_REMAINDER_ALLOCATION'),
  original_snapshot_sha256 char(64) NOT NULL CHECK (original_snapshot_sha256 ~ '^[0-9a-f]{64}$'),
  remainder_recipient_type varchar(16) NOT NULL CHECK (remainder_recipient_type IN ('INSTITUTION','COMPANY')),
  remainder_institution_id bigint REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  remainder_legal_entity_id bigint REFERENCES billing_legal_entity(id) ON DELETE RESTRICT,
  remainder_amount_paise bigint NOT NULL CHECK (remainder_amount_paise>0),
  currency char(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
  reason varchar(500) NOT NULL CHECK (length(btrim(reason)) BETWEEN 5 AND 500),
  evidence_reference varchar(180) NOT NULL CHECK (length(btrim(evidence_reference)) BETWEEN 3 AND 180),
  idempotency_key varchar(180) NOT NULL UNIQUE CHECK (idempotency_key ~ '^[A-Za-z0-9_-]{10,180}$'),
  status varchar(24) NOT NULL DEFAULT 'PENDING_APPROVAL'
    CHECK (status IN ('PENDING_APPROVAL','APPLIED','REJECTED')),
  proposed_by_staff_id bigint NOT NULL REFERENCES staff_account(id) ON DELETE RESTRICT,
  reviewed_by_staff_id bigint REFERENCES staff_account(id) ON DELETE RESTRICT,
  reviewed_at timestamptz,
  applied_at timestamptz,
  review_reason varchar(500),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (
    (remainder_recipient_type='INSTITUTION'
      AND remainder_institution_id IS NOT NULL AND remainder_legal_entity_id IS NULL)
    OR
    (remainder_recipient_type='COMPANY'
      AND remainder_institution_id IS NULL AND remainder_legal_entity_id IS NOT NULL)
  ),
  CHECK (
    (status='PENDING_APPROVAL' AND reviewed_by_staff_id IS NULL AND reviewed_at IS NULL
      AND applied_at IS NULL AND review_reason IS NULL)
    OR
    (status='APPLIED' AND reviewed_by_staff_id IS NOT NULL AND reviewed_at IS NOT NULL
      AND applied_at IS NOT NULL AND review_reason IS NOT NULL)
    OR
    (status='REJECTED' AND reviewed_by_staff_id IS NOT NULL AND reviewed_at IS NOT NULL
      AND applied_at IS NULL AND review_reason IS NOT NULL)
  )
);
CREATE INDEX idx_course_revenue_distribution_repair_order
  ON course_revenue_distribution_repair(course_payment_order_id,created_at DESC,id DESC);
CREATE UNIQUE INDEX uq_course_revenue_distribution_repair_active_order
  ON course_revenue_distribution_repair(course_payment_order_id,repair_type)
  WHERE status IN ('PENDING_APPROVAL','APPLIED');

-- Proposal facts never change after submission. Only a pending request can transition once
-- to APPLIED or REJECTED; every transition is separately recorded in the finance audit log.
CREATE OR REPLACE FUNCTION protect_course_revenue_distribution_repair()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP='DELETE' THEN
    RAISE EXCEPTION 'course_revenue_distribution_repair is retained for audit and cannot be deleted'
      USING ERRCODE='23514';
  END IF;
  IF NEW.id IS DISTINCT FROM OLD.id
    OR NEW.public_id IS DISTINCT FROM OLD.public_id
    OR NEW.course_payment_order_id IS DISTINCT FROM OLD.course_payment_order_id
    OR NEW.repair_type IS DISTINCT FROM OLD.repair_type
    OR NEW.original_snapshot_sha256 IS DISTINCT FROM OLD.original_snapshot_sha256
    OR NEW.remainder_recipient_type IS DISTINCT FROM OLD.remainder_recipient_type
    OR NEW.remainder_institution_id IS DISTINCT FROM OLD.remainder_institution_id
    OR NEW.remainder_legal_entity_id IS DISTINCT FROM OLD.remainder_legal_entity_id
    OR NEW.remainder_amount_paise IS DISTINCT FROM OLD.remainder_amount_paise
    OR NEW.currency IS DISTINCT FROM OLD.currency
    OR NEW.reason IS DISTINCT FROM OLD.reason
    OR NEW.evidence_reference IS DISTINCT FROM OLD.evidence_reference
    OR NEW.idempotency_key IS DISTINCT FROM OLD.idempotency_key
    OR NEW.proposed_by_staff_id IS DISTINCT FROM OLD.proposed_by_staff_id
    OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
    RAISE EXCEPTION 'Submitted distribution-repair proposal facts are immutable'
      USING ERRCODE='23514';
  END IF;
  IF OLD.status<>'PENDING_APPROVAL' OR NEW.status NOT IN ('APPLIED','REJECTED') THEN
    RAISE EXCEPTION 'Only a pending distribution-repair proposal can be reviewed once'
      USING ERRCODE='23514';
  END IF;
  IF NEW.status='APPLIED' AND NOT EXISTS (
    SELECT 1
    FROM revenue_share_allocation a
    JOIN revenue_share_allocation_event e ON e.allocation_id=a.id
      AND e.event_type='EARNED'
      AND e.details->>'distributionRepairId'=NEW.id::text
      AND e.amount_paise=NEW.remainder_amount_paise
    WHERE a.course_payment_order_id=NEW.course_payment_order_id
      AND a.recipient_type=NEW.remainder_recipient_type
      AND ((NEW.remainder_recipient_type='INSTITUTION' AND a.institution_id=NEW.remainder_institution_id)
        OR (NEW.remainder_recipient_type='COMPANY' AND a.legal_entity_id=NEW.remainder_legal_entity_id))
  ) THEN
    RAISE EXCEPTION 'A distribution repair cannot be marked applied without its matching allocation and EARNED event'
      USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER trg_course_revenue_distribution_repair_guard
BEFORE UPDATE OR DELETE ON course_revenue_distribution_repair
FOR EACH ROW EXECUTE FUNCTION protect_course_revenue_distribution_repair();

INSERT INTO app_metadata(key,value)
VALUES ('schema','audited-course-revenue-distribution-repair-v216')
ON CONFLICT(key) DO UPDATE SET value=excluded.value;
