-- V111: provider-neutral learning resources and ordered chapter/lesson/artifact assignments.
-- Existing media remains referenced by ID; only new uploads have a private-disk storage key.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='uq_lesson_id_chapter') THEN
    ALTER TABLE lesson ADD CONSTRAINT uq_lesson_id_chapter UNIQUE(id,chapter_id);
  END IF;
END $$;

CREATE TABLE learning_resource (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resource_type varchar(24) NOT NULL CHECK (resource_type IN ('VIDEO','PDF','WORKSHEET','SLIDES','AUDIO','IMAGE','EXTERNAL_LINK','OTHER')),
  title varchar(240) NOT NULL,
  description varchar(1600),
  language varchar(8) NOT NULL DEFAULT 'mul' CHECK (language IN ('hi','en','mul')),
  source_kind varchar(24) NOT NULL CHECK (source_kind IN ('RECORDED_CLASS','LEARNING_DOCUMENT','CONTENT_ASSET','PRIVATE_UPLOAD','EXTERNAL_URL')),
  recorded_class_id bigint REFERENCES recorded_class(id) ON DELETE RESTRICT,
  learning_document_id bigint REFERENCES learning_document(id) ON DELETE RESTRICT,
  content_asset_id bigint REFERENCES content_asset(id) ON DELETE RESTRICT,
  storage_key varchar(180) UNIQUE,
  external_url varchar(2000),
  original_filename varchar(255),
  media_type varchar(120),
  file_size_bytes bigint,
  sha256 varchar(64),
  duration_seconds integer CHECK (duration_seconds IS NULL OR duration_seconds BETWEEN 1 AND 86400),
  source_reference varchar(500),
  download_allowed boolean NOT NULL DEFAULT false,
  status varchar(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','REVIEW','PUBLISHED','ARCHIVED')),
  version_no integer NOT NULL DEFAULT 1 CHECK (version_no > 0),
  supersedes_resource_id bigint REFERENCES learning_resource(id) ON DELETE RESTRICT,
  created_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  published_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  published_at timestamptz,
  CONSTRAINT ck_learning_resource_exact_source CHECK (
    (source_kind='RECORDED_CLASS' AND recorded_class_id IS NOT NULL AND learning_document_id IS NULL
      AND content_asset_id IS NULL AND storage_key IS NULL AND external_url IS NULL)
    OR
    (source_kind='LEARNING_DOCUMENT' AND recorded_class_id IS NULL AND learning_document_id IS NOT NULL
      AND content_asset_id IS NULL AND storage_key IS NULL AND external_url IS NULL)
    OR
    (source_kind='CONTENT_ASSET' AND recorded_class_id IS NULL AND learning_document_id IS NULL
      AND content_asset_id IS NOT NULL AND storage_key IS NULL AND external_url IS NULL)
    OR
    (source_kind='PRIVATE_UPLOAD' AND recorded_class_id IS NULL AND learning_document_id IS NULL
      AND content_asset_id IS NULL AND storage_key IS NOT NULL AND external_url IS NULL
      AND original_filename IS NOT NULL AND media_type IS NOT NULL
      AND file_size_bytes BETWEEN 1 AND 524288000 AND sha256 IS NOT NULL AND length(sha256)=64)
    OR
    (source_kind='EXTERNAL_URL' AND recorded_class_id IS NULL AND learning_document_id IS NULL
      AND content_asset_id IS NULL AND storage_key IS NULL AND external_url IS NOT NULL
      AND lower(external_url) LIKE 'https://%')
  ),
  CONSTRAINT ck_learning_resource_link_type CHECK (
    (source_kind='RECORDED_CLASS' AND resource_type='VIDEO')
    OR (source_kind='LEARNING_DOCUMENT' AND resource_type='PDF')
    OR (source_kind='CONTENT_ASSET' AND resource_type IN ('VIDEO','AUDIO','IMAGE','OTHER'))
    OR source_kind IN ('PRIVATE_UPLOAD','EXTERNAL_URL')
  ),
  CONSTRAINT ck_learning_resource_sha256 CHECK (
    sha256 IS NULL OR (length(sha256)=64 AND sha256 !~ '[^0-9a-f]')
  )
);
CREATE INDEX idx_learning_resource_status_type ON learning_resource(status,resource_type,created_at DESC);
CREATE INDEX idx_learning_resource_recorded_class ON learning_resource(recorded_class_id) WHERE recorded_class_id IS NOT NULL;
CREATE INDEX idx_learning_resource_learning_document ON learning_resource(learning_document_id) WHERE learning_document_id IS NOT NULL;
CREATE INDEX idx_learning_resource_content_asset ON learning_resource(content_asset_id) WHERE content_asset_id IS NOT NULL;

-- Stable structured artifact IDs require an explicit, audited mapping to canonical chapter IDs.
CREATE TABLE learning_resource_artifact_scope (
  artifact_id varchar(120) PRIMARY KEY,
  chapter_id bigint NOT NULL REFERENCES curriculum_chapter(id) ON DELETE RESTRICT,
  artifact_sha256 varchar(64) NOT NULL CHECK (length(artifact_sha256)=64),
  created_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  updated_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(artifact_id,chapter_id)
);

CREATE TABLE learning_resource_assignment (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resource_id bigint NOT NULL REFERENCES learning_resource(id) ON DELETE RESTRICT,
  target_kind varchar(24) NOT NULL CHECK (target_kind IN ('CHAPTER','LESSON','STRUCTURED_ARTIFACT')),
  chapter_id bigint NOT NULL REFERENCES curriculum_chapter(id) ON DELETE RESTRICT,
  lesson_id bigint,
  artifact_id varchar(120),
  sort_order integer NOT NULL DEFAULT 0 CHECK (sort_order BETWEEN 0 AND 1000000),
  status varchar(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','PUBLISHED','ARCHIVED')),
  created_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  published_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  published_at timestamptz,
  CONSTRAINT ck_learning_resource_assignment_target CHECK (
    (target_kind='CHAPTER' AND lesson_id IS NULL AND artifact_id IS NULL)
    OR (target_kind='LESSON' AND lesson_id IS NOT NULL AND artifact_id IS NULL)
    OR (target_kind='STRUCTURED_ARTIFACT' AND lesson_id IS NULL AND artifact_id IS NOT NULL)
  ),
  CONSTRAINT fk_learning_resource_assignment_lesson_chapter
    FOREIGN KEY(lesson_id,chapter_id) REFERENCES lesson(id,chapter_id) ON DELETE RESTRICT,
  CONSTRAINT fk_learning_resource_assignment_artifact_scope
    FOREIGN KEY(artifact_id,chapter_id) REFERENCES learning_resource_artifact_scope(artifact_id,chapter_id) ON DELETE RESTRICT
);
CREATE INDEX idx_learning_resource_assignment_chapter ON learning_resource_assignment(chapter_id,status,sort_order,id);
CREATE INDEX idx_learning_resource_assignment_lesson ON learning_resource_assignment(lesson_id,status,sort_order,id) WHERE lesson_id IS NOT NULL;
CREATE INDEX idx_learning_resource_assignment_artifact ON learning_resource_assignment(artifact_id,status,sort_order,id) WHERE artifact_id IS NOT NULL;
CREATE INDEX idx_learning_resource_assignment_resource ON learning_resource_assignment(resource_id,status);
CREATE UNIQUE INDEX uq_learning_resource_assignment_chapter_active
  ON learning_resource_assignment(resource_id,chapter_id) WHERE target_kind='CHAPTER' AND status<>'ARCHIVED';
CREATE UNIQUE INDEX uq_learning_resource_assignment_lesson_active
  ON learning_resource_assignment(resource_id,lesson_id) WHERE target_kind='LESSON' AND status<>'ARCHIVED';
CREATE UNIQUE INDEX uq_learning_resource_assignment_artifact_active
  ON learning_resource_assignment(resource_id,artifact_id) WHERE target_kind='STRUCTURED_ARTIFACT' AND status<>'ARCHIVED';

CREATE TABLE student_learning_resource_progress (
  student_id bigint NOT NULL REFERENCES student(id) ON DELETE CASCADE,
  resource_id bigint NOT NULL REFERENCES learning_resource(id) ON DELETE RESTRICT,
  last_position_seconds bigint NOT NULL DEFAULT 0 CHECK (last_position_seconds >= 0),
  watched_seconds bigint NOT NULL DEFAULT 0 CHECK (watched_seconds >= 0),
  completed boolean NOT NULL DEFAULT false,
  last_opened_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(student_id,resource_id)
);
CREATE INDEX idx_student_learning_resource_progress_updated ON student_learning_resource_progress(student_id,updated_at DESC);

