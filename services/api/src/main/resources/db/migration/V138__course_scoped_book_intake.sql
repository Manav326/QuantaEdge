-- V138: bind uploaded complete-book intake records to their institution and exact course.
-- Pre-institution inventory rows belong to the explicitly migrated QuantaEdge tenant. Only
-- unambiguous course mappings are backfilled; unresolved legacy rows remain hidden from scoped UI.
ALTER TABLE learning_book_intake
  ADD COLUMN institution_id bigint REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  ADD COLUMN course_id bigint REFERENCES curriculum_program(id) ON DELETE RESTRICT;

-- An uploaded PDF is reusable in more than one course. Keep one intake/review lifecycle per
-- (PDF asset, institution, course) instead of preserving V53's global PDF-only primary key.
ALTER TABLE learning_book_intake
  ADD COLUMN id bigint GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE learning_book_intake
  DROP CONSTRAINT IF EXISTS learning_book_intake_pkey;
ALTER TABLE learning_book_intake
  ADD CONSTRAINT learning_book_intake_pkey PRIMARY KEY (id);

DO $require_qe_book_intake$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM institution_tenant
    WHERE tenant_code='QUANTA-EDGE' AND status='ACTIVE'
  ) THEN
    RAISE EXCEPTION 'V138 requires the active QUANTA-EDGE destination institution.';
  END IF;
END
$require_qe_book_intake$;

UPDATE learning_book_intake i
SET institution_id=t.id
FROM institution_tenant t
WHERE t.tenant_code='QUANTA-EDGE' AND t.status='ACTIVE' AND i.institution_id IS NULL;

WITH candidates AS (
  SELECT i.pdf_asset_id AS asset_id,min(p.id) AS course_id
  FROM learning_book_intake i
  JOIN curriculum_subject s ON s.id=i.subject_id AND s.class_id=i.class_id AND s.active=true
  JOIN curriculum_program_subject cps ON cps.subject_id=s.id AND cps.class_id=s.class_id
  JOIN curriculum_program p ON p.id=cps.program_id AND p.status='ACTIVE' AND p.code<>'GENERAL'
  JOIN institution_course_assignment a ON a.institution_id=i.institution_id AND a.status='ASSIGNED'
  JOIN institution_course_release r ON r.id=a.course_release_id AND r.program_id=p.id
  WHERE i.course_id IS NULL AND i.institution_id IS NOT NULL
    AND (s.program_id=p.id OR (s.program_id IS NULL AND p.class_id=s.class_id))
  GROUP BY i.pdf_asset_id
  HAVING count(DISTINCT p.id)=1
)
UPDATE learning_book_intake i
SET course_id=c.course_id
FROM candidates c
WHERE i.pdf_asset_id=c.asset_id AND i.course_id IS NULL;

ALTER TABLE learning_book_intake
  ALTER COLUMN institution_id SET NOT NULL;

CREATE UNIQUE INDEX uq_learning_book_intake_asset_tenant_course
  ON learning_book_intake(pdf_asset_id,institution_id,course_id)
  WHERE course_id IS NOT NULL;

CREATE INDEX idx_learning_book_intake_tenant_course
  ON learning_book_intake(institution_id,course_id,status,updated_at DESC,pdf_asset_id DESC);

CREATE OR REPLACE FUNCTION qe_require_learning_book_intake_course_scope()
RETURNS trigger
LANGUAGE plpgsql
AS $book_intake_scope$
BEGIN
  IF TG_OP='UPDATE'
     AND NEW.institution_id IS NOT DISTINCT FROM OLD.institution_id
     AND NEW.course_id IS NOT DISTINCT FROM OLD.course_id
     AND NEW.class_id IS NOT DISTINCT FROM OLD.class_id
     AND NEW.subject_id IS NOT DISTINCT FROM OLD.subject_id THEN
    RETURN NEW;
  END IF;

  IF NEW.institution_id IS NULL OR NEW.course_id IS NULL THEN
    RAISE EXCEPTION 'COURSE_SCOPE_REQUIRED: book intake requires institution_id and course_id'
      USING ERRCODE='23514';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM curriculum_program p
    JOIN curriculum_program_subject cps ON cps.program_id=p.id
    JOIN curriculum_subject s ON s.id=cps.subject_id AND s.class_id=cps.class_id
      AND s.active=true
    JOIN institution_course_assignment a ON a.institution_id=NEW.institution_id
      AND a.status='ASSIGNED'
    JOIN institution_course_release r ON r.id=a.course_release_id AND r.program_id=p.id
    WHERE p.id=NEW.course_id AND p.status='ACTIVE' AND p.code<>'GENERAL'
      AND s.id=NEW.subject_id AND s.class_id=NEW.class_id
      AND (s.program_id=p.id OR (s.program_id IS NULL AND p.class_id=s.class_id))
  ) THEN
    RAISE EXCEPTION 'COURSE_SUBJECT_SCOPE_MISMATCH: book intake subject is not mapped to selected course'
      USING ERRCODE='23514';
  END IF;

  RETURN NEW;
END
$book_intake_scope$;

CREATE TRIGGER trg_learning_book_intake_course_scope
  BEFORE INSERT OR UPDATE OF institution_id,course_id,class_id,subject_id
  ON learning_book_intake
  FOR EACH ROW EXECUTE FUNCTION qe_require_learning_book_intake_course_scope();

