-- V31: separate staff identities from parent/student accounts and add task permissions + audit trail.
-- Existing admin identities are copied into the dedicated staff table before their user_account role is normalized.
create table staff_account (
  id bigint generated by default as identity primary key,
  public_id uuid not null unique,
  mobile_e164 varchar(24) not null unique,
  display_name varchar(120) not null,
  role varchar(32) not null check (role in ('ADMIN','MANAGER','MODERATOR','CONTENT_AUTHOR','CONTENT_REVIEWER','PUBLISHER')),
  active boolean not null default true,
  created_by_staff_id bigint references staff_account(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_login_at timestamptz
);

alter table auth_session
  add column if not exists staff_id bigint references staff_account(id) on delete cascade;

create index if not exists idx_auth_session_staff_active
  on auth_session(staff_id, expires_at)
  where staff_id is not null;

-- Permit an authenticated session to belong to a staff identity as well as a parent/user or student.
-- Replace only a legacy guard that required user_id or student_id; keep unrelated constraints intact.
do $staff_auth_session_constraint$ declare
  constraint_row record;
  definition text;
begin
  for constraint_row in
    select conname, pg_get_constraintdef(oid) as definition
    from pg_constraint
    where conrelid='public.auth_session'::regclass and contype='c'
  loop
    definition := constraint_row.definition;
    if definition ilike '%user_id IS NOT NULL%'
       and definition ilike '%student_id IS NOT NULL%'
       and definition ilike '% OR %' then
      execute format('alter table public.auth_session drop constraint %I', constraint_row.conname);
    end if;
  end loop;
end $staff_auth_session_constraint$;

do $staff_auth_session_identity$ begin
  if not exists (
    select 1 from pg_constraint
    where conrelid='public.auth_session'::regclass
      and conname='auth_session_identity_required'
  ) then
    alter table public.auth_session
      add constraint auth_session_identity_required
      check (user_id is not null or student_id is not null or staff_id is not null);
  end if;
end $staff_auth_session_identity$;

create table staff_permission_catalog (
  permission_key varchar(64) primary key,
  display_name varchar(120) not null,
  description varchar(300) not null,
  created_at timestamptz not null default now()
);

insert into staff_permission_catalog(permission_key, display_name, description) values
 ('CONTENT_VIEW','View learning content','Open the curriculum and inspect chapters, topics and lesson content.'),
 ('CONTENT_CREATE','Create content','Create new chapters and micro-topics as drafts.'),
 ('CONTENT_EDIT','Edit content','Change lesson details, teaching blocks and practice questions.'),
 ('CONTENT_SUBMIT','Submit for review','Send authored content to the review queue.'),
 ('CONTENT_REVIEW','Review content','Review content and approve or return practice questions.'),
 ('CONTENT_PUBLISH','Publish content','Publish or unpublish approved content after all checks pass.'),
