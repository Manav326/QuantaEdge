-- V179: immutable, source-owned course-version identities and published-graph mutation guardrails.
-- Existing curriculum rows and learner history are retained. A new content version gets a
-- distinct curriculum_program graph; it never rewrites an earlier released graph.

CREATE TABLE institution_course_identity (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  source_institution_id bigint NOT NULL REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  stable_course_key varchar(160) NOT NULL,
  display_name varchar(200) NOT NULL,
  course_type_code varchar(32) NOT NULL REFERENCES course_type_registry(code) ON DELETE RESTRICT,
  status varchar(16) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','ARCHIVED')),
  created_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  created_by_institution_admin_id bigint REFERENCES institution_admin_account(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(source_institution_id,stable_course_key)
);

ALTER TABLE curriculum_program
  ADD COLUMN course_identity_id bigint REFERENCES institution_course_identity(id) ON DELETE RESTRICT,
  ADD COLUMN content_version_no integer NOT NULL DEFAULT 1 CHECK (content_version_no > 0),
  ADD COLUMN supersedes_program_id bigint REFERENCES curriculum_program(id) ON DELETE RESTRICT;

CREATE UNIQUE INDEX uq_curriculum_program_identity_version
  ON curriculum_program(course_identity_id,content_version_no)
  WHERE course_identity_id IS NOT NULL;
CREATE INDEX idx_curriculum_program_identity_latest
  ON curriculum_program(course_identity_id,content_version_no DESC,id DESC)
  WHERE course_identity_id IS NOT NULL;

-- Historical source ownership can only be inferred when all recorded releases agree on the
-- source institution. Ambiguous/orphaned legacy courses are intentionally not guessed into a
-- new identity; the HRMS/source-owner reconciliation workflow must resolve those separately.
WITH unambiguous_source AS (
  SELECT r.program_id,min(r.source_institution_id) AS source_institution_id
  FROM institution_course_release r
  GROUP BY r.program_id
  HAVING count(DISTINCT r.source_institution_id)=1
)
INSERT INTO institution_course_identity(
  source_institution_id,stable_course_key,display_name,course_type_code
)
SELECT s.source_institution_id,'legacy-program-'||p.id::text,p.display_name,
       coalesce(t.code,'K12')
FROM curriculum_program p
JOIN unambiguous_source s ON s.program_id=p.id
LEFT JOIN course_type_registry t ON t.code=p.course_type_code
WHERE p.code<>'GENERAL'
  AND p.course_identity_id IS NULL
ON CONFLICT(source_institution_id,stable_course_key) DO NOTHING;

UPDATE curriculum_program p
SET course_identity_id=i.id,content_version_no=1,updated_at=now()
FROM institution_course_identity i
WHERE p.course_identity_id IS NULL
  AND i.stable_course_key='legacy-program-'||p.id::text
  AND EXISTS (
    SELECT 1 FROM institution_course_release r
    WHERE r.program_id=p.id AND r.source_institution_id=i.source_institution_id
  );

CREATE TABLE institution_course_version_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_identity_id bigint NOT NULL REFERENCES institution_course_identity(id) ON DELETE RESTRICT,
  source_program_id bigint NOT NULL REFERENCES curriculum_program(id) ON DELETE RESTRICT,
  version_program_id bigint NOT NULL REFERENCES curriculum_program(id) ON DELETE RESTRICT,
  content_version_no integer NOT NULL CHECK (content_version_no > 1),
  event_type varchar(40) NOT NULL CHECK (event_type IN (
    'DRAFT_VERSION_CREATED','DRAFT_VERSION_IMPORTED','VERSION_SUBMITTED_FOR_REVIEW',
    'VERSION_REVIEWED','VERSION_SHAREABLE','VERSION_OFFER_PUBLISHED','VERSION_WITHDRAWN'
  )),
  actor_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  actor_institution_admin_id bigint REFERENCES institution_admin_account(id) ON DELETE SET NULL,
  details jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(details)='object'),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(course_identity_id,version_program_id,event_type)
);
CREATE INDEX idx_institution_course_version_event_identity
  ON institution_course_version_event(course_identity_id,content_version_no,created_at DESC,id DESC);

-- The entity map preserves explicit source-to-version links for reporting and any later, separately
-- approved migration of progress. It is not a learner-history copy table.
CREATE TABLE institution_course_version_entity_map (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_identity_id bigint NOT NULL REFERENCES institution_course_identity(id) ON DELETE RESTRICT,
  source_program_id bigint NOT NULL REFERENCES curriculum_program(id) ON DELETE RESTRICT,
  version_program_id bigint NOT NULL REFERENCES curriculum_program(id) ON DELETE RESTRICT,
  entity_type varchar(32) NOT NULL CHECK (entity_type IN (
    'SUBJECT','CHAPTER','OBJECTIVE','CONCEPT','LESSON','LESSON_BLOCK','QUESTION','QUESTION_OPTION',
    'ASSESSMENT','ASSESSMENT_QUESTION','ASSESSMENT_PACK','ASSESSMENT_PACK_ITEM',
    'RESOURCE_ASSIGNMENT','LEARNING_DOCUMENT','LEARNING_RESOURCE','SOURCE_BOOK','SOURCE_PAGE'
  )),
  source_entity_id bigint NOT NULL,
  version_entity_id bigint NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(version_program_id,entity_type,source_entity_id),
  UNIQUE(version_program_id,entity_type,version_entity_id)
);
CREATE INDEX idx_course_version_entity_source
  ON institution_course_version_entity_map(course_identity_id,entity_type,source_entity_id);

-- Each entity resolver returns the course graph(s) that depend on a row. Legacy subjects may be
-- shared among several course products, so they must be treated as immutable when any mapped
-- released course uses them.
CREATE OR REPLACE FUNCTION qe_course_program_ids_for_subject(p_subject_id bigint)
RETURNS TABLE(program_id bigint)
LANGUAGE sql
STABLE
AS $$
  SELECT s.program_id
  FROM curriculum_subject s
  WHERE s.id=p_subject_id AND s.program_id IS NOT NULL
  UNION
  SELECT cps.program_id
  FROM curriculum_program_subject cps
  WHERE cps.subject_id=p_subject_id
$$;

CREATE OR REPLACE FUNCTION qe_course_program_ids_for_chapter(p_chapter_id bigint)
RETURNS TABLE(program_id bigint)
LANGUAGE sql
STABLE
AS $$
  SELECT DISTINCT ids.program_id
  FROM curriculum_chapter ch
  CROSS JOIN LATERAL qe_course_program_ids_for_subject(ch.subject_id) ids
  WHERE ch.id=p_chapter_id
$$;

CREATE OR REPLACE FUNCTION qe_course_program_ids_for_lesson(p_lesson_id bigint)
RETURNS TABLE(program_id bigint)
LANGUAGE sql
STABLE
AS $$
  SELECT DISTINCT ids.program_id
  FROM lesson l
  CROSS JOIN LATERAL qe_course_program_ids_for_chapter(l.chapter_id) ids
  WHERE l.id=p_lesson_id
$$;

CREATE OR REPLACE FUNCTION qe_course_program_ids_for_objective(p_objective_id bigint)
RETURNS TABLE(program_id bigint)
LANGUAGE sql
STABLE
AS $$
  SELECT DISTINCT ids.program_id
  FROM learning_objective o
  CROSS JOIN LATERAL qe_course_program_ids_for_chapter(o.chapter_id) ids
  WHERE o.id=p_objective_id
$$;

CREATE OR REPLACE FUNCTION qe_course_program_ids_for_concept(p_concept_id bigint)
RETURNS TABLE(program_id bigint)
LANGUAGE sql
STABLE
AS $$
  SELECT DISTINCT ids.program_id
  FROM chapter_concept c
  CROSS JOIN LATERAL qe_course_program_ids_for_chapter(c.chapter_id) ids
  WHERE c.id=p_concept_id
$$;

CREATE OR REPLACE FUNCTION qe_course_program_ids_for_question(p_question_id bigint)
RETURNS TABLE(program_id bigint)
LANGUAGE sql
STABLE
AS $$
  SELECT DISTINCT ids.program_id
  FROM question q
  CROSS JOIN LATERAL (
    SELECT l.program_id FROM qe_course_program_ids_for_lesson(q.lesson_id) l
    UNION
    SELECT o.program_id FROM qe_course_program_ids_for_objective(q.objective_id) o
    UNION
    SELECT c.program_id FROM qe_course_program_ids_for_concept(q.concept_id) c
  ) ids
  WHERE q.id=p_question_id
$$;

CREATE OR REPLACE FUNCTION qe_course_program_ids_for_assessment(p_assessment_id bigint)
RETURNS TABLE(program_id bigint)
LANGUAGE sql
STABLE
AS $$
  SELECT a.course_id
  FROM assessment a
  WHERE a.id=p_assessment_id AND a.course_id IS NOT NULL
$$;

CREATE OR REPLACE FUNCTION qe_course_program_ids_for_resource(p_resource_id bigint)
RETURNS TABLE(program_id bigint)
LANGUAGE sql
STABLE
AS $$
  SELECT DISTINCT ids.program_id
  FROM learning_resource_assignment a
  CROSS JOIN LATERAL qe_course_program_ids_for_chapter(a.chapter_id) ids
  WHERE a.resource_id=p_resource_id
  UNION
  SELECT p.course_id
  FROM course_assessment_pack_resource pr
  JOIN course_assessment_pack p ON p.id=pr.pack_id
  WHERE pr.resource_id=p_resource_id
$$;

CREATE OR REPLACE FUNCTION qe_course_program_ids_for_row(p_table_name text,p_row jsonb)
RETURNS TABLE(program_id bigint)
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
  v_id bigint := NULLIF(p_row->>'id','')::bigint;
  v_parent_id bigint;
  v_subject_id bigint;
  v_program_id bigint;
BEGIN
  CASE p_table_name
    WHEN 'institution_course_identity' THEN
      RETURN QUERY SELECT p.id FROM curriculum_program p WHERE p.course_identity_id=v_id;
    WHEN 'curriculum_program' THEN
      RETURN QUERY SELECT v_id;
    WHEN 'curriculum_subject' THEN
      v_program_id := NULLIF(p_row->>'program_id','')::bigint;
      IF v_program_id IS NOT NULL THEN RETURN QUERY SELECT v_program_id; END IF;
      RETURN QUERY SELECT ids.program_id FROM qe_course_program_ids_for_subject(v_id) ids;
    WHEN 'curriculum_program_subject' THEN
      RETURN QUERY SELECT NULLIF(p_row->>'program_id','')::bigint;
    WHEN 'curriculum_chapter' THEN
      v_subject_id := NULLIF(p_row->>'subject_id','')::bigint;
      RETURN QUERY SELECT ids.program_id FROM qe_course_program_ids_for_subject(v_subject_id) ids;
    WHEN 'learning_objective' THEN
      v_parent_id := NULLIF(p_row->>'chapter_id','')::bigint;
      RETURN QUERY SELECT ids.program_id FROM qe_course_program_ids_for_chapter(v_parent_id) ids;
    WHEN 'chapter_concept' THEN
      v_parent_id := NULLIF(p_row->>'chapter_id','')::bigint;
      RETURN QUERY SELECT ids.program_id FROM qe_course_program_ids_for_chapter(v_parent_id) ids;
    WHEN 'lesson_requirement' THEN
      v_parent_id := NULLIF(p_row->>'chapter_id','')::bigint;
      RETURN QUERY SELECT ids.program_id FROM qe_course_program_ids_for_chapter(v_parent_id) ids;
    WHEN 'chapter_source' THEN
      v_parent_id := NULLIF(p_row->>'chapter_id','')::bigint;
      RETURN QUERY SELECT ids.program_id FROM qe_course_program_ids_for_chapter(v_parent_id) ids;
    WHEN 'learning_resource_artifact_scope' THEN
      v_parent_id := NULLIF(p_row->>'chapter_id','')::bigint;
      RETURN QUERY SELECT ids.program_id FROM qe_course_program_ids_for_chapter(v_parent_id) ids;
    WHEN 'lesson' THEN
      v_parent_id := NULLIF(p_row->>'chapter_id','')::bigint;
      RETURN QUERY SELECT ids.program_id FROM qe_course_program_ids_for_chapter(v_parent_id) ids;
      v_parent_id := NULLIF(p_row->>'objective_id','')::bigint;
      IF v_parent_id IS NOT NULL THEN
        RETURN QUERY SELECT ids.program_id FROM qe_course_program_ids_for_objective(v_parent_id) ids;
      END IF;
    WHEN 'lesson_block' THEN
      v_parent_id := NULLIF(p_row->>'lesson_id','')::bigint;
      RETURN QUERY SELECT ids.program_id FROM qe_course_program_ids_for_lesson(v_parent_id) ids;
    WHEN 'curriculum_program_translation' THEN
      RETURN QUERY SELECT NULLIF(p_row->>'program_id','')::bigint;
    WHEN 'curriculum_subject_translation' THEN
      v_parent_id := NULLIF(p_row->>'subject_id','')::bigint;
      RETURN QUERY SELECT ids.program_id FROM qe_course_program_ids_for_subject(v_parent_id) ids;
    WHEN 'curriculum_chapter_translation' THEN
      v_parent_id := NULLIF(p_row->>'chapter_id','')::bigint;
      RETURN QUERY SELECT ids.program_id FROM qe_course_program_ids_for_chapter(v_parent_id) ids;
    WHEN 'learning_objective_translation' THEN
      v_parent_id := NULLIF(p_row->>'objective_id','')::bigint;
      RETURN QUERY SELECT ids.program_id FROM qe_course_program_ids_for_objective(v_parent_id) ids;
    WHEN 'lesson_translation' THEN
      v_parent_id := NULLIF(p_row->>'lesson_id','')::bigint;
      RETURN QUERY SELECT ids.program_id FROM qe_course_program_ids_for_lesson(v_parent_id) ids;
    WHEN 'lesson_block_translation' THEN
      SELECT l.id INTO v_parent_id
      FROM lesson_block b JOIN lesson l ON l.id=b.lesson_id
      WHERE b.id=NULLIF(p_row->>'block_id','')::bigint;
      RETURN QUERY SELECT ids.program_id FROM qe_course_program_ids_for_lesson(v_parent_id) ids;
    WHEN 'question' THEN
      v_parent_id := NULLIF(p_row->>'lesson_id','')::bigint;
      IF v_parent_id IS NOT NULL THEN
        RETURN QUERY SELECT ids.program_id FROM qe_course_program_ids_for_lesson(v_parent_id) ids;
      END IF;
      v_parent_id := NULLIF(p_row->>'objective_id','')::bigint;
      IF v_parent_id IS NOT NULL THEN
        RETURN QUERY SELECT ids.program_id FROM qe_course_program_ids_for_objective(v_parent_id) ids;
      END IF;
      v_parent_id := NULLIF(p_row->>'concept_id','')::bigint;
      IF v_parent_id IS NOT NULL THEN
        RETURN QUERY SELECT ids.program_id FROM qe_course_program_ids_for_concept(v_parent_id) ids;
      END IF;
    WHEN 'question_option' THEN
      v_parent_id := NULLIF(p_row->>'question_id','')::bigint;
      RETURN QUERY SELECT ids.program_id FROM qe_course_program_ids_for_question(v_parent_id) ids;
    WHEN 'question_translation' THEN
      v_parent_id := NULLIF(p_row->>'question_id','')::bigint;
      RETURN QUERY SELECT ids.program_id FROM qe_course_program_ids_for_question(v_parent_id) ids;
    WHEN 'assessment' THEN
      RETURN QUERY SELECT NULLIF(p_row->>'course_id','')::bigint;
    WHEN 'assessment_question' THEN
      v_parent_id := NULLIF(p_row->>'assessment_id','')::bigint;
      RETURN QUERY SELECT ids.program_id FROM qe_course_program_ids_for_assessment(v_parent_id) ids;
    WHEN 'assessment_translation' THEN
      v_parent_id := NULLIF(p_row->>'assessment_id','')::bigint;
      RETURN QUERY SELECT ids.program_id FROM qe_course_program_ids_for_assessment(v_parent_id) ids;
    WHEN 'assessment_question_translation' THEN
      SELECT aq.assessment_id INTO v_parent_id
      FROM assessment_question aq
      WHERE aq.id=NULLIF(p_row->>'assessment_question_id','')::bigint;
      RETURN QUERY SELECT ids.program_id FROM qe_course_program_ids_for_assessment(v_parent_id) ids;
    WHEN 'course_assessment_pack' THEN
      RETURN QUERY SELECT NULLIF(p_row->>'course_id','')::bigint;
    WHEN 'course_assessment_pack_item' THEN
      v_parent_id := NULLIF(p_row->>'pack_id','')::bigint;
      SELECT p.course_id INTO v_program_id
      FROM course_assessment_pack p WHERE p.id=v_parent_id;
      RETURN QUERY SELECT v_program_id WHERE v_program_id IS NOT NULL;
    WHEN 'course_assessment_pack_resource' THEN
      v_parent_id := NULLIF(p_row->>'pack_id','')::bigint;
      SELECT p.course_id INTO v_program_id
      FROM course_assessment_pack p WHERE p.id=v_parent_id;
      RETURN QUERY SELECT v_program_id WHERE v_program_id IS NOT NULL;
    WHEN 'learning_resource_assignment' THEN
      v_parent_id := NULLIF(p_row->>'chapter_id','')::bigint;
      RETURN QUERY SELECT ids.program_id FROM qe_course_program_ids_for_chapter(v_parent_id) ids;
    WHEN 'learning_resource' THEN
      RETURN QUERY SELECT ids.program_id FROM qe_course_program_ids_for_resource(v_id) ids;
    WHEN 'learning_document' THEN
      RETURN QUERY
        SELECT a.course_id FROM learning_document_course_assignment a
        WHERE a.learning_document_id=v_id
        UNION
        SELECT ids.program_id FROM learning_resource r
        CROSS JOIN LATERAL qe_course_program_ids_for_resource(r.id) ids
        WHERE r.learning_document_id=v_id;
    WHEN 'learning_document_course_assignment' THEN
      RETURN QUERY SELECT NULLIF(p_row->>'course_id','')::bigint;
    WHEN 'content_asset' THEN
      RETURN QUERY
        SELECT ids.program_id
        FROM lesson_block b
        CROSS JOIN LATERAL qe_course_program_ids_for_lesson(b.lesson_id) ids
        WHERE b.asset_id=v_id;
    WHEN 'textbook_source_book' THEN
      v_program_id := NULLIF(p_row->>'program_id','')::bigint;
      IF v_program_id IS NOT NULL THEN RETURN QUERY SELECT v_program_id; END IF;
      v_subject_id := NULLIF(p_row->>'subject_id','')::bigint;
      RETURN QUERY SELECT ids.program_id FROM qe_course_program_ids_for_subject(v_subject_id) ids;
    WHEN 'textbook_extracted_page' THEN
      SELECT b.program_id,b.subject_id INTO v_program_id,v_subject_id
      FROM textbook_source_book b
      WHERE b.id=NULLIF(p_row->>'source_book_id','')::bigint;
      IF v_program_id IS NOT NULL THEN RETURN QUERY SELECT v_program_id; END IF;
      RETURN QUERY SELECT ids.program_id FROM qe_course_program_ids_for_subject(v_subject_id) ids;
    ELSE
      RETURN;
  END CASE;
END
$$;

CREATE OR REPLACE FUNCTION reject_published_course_graph_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_payloads jsonb;
  v_row jsonb;
  v_program_id bigint;
BEGIN
  IF TG_OP='UPDATE' THEN
    v_payloads := jsonb_build_array(to_jsonb(OLD),to_jsonb(NEW));
  ELSIF TG_OP='DELETE' THEN
    v_payloads := jsonb_build_array(to_jsonb(OLD));
  ELSE
    v_payloads := jsonb_build_array(to_jsonb(NEW));
  END IF;

  FOR v_row IN SELECT value FROM jsonb_array_elements(v_payloads) AS rows(value)
  LOOP
    FOR v_program_id IN
      SELECT DISTINCT ids.program_id
      FROM qe_course_program_ids_for_row(TG_TABLE_NAME,v_row) ids
      WHERE ids.program_id IS NOT NULL
    LOOP
      IF EXISTS (
        SELECT 1 FROM institution_course_release r
        WHERE r.program_id=v_program_id
          AND r.release_state IN ('IN_QUALITY_REVIEW','QUALITY_APPROVED','SHAREABLE','LEGACY_MIGRATED','WITHDRAWN')
      ) OR EXISTS (
        SELECT 1 FROM institution_marketplace_offer o
        WHERE o.course_id=v_program_id
          AND (o.status='PUBLISHED' OR o.hrms_published_by_staff_id IS NOT NULL)
      ) THEN
        RAISE EXCEPTION 'COURSE_VERSION_IMMUTABLE: content in course version % has entered the release/publication workflow. Create a new draft version; the existing graph cannot be edited in place.',v_program_id
          USING ERRCODE='23514';
      END IF;
    END LOOP;
  END LOOP;

  IF TG_OP='DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END
$$;

-- Defense in depth. API-level permission checks provide a friendly 409 response; these triggers
-- protect released content from alternative controllers, old clients, scripts and direct SQL.
DO $course_graph_immutability$
DECLARE v_table text;
BEGIN
  FOREACH v_table IN ARRAY ARRAY[
    'institution_course_identity',
    'curriculum_program',
    'curriculum_subject',
    'curriculum_program_subject',
    'curriculum_chapter',
    'learning_objective',
    'chapter_concept',
    'lesson_requirement',
    'chapter_source',
    'lesson',
    'lesson_block',
    'question',
    'question_option',
    'curriculum_program_translation',
    'curriculum_subject_translation',
    'curriculum_chapter_translation',
    'learning_objective_translation',
    'lesson_translation',
    'lesson_block_translation',
    'question_translation',
    'assessment',
    'assessment_question',
    'assessment_translation',
    'assessment_question_translation',
    'course_assessment_pack',
    'course_assessment_pack_item',
    'course_assessment_pack_resource',
    'learning_resource',
    'learning_resource_assignment',
    'learning_resource_artifact_scope',
    'learning_document',
    'learning_document_course_assignment',
    'content_asset',
    'textbook_source_book',
    'textbook_extracted_page'
  ]
  LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS trg_reject_published_course_graph_mutation ON public.%I',v_table);
    EXECUTE format(
      'CREATE TRIGGER trg_reject_published_course_graph_mutation BEFORE INSERT OR UPDATE OR DELETE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.reject_published_course_graph_mutation()',
      v_table
    );
  END LOOP;
END
$course_graph_immutability$;

COMMENT ON TABLE institution_course_identity IS
  'Stable logical course identity owned by a single source institution. Each curriculum_program row is one immutable content version of this identity.';
COMMENT ON COLUMN curriculum_program.course_identity_id IS
  'Stable source-owned course family. Distinct versions use distinct curriculum_program/content graphs while retaining this identity.';
COMMENT ON COLUMN curriculum_program.content_version_no IS
  'Monotonic content version within course_identity; it is separate from the release workflow version.';
COMMENT ON COLUMN curriculum_program.supersedes_program_id IS
  'Previous content graph this version was forked from; learner history on the previous graph is never re-parented.';
COMMENT ON FUNCTION reject_published_course_graph_mutation() IS
  'Blocks direct edits to any course content graph already submitted for release review, made shareable, historically migrated as published, or used by an HRMS-published offer. New drafts use distinct curriculum_program and child IDs.';

