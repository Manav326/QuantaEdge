-- HRMS foundation: organisational employee records are deliberately separate from staff_account.
-- staff_account represents access to the platform administration workspace; hr_employee represents employment.
create sequence hr_employee_number_seq start 1;

create table hr_organization (
  id bigint generated by default as identity primary key,
  public_id uuid not null unique,
  name varchar(160) not null,
  legal_name varchar(200),
  timezone varchar(80) not null default 'Asia/Kolkata',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (name)
);

insert into hr_organization(public_id,name,legal_name)
values (gen_random_uuid(),'QuantaEdge','QuantaEdge')
on conflict(name) do nothing;

create table hr_department (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references hr_organization(id),
  parent_department_id bigint references hr_department(id),
  code varchar(32) not null,
  name varchar(120) not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(organization_id,code),
  unique(organization_id,name),
  check(parent_department_id is null or parent_department_id<>id)
);

create table hr_designation (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references hr_organization(id),
  code varchar(32) not null,
  name varchar(120) not null,
  category varchar(24) not null default 'OTHER'
    check(category in ('ACADEMIC','ADMINISTRATIVE','OPERATIONS','LEADERSHIP','OTHER')),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(organization_id,code),
  unique(organization_id,name)
);

create table hr_employment_type (
  code varchar(32) primary key,
  display_name varchar(80) not null,
  active boolean not null default true
);
insert into hr_employment_type(code,display_name) values
 ('FULL_TIME','Full-time'),('PART_TIME','Part-time'),('FIXED_TERM','Fixed-term'),
 ('VISITING_FACULTY','Visiting faculty'),('DAILY_WAGE','Daily wage'),
 ('INTERN','Intern / trainee'),('CONSULTANT','Consultant / service provider')
on conflict(code) do nothing;

create table hr_employee (
  id bigint generated by default as identity primary key,
  public_id uuid not null unique,
  employee_number varchar(32) not null unique,
  organization_id bigint not null references hr_organization(id),
  department_id bigint references hr_department(id),
  designation_id bigint references hr_designation(id),
  employment_type_code varchar(32) not null references hr_employment_type(code),
  manager_employee_id bigint references hr_employee(id),
  linked_staff_account_id bigint unique references staff_account(id) on delete set null,
  display_name varchar(120) not null,
  email varchar(254),
  phone_e164 varchar(24),
  joining_date date not null,
  probation_end_date date,
  employment_status varchar(24) not null default 'ACTIVE'
    check(employment_status in ('DRAFT','ACTIVE','ON_LEAVE','NOTICE_PERIOD','SEPARATED','INACTIVE')),
  exit_date date,
  notes varchar(1000),
  created_by_staff_id bigint references staff_account(id) on delete set null,
  updated_by_staff_id bigint references staff_account(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check(manager_employee_id is null or manager_employee_id<>id),
  check(exit_date is null or exit_date>=joining_date)
);

create index idx_hr_employee_org_status on hr_employee(organization_id,employment_status);
create index idx_hr_employee_department on hr_employee(department_id,display_name);
create index idx_hr_employee_manager on hr_employee(manager_employee_id);
create index idx_hr_employee_name_lower on hr_employee(lower(display_name));

create table hr_employee_history (
  id bigint generated by default as identity primary key,
  employee_id bigint not null references hr_employee(id) on delete restrict,
  changed_by_staff_id bigint references staff_account(id) on delete set null,
  change_type varchar(40) not null,
  effective_date date not null,
  before_state jsonb,
  after_state jsonb not null,
  reason varchar(500),
  created_at timestamptz not null default now()
);
create index idx_hr_employee_history_employee on hr_employee_history(employee_id,effective_date desc,id desc);

insert into staff_permission_catalog(permission_key,display_name,description) values
 ('HR_EMPLOYEE_VIEW','View employee records','View permitted organisational structure and employee directory information.'),
 ('HR_EMPLOYEE_MANAGE','Manage employee records','Create and update employee records, departments and designations.')
on conflict(permission_key) do update
set display_name=excluded.display_name,description=excluded.description;
