-- V131: every login identity belongs to one or more institution tenants.
-- Existing institutional learner/guardian relationships are preserved. Remaining pre-tenant
-- global accounts are explicitly assigned to QUANTA-EDGE as legacy users; future accounts are
-- enrolled only into the institution selected during signup/onboarding.
CREATE TABLE institution_user_membership (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institution_id bigint NOT NULL REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  user_id bigint NOT NULL REFERENCES user_account(id) ON DELETE RESTRICT,
  status varchar(12) NOT NULL DEFAULT 'ACTIVE'
    CHECK (status IN ('ACTIVE','SUSPENDED','LEFT')),
  joined_at timestamptz NOT NULL DEFAULT now(),
  left_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(institution_id,user_id),
  CHECK ((status='LEFT' AND left_at IS NOT NULL) OR (status<>'LEFT' AND left_at IS NULL))
);

CREATE INDEX idx_institution_user_membership_user
  ON institution_user_membership(user_id,status,institution_id);
CREATE INDEX idx_institution_user_membership_roster
  ON institution_user_membership(institution_id,status,joined_at DESC,id DESC);

CREATE TABLE institution_user_membership_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institution_id bigint NOT NULL REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  membership_id bigint NOT NULL REFERENCES institution_user_membership(id) ON DELETE RESTRICT,
  user_id bigint NOT NULL REFERENCES user_account(id) ON DELETE RESTRICT,
  event_type varchar(32) NOT NULL CHECK (event_type IN (
    'USER_MEMBERSHIP_CREATED','USER_MEMBERSHIP_SUSPENDED','USER_MEMBERSHIP_LEFT',
    'USER_MEMBERSHIP_REACTIVATED','LEGACY_USER_MAPPED'
  )),
  actor_user_id bigint REFERENCES user_account(id) ON DELETE SET NULL,
  details jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(details)='object'),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_institution_user_membership_event_tenant_time
  ON institution_user_membership_event(institution_id,created_at DESC,id DESC);
CREATE INDEX idx_institution_user_membership_event_user_time
  ON institution_user_membership_event(user_id,created_at DESC,id DESC);

DO $require_qe$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM institution_tenant
    WHERE tenant_code='QUANTA-EDGE' AND status='ACTIVE'
  ) THEN
    RAISE EXCEPTION 'V131 requires the active QUANTA-EDGE legacy destination tenant.';
  END IF;
END
$require_qe$;

-- Derive accounts' tenant memberships from their pre-existing learner/guardian relationships.
-- If the old account is genuinely global and has no tenant provenance, map it to QuantaEdge.
WITH qe AS (
  SELECT id FROM institution_tenant WHERE tenant_code='QUANTA-EDGE' AND status='ACTIVE'
),
relationship_scopes AS (
  SELECT st.user_account_id AS user_id,m.institution_id,m.status AS relation_status
  FROM student st
  JOIN institution_membership m ON m.student_id=st.id
  WHERE st.user_account_id IS NOT NULL
  UNION ALL
  SELECT gs.guardian_user_id AS user_id,m.institution_id,m.status AS relation_status
  FROM guardian_student gs
  JOIN institution_membership m ON m.student_id=gs.student_id
  WHERE gs.guardian_user_id IS NOT NULL
),
scoped_users AS (
  SELECT user_id,institution_id,
    CASE max(CASE relation_status WHEN 'ACTIVE' THEN 3 WHEN 'SUSPENDED' THEN 2 ELSE 1 END)
      WHEN 3 THEN 'ACTIVE' WHEN 2 THEN 'SUSPENDED' ELSE 'LEFT' END AS membership_status
  FROM relationship_scopes
  GROUP BY user_id,institution_id
),
all_legacy_scopes AS (
  SELECT user_id,institution_id,membership_status FROM scoped_users
  UNION ALL
  SELECT u.id,qe.id,CASE WHEN u.active THEN 'ACTIVE' ELSE 'SUSPENDED' END
  FROM user_account u CROSS JOIN qe
  WHERE NOT EXISTS (SELECT 1 FROM scoped_users ss WHERE ss.user_id=u.id)
),
inserted AS (
  INSERT INTO institution_user_membership(
    institution_id,user_id,status,joined_at,left_at,created_at,updated_at
  )
  SELECT institution_id,user_id,membership_status,now(),
    CASE WHEN membership_status='LEFT' THEN now() ELSE NULL END,now(),now()
  FROM all_legacy_scopes
  ON CONFLICT(institution_id,user_id) DO NOTHING
  RETURNING id,institution_id,user_id
)
INSERT INTO institution_user_membership_event(
  institution_id,membership_id,user_id,event_type,details
)
SELECT institution_id,id,user_id,'LEGACY_USER_MAPPED',
       jsonb_build_object('source','LEGACY_GLOBAL_OR_EXISTING_RELATIONSHIP','migration','V131')
FROM inserted;

