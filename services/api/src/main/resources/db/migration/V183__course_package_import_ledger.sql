-- V183: idempotent ledger for nested source-course package imports.
-- Every imported graph and its reservation commit atomically; failed imports leave no partial ledger.
CREATE TABLE institution_course_package_import (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_institution_id bigint NOT NULL REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  package_id varchar(120) NOT NULL CHECK (package_id ~ '^[a-z0-9][a-z0-9._-]{2,119}$'),
  package_version varchar(40) NOT NULL CHECK (package_version ~ '^[A-Za-z0-9][A-Za-z0-9._+-]{0,39}$'),
  package_sha256 char(64) NOT NULL CHECK (package_sha256 ~ '^[0-9a-f]{64}$'),
  state varchar(16) NOT NULL DEFAULT 'IMPORTING' CHECK (state IN ('IMPORTING','IMPORTED')),
  course_id bigint REFERENCES curriculum_program(id) ON DELETE RESTRICT,
  release_id bigint REFERENCES institution_course_release(id) ON DELETE RESTRICT,
  imported_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  editorial_metadata jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(editorial_metadata)='object'),
  import_summary jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(import_summary)='object'),
  created_at timestamptz NOT NULL DEFAULT now(),
  imported_at timestamptz,
  UNIQUE(source_institution_id,package_id,package_version),
  CHECK (
    (state='IMPORTING' AND course_id IS NULL AND release_id IS NULL AND imported_at IS NULL)
    OR (state='IMPORTED' AND course_id IS NOT NULL AND release_id IS NOT NULL AND imported_at IS NOT NULL)
  )
);
CREATE INDEX idx_course_package_import_institution
  ON institution_course_package_import(source_institution_id,created_at DESC,id DESC);

INSERT INTO app_metadata(key,value)
