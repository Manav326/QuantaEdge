-- Effective-dated academic teaching assignments, separate from employee identity and CMS permissions.
-- No employee, class assignment or academic-period data is seeded.
create table hr_academic_period (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references hr_organization(id) on delete restrict,
  period_code varchar(40) not null,
  name varchar(120) not null,
  start_date date not null,
  end_date date not null,
  status varchar(16) not null default 'PLANNED'
    check (status in ('PLANNED','ACTIVE','CLOSED','CANCELLED')),
  created_by_staff_id bigint references staff_account(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (end_date >= start_date),
  unique(organization_id,period_code),
  unique(organization_id,name)
);

create table hr_teaching_assignment (
  id bigint generated by default as identity primary key,
  public_id uuid not null unique default gen_random_uuid(),
  organization_id bigint not null references hr_organization(id) on delete restrict,
  employee_id bigint not null references hr_employee(id) on delete restrict,
  subject_id bigint not null references curriculum_subject(id) on delete restrict,
  academic_period_id bigint not null references hr_academic_period(id) on delete restrict,
  effective_start date not null,
  effective_end date not null,
  status varchar(20) not null default 'PENDING_APPROVAL'
    check (status in ('PENDING_APPROVAL','APPROVED','REJECTED','CANCELLED','ENDED')),
  replaces_assignment_id bigint references hr_teaching_assignment(id) on delete restrict,
  assignment_note varchar(1000),
  decision_reason varchar(1000),
  created_by_staff_id bigint references staff_account(id) on delete set null,
  approved_by_staff_id bigint references staff_account(id) on delete set null,
  approved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (effective_end >= effective_start)
);
create index idx_hr_teaching_assignment_subject_dates
  on hr_teaching_assignment(organization_id,subject_id,academic_period_id,effective_start,effective_end,status);
create index idx_hr_teaching_assignment_employee_dates
  on hr_teaching_assignment(employee_id,effective_start desc,effective_end desc);
create unique index uq_hr_teaching_assignment_single_approval
  on hr_teaching_assignment(replaces_assignment_id)
  where replaces_assignment_id is not null and status='APPROVED';

create table hr_teaching_assignment_history (
  id bigint generated by default as identity primary key,
  assignment_id bigint not null references hr_teaching_assignment(id) on delete restrict,
  event_type varchar(40) not null,
  actor_staff_id bigint references staff_account(id) on delete set null,
  effective_date date not null,
  reason varchar(1000),
  before_state jsonb,
  after_state jsonb not null,
  created_at timestamptz not null default now()
);
create index idx_hr_teaching_assignment_history
  on hr_teaching_assignment_history(assignment_id,created_at desc,id desc);

insert into staff_permission_catalog(permission_key,display_name,description) values
 ('HR_ACADEMIC_ASSIGNMENT_VIEW','View teaching assignments','View employee teaching assignments and academic periods.'),
 ('HR_ACADEMIC_ASSIGNMENT_MANAGE','Manage teaching assignments','Create and update effective-dated teaching assignment proposals.'),
 ('HR_ACADEMIC_ASSIGNMENT_APPROVE','Approve teaching assignments','Approve or reject teaching assignments and replacement transitions.'),
 ('TEACHING_ASSIGNMENT_VIEW','Consume approved teaching assignments','Read only approved teaching assignments for authorised academic workflows.')
on conflict(permission_key) do update set display_name=excluded.display_name,description=excluded.description;
