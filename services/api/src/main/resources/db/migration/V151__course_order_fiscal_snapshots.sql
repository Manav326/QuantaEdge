-- V151: locked course-order fiscal snapshots and purchaser billing identity.
-- No coupons, tax rates, customer records, invoices or payouts are seeded.
ALTER TABLE course_payment_order
  ADD COLUMN listed_price_paise bigint,
  ADD COLUMN discount_amount_paise bigint NOT NULL DEFAULT 0 CHECK (discount_amount_paise >= 0),
  ADD COLUMN discount_reference varchar(100),
  ADD COLUMN discount_snapshot jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(discount_snapshot)='object'),
  ADD COLUMN tax_profile_id bigint REFERENCES course_tax_profile(id) ON DELETE RESTRICT,
  ADD COLUMN taxable_value_paise bigint CHECK (taxable_value_paise IS NULL OR taxable_value_paise >= 0),
  ADD COLUMN output_tax_paise bigint CHECK (output_tax_paise IS NULL OR output_tax_paise >= 0),
  ADD COLUMN tax_calculation_snapshot jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(tax_calculation_snapshot)='object'),
  ADD COLUMN buyer_snapshot jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(buyer_snapshot)='object'),
  ADD COLUMN captured_amount_paise bigint CHECK (captured_amount_paise IS NULL OR captured_amount_paise >= 0),
  ADD COLUMN captured_at timestamptz,
  ADD COLUMN fiscal_document_id bigint REFERENCES fiscal_document(id) ON DELETE RESTRICT;

UPDATE course_payment_order
SET listed_price_paise=offer_price_paise
WHERE listed_price_paise IS NULL;

UPDATE course_payment_order
SET captured_amount_paise=offer_price_paise,
    captured_at=coalesce(verified_at,updated_at,created_at)
WHERE status='VERIFIED' AND provider_payment_id IS NOT NULL AND captured_amount_paise IS NULL;

ALTER TABLE course_payment_order
  ALTER COLUMN listed_price_paise SET NOT NULL,
  ADD CONSTRAINT ck_course_order_discount_not_over_list
    CHECK (discount_amount_paise <= listed_price_paise),
  ADD CONSTRAINT ck_course_order_capture_timestamp
    CHECK (captured_amount_paise IS NULL OR captured_at IS NOT NULL);

CREATE UNIQUE INDEX uq_course_payment_order_fiscal_document
  ON course_payment_order(fiscal_document_id) WHERE fiscal_document_id IS NOT NULL;
CREATE INDEX idx_course_payment_order_tax_profile
  ON course_payment_order(tax_profile_id,created_at DESC) WHERE tax_profile_id IS NOT NULL;

CREATE TABLE billing_customer_profile (
  user_account_id bigint PRIMARY KEY REFERENCES user_account(id) ON DELETE RESTRICT,
  billing_type varchar(16) NOT NULL DEFAULT 'INDIVIDUAL'
    CHECK (billing_type IN ('INDIVIDUAL','BUSINESS')),
  legal_name varchar(240) NOT NULL CHECK (length(btrim(legal_name))>0),
  gstin varchar(15) CHECK (gstin IS NULL OR gstin ~ '^[0-9A-Z]{15}$'),
  gst_state_code char(2) CHECK (gst_state_code IS NULL OR gst_state_code ~ '^[0-9]{2}$'),
  billing_address jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(billing_address)='object'),
  contact_email varchar(320),
  contact_phone varchar(40),
  version bigint NOT NULL DEFAULT 1 CHECK (version>0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (gstin IS NULL OR (gst_state_code IS NOT NULL AND left(gstin,2)=gst_state_code))
);
CREATE INDEX idx_billing_customer_profile_gstin ON billing_customer_profile(gstin) WHERE gstin IS NOT NULL;

CREATE TABLE billing_customer_profile_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_account_id bigint NOT NULL REFERENCES user_account(id) ON DELETE RESTRICT,
  event_type varchar(24) NOT NULL CHECK (event_type IN ('CREATED','UPDATED')),
  profile_version bigint NOT NULL CHECK (profile_version>0),
  actor_user_account_id bigint NOT NULL REFERENCES user_account(id) ON DELETE RESTRICT,
  changed_fields jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(changed_fields)='array'),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(user_account_id,profile_version)
);
CREATE INDEX idx_billing_customer_profile_event_history
  ON billing_customer_profile_event(user_account_id,created_at DESC,id DESC);

CREATE OR REPLACE FUNCTION reject_billing_customer_profile_event_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'Billing profile history is append-only'
    USING ERRCODE='23514';
END;
$$;
CREATE TRIGGER trg_billing_customer_profile_event_immutable
BEFORE UPDATE OR DELETE ON billing_customer_profile_event
FOR EACH ROW EXECUTE FUNCTION reject_billing_customer_profile_event_mutation();

CREATE OR REPLACE FUNCTION lock_verified_course_order_financial_snapshot()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.status='VERIFIED' AND ROW(
      NEW.listed_price_paise,NEW.discount_amount_paise,NEW.discount_reference,NEW.discount_snapshot,
      NEW.tax_profile_id,NEW.taxable_value_paise,NEW.output_tax_paise,NEW.tax_calculation_snapshot,
      NEW.buyer_snapshot,NEW.captured_amount_paise,NEW.captured_at
    ) IS DISTINCT FROM ROW(
      OLD.listed_price_paise,OLD.discount_amount_paise,OLD.discount_reference,OLD.discount_snapshot,
      OLD.tax_profile_id,OLD.taxable_value_paise,OLD.output_tax_paise,OLD.tax_calculation_snapshot,
      OLD.buyer_snapshot,OLD.captured_amount_paise,OLD.captured_at
    ) THEN
    RAISE EXCEPTION 'Verified course-order financial snapshots are immutable; use a fiscal adjustment'
      USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER trg_course_order_financial_snapshot_immutable
BEFORE UPDATE ON course_payment_order
FOR EACH ROW EXECUTE FUNCTION lock_verified_course_order_financial_snapshot();

