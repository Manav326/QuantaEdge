-- Payroll foundation: all compensation and payroll results are explicit, versioned and auditable.
-- No salary, payroll, payment or employee data is seeded.
create table hr_salary_component (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references hr_organization(id) on delete restrict,
  code varchar(32) not null,
  name varchar(120) not null,
  component_type varchar(16) not null check (component_type in ('EARNING','DEDUCTION')),
  active boolean not null default true,
  created_by_staff_id bigint references staff_account(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(organization_id,code),
  unique(organization_id,name)
);

create table hr_employee_salary_component (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references hr_organization(id) on delete restrict,
  employee_id bigint not null references hr_employee(id) on delete restrict,
  component_id bigint not null references hr_salary_component(id) on delete restrict,
  monthly_amount numeric(12,2) not null check (monthly_amount > 0 and monthly_amount <= 9999999999.99),
  currency char(3) not null check (currency ~ '^[A-Z]{3}$'),
  effective_from date not null,
  effective_to date,
  reason varchar(1000) not null check (length(trim(reason)) > 0),
  created_by_staff_id bigint references staff_account(id) on delete set null,
  created_at timestamptz not null default now(),
  check (effective_to is null or effective_to >= effective_from)
);
create index idx_hr_salary_component_employee_dates
  on hr_employee_salary_component(employee_id,effective_from,effective_to);
create index idx_hr_salary_component_org_dates
  on hr_employee_salary_component(organization_id,effective_from,effective_to);

create table hr_payroll_period (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references hr_organization(id) on delete restrict,
  period_name varchar(100) not null,
  start_date date not null,
  end_date date not null,
  status varchar(16) not null default 'OPEN'
    check (status in ('OPEN','CALCULATED','SUBMITTED','APPROVED','PAID','CANCELLED')),
  created_by_staff_id bigint references staff_account(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (end_date >= start_date),
  unique(organization_id,start_date,end_date),
  unique(organization_id,period_name)
);

create table hr_payroll_run (
  id bigint generated by default as identity primary key,
  period_id bigint not null references hr_payroll_period(id) on delete restrict,
  version_no integer not null check (version_no > 0),
  status varchar(16) not null default 'CALCULATED'
    check (status in ('CALCULATED','SUBMITTED','APPROVED','PAID','VOID')),
  currency char(3) not null check (currency ~ '^[A-Z]{3}$'),
  total_gross numeric(14,2) not null default 0 check (total_gross >= 0),
  total_deductions numeric(14,2) not null default 0 check (total_deductions >= 0),
  total_net numeric(14,2) not null default 0 check (total_net >= 0),
  calculation_policy_version varchar(40) not null,
  created_by_staff_id bigint references staff_account(id) on delete set null,
  submitted_by_staff_id bigint references staff_account(id) on delete set null,
  submitted_at timestamptz,
  approved_by_staff_id bigint references staff_account(id) on delete set null,
  approved_at timestamptz,
  created_at timestamptz not null default now(),
  unique(period_id,version_no),
  check (total_net = total_gross - total_deductions)
);
create index idx_hr_payroll_run_period on hr_payroll_run(period_id,version_no desc);

create table hr_payroll_line (
  id bigint generated by default as identity primary key,
  run_id bigint not null references hr_payroll_run(id) on delete restrict,
  employee_id bigint not null references hr_employee(id) on delete restrict,
  employee_number_snapshot varchar(32) not null,
  employee_name_snapshot varchar(120) not null,
  component_snapshot jsonb not null,
  gross_amount numeric(12,2) not null check (gross_amount >= 0),
  deduction_amount numeric(12,2) not null check (deduction_amount >= 0),
  net_amount numeric(12,2) not null check (net_amount >= 0),
  currency char(3) not null check (currency ~ '^[A-Z]{3}$'),
  created_at timestamptz not null default now(),
  unique(run_id,employee_id),
  check (net_amount = gross_amount - deduction_amount)
);
create index idx_hr_payroll_line_employee on hr_payroll_line(employee_id,run_id);

create table hr_payroll_event (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references hr_organization(id) on delete restrict,
  period_id bigint references hr_payroll_period(id) on delete restrict,
  run_id bigint references hr_payroll_run(id) on delete restrict,
  event_type varchar(40) not null,
  actor_staff_id bigint references staff_account(id) on delete set null,
  reason varchar(1000),
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index idx_hr_payroll_event_period on hr_payroll_event(period_id,created_at desc);

create table hr_payroll_payment (
  id bigint generated by default as identity primary key,
  run_id bigint not null references hr_payroll_run(id) on delete restrict,
  employee_id bigint not null references hr_employee(id) on delete restrict,
  amount numeric(12,2) not null check (amount >= 0),
  currency char(3) not null check (currency ~ '^[A-Z]{3}$'),
  payment_status varchar(16) not null check (payment_status in ('PENDING','SETTLED','FAILED','REVERSED')),
  provider_reference varchar(160) not null,
  note varchar(1000),
  reconciled_by_staff_id bigint references staff_account(id) on delete set null,
  settled_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(provider_reference)
);
create index idx_hr_payroll_payment_run on hr_payroll_payment(run_id,employee_id,created_at desc);

