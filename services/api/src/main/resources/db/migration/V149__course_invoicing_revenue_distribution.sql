CREATE TABLE revenue_share_policy_recipient (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  policy_id bigint NOT NULL REFERENCES revenue_share_policy(id) ON DELETE RESTRICT,
  institution_id bigint NOT NULL REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  calculation_type varchar(12) NOT NULL CHECK (calculation_type IN ('PERCENTAGE','FLAT')),
  percentage_basis_points integer,
  flat_amount_paise bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(policy_id,institution_id),
  UNIQUE(id,policy_id,institution_id),
  CHECK (
    (calculation_type='PERCENTAGE' AND percentage_basis_points BETWEEN 1 AND 10000
      AND flat_amount_paise IS NULL)
    OR
    (calculation_type='FLAT' AND percentage_basis_points IS NULL
      AND flat_amount_paise > 0)
  )
);
CREATE INDEX idx_revenue_share_recipient_institution ON revenue_share_policy_recipient(institution_id,policy_id);

CREATE TABLE revenue_share_allocation (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  course_payment_order_id bigint NOT NULL REFERENCES course_payment_order(id) ON DELETE RESTRICT,
  policy_id bigint NOT NULL REFERENCES revenue_share_policy(id) ON DELETE RESTRICT,
  policy_recipient_id bigint NOT NULL REFERENCES revenue_share_policy_recipient(id) ON DELETE RESTRICT,
  institution_id bigint NOT NULL REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  currency char(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
  actual_paid_paise bigint NOT NULL CHECK (actual_paid_paise >= 0),
  output_tax_paise bigint NOT NULL CHECK (output_tax_paise >= 0),
  distributable_pool_paise bigint NOT NULL CHECK (distributable_pool_paise >= 0),
  total_institution_allocated_paise bigint NOT NULL CHECK (total_institution_allocated_paise >= 0),
  allocated_amount_paise bigint NOT NULL CHECK (allocated_amount_paise >= 0),
  platform_remainder_paise bigint NOT NULL CHECK (platform_remainder_paise >= 0),
  calculation_snapshot jsonb NOT NULL CHECK (jsonb_typeof(calculation_snapshot)='object'),
  idempotency_key varchar(180) NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(course_payment_order_id,institution_id),
  FOREIGN KEY (policy_recipient_id,policy_id,institution_id)
    REFERENCES revenue_share_policy_recipient(id,policy_id,institution_id) ON DELETE RESTRICT,
  CHECK (output_tax_paise <= actual_paid_paise),
  CHECK (distributable_pool_paise = actual_paid_paise - output_tax_paise),
  CHECK (total_institution_allocated_paise <= distributable_pool_paise),
  CHECK (allocated_amount_paise <= total_institution_allocated_paise),
  CHECK (platform_remainder_paise = distributable_pool_paise - total_institution_allocated_paise)
);
CREATE INDEX idx_revenue_share_allocation_institution
  ON revenue_share_allocation(institution_id,created_at DESC,id DESC);
CREATE INDEX idx_revenue_share_allocation_order
  ON revenue_share_allocation(course_payment_order_id);

