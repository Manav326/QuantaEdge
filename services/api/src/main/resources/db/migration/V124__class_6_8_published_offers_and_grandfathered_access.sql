-- V124: publish Class 6/7/8 as ordinary INR 1,000 courses and grandfather learners
-- who already had access to that same class. This is not a payment/purchase record.
-- Do not duplicate lesson, chapter, question, assessment, certificate or progress data.

CREATE TABLE student_course_access_grant (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id bigint NOT NULL REFERENCES student(id) ON DELETE RESTRICT,
  course_id bigint NOT NULL REFERENCES curriculum_program(id) ON DELETE RESTRICT,
  grant_reason varchar(40) NOT NULL
    CHECK (grant_reason IN ('LEGACY_CLASS_ENROLLMENT')),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(student_id, course_id, grant_reason)
);

CREATE INDEX idx_student_course_access_grant_course
  ON student_course_access_grant(course_id, student_id);

-- "Already enrolled" is evidenced by either the prior same-class GENERAL enrollment
-- or an existing active/paused enrollment in one of that class's legacy subject tracks.
-- The class_code must match the product; this never grants adjacent or unrelated classes.
INSERT INTO student_course_access_grant(student_id, course_id, grant_reason)
SELECT DISTINCT st.id, course.id, 'LEGACY_CLASS_ENROLLMENT'
FROM student st
JOIN curriculum_class c ON c.code=st.class_code AND c.active=true AND c.code IN ('6','7','8')
JOIN curriculum_program course ON course.class_id=c.id
  AND course.code='CLASS_' || c.code
  AND course.curriculum_version='CURRENT' AND course.status='ACTIVE'
WHERE
  EXISTS (
    SELECT 1
    FROM curriculum_program general_course
    JOIN student_program_enrollment old_enrollment
      ON old_enrollment.program_id=general_course.id
     AND old_enrollment.student_id=st.id
     AND old_enrollment.status IN ('ACTIVE','PAUSED')
    WHERE general_course.class_id=c.id AND general_course.code='GENERAL'
      AND general_course.curriculum_version='CURRENT'
  )
  OR EXISTS (
    SELECT 1
    FROM student_track_enrollment legacy_track
    JOIN curriculum_subject legacy_subject ON legacy_subject.id=legacy_track.subject_id
      AND legacy_subject.class_id=c.id AND legacy_subject.program_id IS NULL
      AND legacy_subject.active=true
    WHERE legacy_track.student_id=st.id AND legacy_track.status IN ('ACTIVE','PAUSED')
  )
ON CONFLICT(student_id, course_id, grant_reason) DO NOTHING;

-- Keep every grandfathered course in the ordinary course ownership list. Prefer it as the
-- active course only when no other non-GENERAL course is already active for this learner.
INSERT INTO student_program_enrollment(
  student_id, program_id, status, enrolled_at, ended_at, created_at, updated_at
)
SELECT g.student_id, g.course_id,
  CASE WHEN st.active=true AND NOT EXISTS (
    SELECT 1
    FROM student_program_enrollment other_enrollment
    JOIN curriculum_program other_course ON other_course.id=other_enrollment.program_id
    WHERE other_enrollment.student_id=st.id
      AND other_enrollment.status='ACTIVE'
      AND other_course.code<>'GENERAL'
      AND other_course.id<>g.course_id
  ) THEN 'ACTIVE' ELSE 'PAUSED' END,
  g.created_at, NULL, g.created_at, now()
FROM student_course_access_grant g
JOIN student st ON st.id=g.student_id
WHERE g.grant_reason='LEGACY_CLASS_ENROLLMENT'
ON CONFLICT(student_id, program_id) DO UPDATE
SET status=CASE
      WHEN student_program_enrollment.status='ACTIVE' THEN 'ACTIVE'
      WHEN EXCLUDED.status='ACTIVE' THEN 'ACTIVE'
      WHEN student_program_enrollment.status='ENDED' THEN 'PAUSED'
      ELSE student_program_enrollment.status
    END,
    ended_at=NULL,
    updated_at=now();

-- Prices are stored in paise: INR 1,000 = 100,000 paise. Publishing these offers makes the
-- three courses discoverable in Marketplace. Existing class learners use the explicit free
-- access grant above; do not create course_purchase or Razorpay order rows for them.
INSERT INTO course_marketplace_offer(course_id, price_paise, currency, status)
SELECT p.id, 100000, 'INR', 'PUBLISHED'
FROM curriculum_program p
JOIN curriculum_class c ON c.id=p.class_id AND c.code IN ('6','7','8') AND c.active=true
WHERE p.code='CLASS_' || c.code
  AND p.curriculum_version='CURRENT'
  AND p.status='ACTIVE'
ON CONFLICT(course_id) DO UPDATE
SET price_paise=100000,
    currency='INR',
    status='PUBLISHED',
    updated_at=now();

INSERT INTO app_metadata(key,value)
VALUES ('schema','class-6-8-published-offers-grandfathered-access-v124')
ON CONFLICT(key) DO UPDATE SET value=EXCLUDED.value;
