CREATE UNIQUE INDEX uq_billing_gst_registration_gstin
  ON billing_gst_registration(gstin);
CREATE INDEX idx_billing_gst_registration_entity
  ON billing_gst_registration(legal_entity_id,status,effective_from DESC);

