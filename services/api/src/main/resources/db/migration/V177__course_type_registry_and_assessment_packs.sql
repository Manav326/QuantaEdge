-- One pack is a versioned authoring group. Assessment definitions and immutable question snapshots
-- remain in the existing assessment/assessment_question/attempt tables.
CREATE TABLE course_assessment_pack (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  course_id bigint NOT NULL REFERENCES curriculum_program(id) ON DELETE RESTRICT,
  source_institution_id bigint NOT NULL REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  pack_code varchar(120) NOT NULL CHECK (pack_code ~ '^[a-z0-9][a-z0-9._-]{2,119}$'),
  pack_version varchar(40) NOT NULL CHECK (pack_version ~ '^[A-Za-z0-9][A-Za-z0-9._+-]{0,39}$'),
  title varchar(240) NOT NULL CHECK (length(btrim(title))>0),
  description varchar(1200),
  status varchar(16) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','PUBLISHED','ARCHIVED')),
  content_sha256 char(64) NOT NULL CHECK (content_sha256 ~ '^[0-9a-f]{64}$'),
  open_book_enabled boolean NOT NULL DEFAULT false,
  resource_policy jsonb NOT NULL DEFAULT '{"mode":"CLOSED_BOOK","resources":[]}'::jsonb
    CHECK (jsonb_typeof(resource_policy)='object'),
  created_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  published_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  published_at timestamptz,
  UNIQUE(course_id,pack_code,pack_version)
);
CREATE INDEX idx_course_assessment_pack_course
  ON course_assessment_pack(course_id,status,created_at DESC,id DESC);
CREATE INDEX idx_course_assessment_pack_source
  ON course_assessment_pack(source_institution_id,course_id,status);

CREATE TABLE course_assessment_pack_item (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pack_id bigint NOT NULL REFERENCES course_assessment_pack(id) ON DELETE RESTRICT,
  assessment_id bigint NOT NULL REFERENCES assessment(id) ON DELETE RESTRICT,
  sequence_no integer NOT NULL CHECK (sequence_no BETWEEN 1 AND 1000),
  test_kind varchar(32) NOT NULL CHECK (test_kind ~ '^[A-Z][A-Z0-9_]{1,31}$'),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(pack_id,assessment_id),
  UNIQUE(pack_id,sequence_no)
);
CREATE INDEX idx_course_assessment_pack_item_order
  ON course_assessment_pack_item(pack_id,sequence_no,assessment_id);
CREATE INDEX idx_course_assessment_pack_item_assessment
  ON course_assessment_pack_item(assessment_id,pack_id);

-- Explicit attempt-scoped resources for open-book assessment packs. A resource ID from a portable
-- JSON upload is never trusted by itself: the import API must resolve it to an active source-owned
-- resource before writing this relation.
CREATE TABLE course_assessment_pack_resource (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pack_id bigint NOT NULL REFERENCES course_assessment_pack(id) ON DELETE RESTRICT,
  resource_id bigint NOT NULL REFERENCES learning_resource(id) ON DELETE RESTRICT,
  sequence_no integer NOT NULL DEFAULT 1 CHECK (sequence_no BETWEEN 1 AND 1000),
  access_scope varchar(20) NOT NULL DEFAULT 'ATTEMPT_ONLY'
    CHECK (access_scope IN ('ATTEMPT_ONLY','REVIEW_ONLY','RESULT_ONLY')),
  created_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(pack_id,resource_id),
  UNIQUE(pack_id,sequence_no)
);
CREATE INDEX idx_course_assessment_pack_resource
  ON course_assessment_pack_resource(pack_id,sequence_no,resource_id);

-- Keep the public presentation kind distinct from the legacy assessment_type constraint.
ALTER TABLE assessment
  ADD COLUMN IF NOT EXISTS portable_assessment_type varchar(24);
DO $portable_type_check$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname='ck_assessment_portable_type'
      AND conrelid='public.assessment'::regclass
  ) THEN
    ALTER TABLE assessment
      ADD CONSTRAINT ck_assessment_portable_type
      CHECK (portable_assessment_type IS NULL OR portable_assessment_type IN (
        'PREVIOUS_YEAR_PAPER','MOCK_EXAM','DIAGNOSTIC','PRACTICE_SET'
      ));
  END IF;
END
$portable_type_check$;

