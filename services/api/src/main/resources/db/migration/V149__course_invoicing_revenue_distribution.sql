CREATE TABLE fiscal_document (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  legal_entity_id bigint NOT NULL REFERENCES billing_legal_entity(id) ON DELETE RESTRICT,
  gst_registration_id bigint REFERENCES billing_gst_registration(id) ON DELETE RESTRICT,
  document_type varchar(24) NOT NULL
    CHECK (document_type IN ('TAX_INVOICE','BILL_OF_SUPPLY','RECEIPT_VOUCHER','PAYMENT_RECEIPT','CREDIT_NOTE','DEBIT_NOTE')),
  financial_year varchar(9) NOT NULL CHECK (financial_year ~ '^[0-9]{4}-[0-9]{2}$'),
  series_code varchar(16) NOT NULL,
  sequence_no bigint NOT NULL CHECK (sequence_no > 0),
  document_number varchar(64) NOT NULL CHECK (length(btrim(document_number)) > 0),
  source_type varchar(32) NOT NULL
    CHECK (source_type IN ('COURSE_ORDER','INSTITUTION_CONTRACT','REVENUE_SHARE','MANUAL_ADJUSTMENT')),
  source_record_key varchar(180) NOT NULL,
  idempotency_key varchar(180) NOT NULL UNIQUE,
  original_document_id bigint REFERENCES fiscal_document(id) ON DELETE RESTRICT,
  currency char(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
  supplier_snapshot jsonb NOT NULL CHECK (jsonb_typeof(supplier_snapshot)='object'),
  recipient_snapshot jsonb NOT NULL CHECK (jsonb_typeof(recipient_snapshot)='object'),
  transaction_snapshot jsonb NOT NULL CHECK (jsonb_typeof(transaction_snapshot)='object'),
  tax_summary_snapshot jsonb NOT NULL CHECK (jsonb_typeof(tax_summary_snapshot)='object'),
  taxable_value_paise bigint NOT NULL DEFAULT 0 CHECK (taxable_value_paise >= 0),
  discount_value_paise bigint NOT NULL DEFAULT 0 CHECK (discount_value_paise >= 0),
  tax_value_paise bigint NOT NULL DEFAULT 0 CHECK (tax_value_paise >= 0),
  total_value_paise bigint NOT NULL CHECK (total_value_paise >= 0),
  amount_paid_paise bigint NOT NULL DEFAULT 0 CHECK (amount_paid_paise >= 0),
  template_version_id bigint REFERENCES invoice_template_version(id) ON DELETE RESTRICT,
  issued_at timestamptz NOT NULL DEFAULT now(),
  created_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(legal_entity_id,document_type,financial_year,series_code,sequence_no),
  UNIQUE(legal_entity_id,document_number),
  CHECK (amount_paid_paise <= total_value_paise OR document_type IN ('CREDIT_NOTE','DEBIT_NOTE')),
  CHECK ((document_type IN ('CREDIT_NOTE','DEBIT_NOTE') AND original_document_id IS NOT NULL)
      OR (document_type NOT IN ('CREDIT_NOTE','DEBIT_NOTE') AND original_document_id IS NULL))
);
CREATE UNIQUE INDEX uq_fiscal_document_order_sale_invoice
  ON fiscal_document(source_type,source_record_key)
  WHERE source_type='COURSE_ORDER' AND document_type IN ('TAX_INVOICE','BILL_OF_SUPPLY');
