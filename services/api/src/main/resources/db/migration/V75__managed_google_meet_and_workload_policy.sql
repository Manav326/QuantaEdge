-- V75: managed Google Meet lifecycle and configurable teacher workload policy.
-- A pasted Meet URL is not proof that Google created a valid, managed conference.
alter table learning_class_session
  alter column private_join_url drop not null,
  add column provider_event_id varchar(255),
  add column provider_conference_request_id varchar(128),
  add column provider_operation_status varchar(20) not null default 'NOT_REQUIRED'
    check (provider_operation_status in ('NOT_REQUIRED','PENDING','CREATED','FAILED','CANCELLED')),
  add column provider_error_code varchar(80),
  add column provider_error_message varchar(500),
  add column provider_operation_attempts integer not null default 0 check (provider_operation_attempts >= 0),
  add column provider_last_attempt_at timestamptz;

update learning_class_session
set provider_operation_status='FAILED',
    provider_error_code='LEGACY_UNVERIFIED',
    provider_error_message='This saved Meet URL predates managed Google Calendar verification. Retry Meet setup to create and verify a managed meeting.'
where provider='GOOGLE_MEET';

create index idx_learning_class_session_provider_operation
  on learning_class_session(provider,provider_operation_status,starts_at);

create table hr_teaching_workload_policy (
  id bigint generated by default as identity primary key,
  organization_id bigint not null unique references hr_organization(id) on delete restrict,
  weekly_minutes_limit integer not null check (weekly_minutes_limit between 60 and 6000),
  updated_by_staff_id bigint references staff_account(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

insert into staff_permission_catalog(permission_key,display_name,description) values
 ('CLASS_SCHEDULE_POLICY_MANAGE','Manage teaching workload policy','Configure organisation-level weekly scheduled teaching workload limits.')
on conflict(permission_key) do update
set display_name=excluded.display_name,description=excluded.description;
