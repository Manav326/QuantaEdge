ALTER TABLE revenue_share_allocation_event
  ALTER COLUMN event_type TYPE varchar(40);
ALTER TABLE revenue_share_allocation_event
  DROP CONSTRAINT revenue_share_allocation_event_event_type_check;
ALTER TABLE revenue_share_allocation_event
  ADD CONSTRAINT revenue_share_allocation_event_event_type_check CHECK (
    event_type IN ('EARNED','PAYABLE','PAID','ON_HOLD','RELEASED','REVERSED','REFUNDED',
      'PROCESSING_FEE_DEDUCTED','PROCESSING_FEE_CREDITED')
  );

CREATE TABLE course_payment_order_fee_adjustment (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_payment_order_id bigint NOT NULL REFERENCES course_payment_order(id) ON DELETE RESTRICT,
  previous_processing_fee_paise bigint NOT NULL CHECK(previous_processing_fee_paise>=0),
  previous_fee_tax_paise bigint NOT NULL CHECK(previous_fee_tax_paise>=0),
  requested_processing_fee_paise bigint NOT NULL CHECK(requested_processing_fee_paise>=0),
  requested_fee_tax_paise bigint NOT NULL CHECK(requested_fee_tax_paise>=0),
  settlement_reference varchar(180) NOT NULL CHECK(length(trim(settlement_reference)) BETWEEN 3 AND 180),
  source_type varchar(32) NOT NULL CHECK(source_type IN ('SETTLEMENT_REPORT','PROVIDER_API','MANUAL_RECONCILIATION')),
  reason varchar(500) NOT NULL CHECK(length(trim(reason)) BETWEEN 5 AND 500),
  idempotency_key varchar(180) NOT NULL UNIQUE,
  requested_by_staff_id bigint NOT NULL REFERENCES staff_account(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK(previous_processing_fee_paise<>requested_processing_fee_paise
    OR previous_fee_tax_paise<>requested_fee_tax_paise)
);
CREATE INDEX idx_course_order_fee_adjustment_order
  ON course_payment_order_fee_adjustment(course_payment_order_id,id DESC);

CREATE TABLE course_payment_order_fee_adjustment_review (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  adjustment_id bigint NOT NULL UNIQUE REFERENCES course_payment_order_fee_adjustment(id) ON DELETE RESTRICT,
  decision varchar(8) NOT NULL CHECK(decision IN ('APPROVED','REJECTED')),
  reason varchar(500) NOT NULL CHECK(length(trim(reason)) BETWEEN 5 AND 500),
  reviewed_by_staff_id bigint NOT NULL REFERENCES staff_account(id) ON DELETE RESTRICT,
  reviewed_at timestamptz NOT NULL DEFAULT now()
);

-- Requests, reviews and allocation events are audit facts. A decision is appended, never edited.
CREATE TRIGGER trg_course_payment_order_fee_adjustment_immutable
BEFORE UPDATE OR DELETE ON course_payment_order_fee_adjustment
FOR EACH ROW EXECUTE FUNCTION reject_billing_financial_mutation();
CREATE TRIGGER trg_course_payment_order_fee_adjustment_review_immutable
BEFORE UPDATE OR DELETE ON course_payment_order_fee_adjustment_review
FOR EACH ROW EXECUTE FUNCTION reject_billing_financial_mutation();

