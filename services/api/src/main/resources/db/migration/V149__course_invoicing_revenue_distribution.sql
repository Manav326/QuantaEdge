-- V149: fiscal document, tax-policy, invoice-template and institutional revenue-share foundations.
-- Issued documents and monetary allocations are immutable facts; corrections use linked documents/events.
-- No legal seller, GST rate, sample invoice, revenue or payout is seeded.

CREATE TABLE billing_legal_entity (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  entity_kind varchar(16) NOT NULL CHECK (entity_kind IN ('PLATFORM','INSTITUTION')),
  institution_id bigint REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  legal_name varchar(240) NOT NULL CHECK (length(btrim(legal_name)) > 0),
  trade_name varchar(240),
  contact_email varchar(320),
  contact_phone varchar(40),
  registered_address jsonb NOT NULL DEFAULT '{}'::jsonb
    CHECK (jsonb_typeof(registered_address) = 'object'),
  country_code char(2) NOT NULL DEFAULT 'IN' CHECK (country_code ~ '^[A-Z]{2}$'),
  status varchar(16) NOT NULL DEFAULT 'DRAFT'
    CHECK (status IN ('DRAFT','ACTIVE','SUSPENDED','CLOSED')),
  created_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  updated_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((entity_kind='PLATFORM' AND institution_id IS NULL)
      OR (entity_kind='INSTITUTION' AND institution_id IS NOT NULL))
);
CREATE INDEX idx_billing_legal_entity_status
  ON billing_legal_entity(status,entity_kind,id);

CREATE UNIQUE INDEX uq_billing_legal_entity_institution_active_name
  ON billing_legal_entity(institution_id,lower(legal_name))
  WHERE institution_id IS NOT NULL AND status='ACTIVE';

CREATE TABLE billing_gst_registration (
