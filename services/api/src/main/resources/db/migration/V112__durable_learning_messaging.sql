-- V112: native QuantaEdge classroom and private student-to-teacher messaging.
-- PostgreSQL is the durable source of truth; realtime delivery is an optimization only.
CREATE TABLE learning_conversation (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_type varchar(24) NOT NULL CHECK (conversation_type IN ('CLASSROOM','STUDENT_TEACHER')),
  session_id bigint NOT NULL REFERENCES learning_class_session(id) ON DELETE RESTRICT,
  student_id bigint REFERENCES student(id) ON DELETE RESTRICT,
  status varchar(16) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','CLOSED','ARCHIVED')),
  slow_mode_seconds integer NOT NULL DEFAULT 0 CHECK (slow_mode_seconds BETWEEN 0 AND 60),
  created_by_student_id bigint REFERENCES student(id) ON DELETE RESTRICT,
  created_by_staff_id bigint REFERENCES staff_account(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  last_message_at timestamptz,
  CONSTRAINT ck_learning_conversation_scope CHECK (
    (conversation_type='CLASSROOM' AND student_id IS NULL)
    OR (conversation_type='STUDENT_TEACHER' AND student_id IS NOT NULL)
  ),
  CONSTRAINT ck_learning_conversation_creator CHECK (
    (created_by_student_id IS NOT NULL) <> (created_by_staff_id IS NOT NULL)
  )
);
CREATE UNIQUE INDEX uq_learning_conversation_classroom
  ON learning_conversation(session_id)
  WHERE conversation_type='CLASSROOM' AND status<>'ARCHIVED';
CREATE UNIQUE INDEX uq_learning_conversation_student_teacher
  ON learning_conversation(session_id,student_id)
  WHERE conversation_type='STUDENT_TEACHER' AND status<>'ARCHIVED';
CREATE INDEX idx_learning_conversation_session_updated
  ON learning_conversation(session_id,last_message_at DESC,id DESC) WHERE status<>'ARCHIVED';

CREATE TABLE learning_message (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id bigint NOT NULL REFERENCES learning_conversation(id) ON DELETE RESTRICT,
  sender_student_id bigint REFERENCES student(id) ON DELETE RESTRICT,
  sender_staff_id bigint REFERENCES staff_account(id) ON DELETE RESTRICT,
  client_message_id uuid NOT NULL,
  message_type varchar(20) NOT NULL DEFAULT 'TEXT' CHECK (message_type IN ('TEXT','QUESTION','ANNOUNCEMENT')),
  body varchar(4000) NOT NULL CHECK (length(btrim(body)) BETWEEN 1 AND 4000),
  status varchar(16) NOT NULL DEFAULT 'VISIBLE' CHECK (status IN ('VISIBLE','HIDDEN')),
  created_at timestamptz NOT NULL DEFAULT now(),
  hidden_at timestamptz,
  hidden_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  pinned_at timestamptz,
  pinned_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  CONSTRAINT ck_learning_message_sender CHECK ((sender_student_id IS NOT NULL) <> (sender_staff_id IS NOT NULL)),
  CONSTRAINT uq_learning_message_client_identity UNIQUE(conversation_id,client_message_id)
);
CREATE INDEX idx_learning_message_conversation_order ON learning_message(conversation_id,id DESC);
CREATE INDEX idx_learning_message_visible_pin
  ON learning_message(conversation_id,pinned_at DESC,id DESC)
  WHERE status='VISIBLE' AND pinned_at IS NOT NULL;

CREATE TABLE learning_conversation_read_state (
  conversation_id bigint NOT NULL REFERENCES learning_conversation(id) ON DELETE CASCADE,
  participant_kind varchar(12) NOT NULL CHECK (participant_kind IN ('STUDENT','STAFF')),
  participant_id bigint NOT NULL CHECK (participant_id>0),
  last_read_message_id bigint REFERENCES learning_message(id) ON DELETE SET NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(conversation_id,participant_kind,participant_id)
);

CREATE TABLE learning_conversation_mute (
  conversation_id bigint NOT NULL REFERENCES learning_conversation(id) ON DELETE CASCADE,
  student_id bigint NOT NULL REFERENCES student(id) ON DELETE CASCADE,
  muted_until timestamptz NOT NULL,
  created_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(conversation_id,student_id)
);
CREATE INDEX idx_learning_conversation_mute_active
  ON learning_conversation_mute(conversation_id,muted_until);

CREATE TABLE learning_message_report (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id bigint NOT NULL REFERENCES learning_conversation(id) ON DELETE RESTRICT,
  message_id bigint NOT NULL REFERENCES learning_message(id) ON DELETE RESTRICT,
  reporter_student_id bigint REFERENCES student(id) ON DELETE RESTRICT,
  reporter_staff_id bigint REFERENCES staff_account(id) ON DELETE RESTRICT,
  reason varchar(1000) NOT NULL CHECK (length(btrim(reason)) BETWEEN 5 AND 1000),
  status varchar(16) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','RESOLVED','DISMISSED')),
  reviewed_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  reviewed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_learning_message_reporter CHECK ((reporter_student_id IS NOT NULL) <> (reporter_staff_id IS NOT NULL))
);
CREATE UNIQUE INDEX uq_learning_message_report_student
  ON learning_message_report(message_id,reporter_student_id) WHERE reporter_student_id IS NOT NULL;
CREATE UNIQUE INDEX uq_learning_message_report_staff
  ON learning_message_report(message_id,reporter_staff_id) WHERE reporter_staff_id IS NOT NULL;
CREATE INDEX idx_learning_message_report_open ON learning_message_report(status,created_at DESC);

CREATE TABLE learning_message_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id bigint NOT NULL REFERENCES learning_conversation(id) ON DELETE RESTRICT,
  message_id bigint REFERENCES learning_message(id) ON DELETE SET NULL,
  actor_kind varchar(12) NOT NULL CHECK (actor_kind IN ('STUDENT','STAFF')),
  actor_id bigint NOT NULL CHECK (actor_id>0),
  action_code varchar(32) NOT NULL CHECK (action_code IN (
    'HIDE','RESTORE','PIN','UNPIN','MUTE_STUDENT','UNMUTE_STUDENT','REPORT',
    'REPORT_RESOLVED','REPORT_DISMISSED','SLOW_MODE_CHANGED')),
  details varchar(1000),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_learning_message_audit_conversation ON learning_message_audit(conversation_id,created_at DESC);

