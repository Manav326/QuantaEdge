-- V146: tenant-bound Android device registrations and retryable FCM delivery.
-- Device tokens are private delivery addresses, never account credentials or recipient identities.

CREATE TABLE notification_device_registration (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id uuid NOT NULL,
  identity_kind varchar(24) NOT NULL CHECK (identity_kind IN ('STUDENT','USER_ACCOUNT')),
  student_id bigint REFERENCES student(id) ON DELETE RESTRICT,
  user_account_id bigint REFERENCES user_account(id) ON DELETE RESTRICT,
  institution_id bigint NOT NULL REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  device_token text NOT NULL CHECK (length(device_token) BETWEEN 100 AND 4096),
  token_hash char(64) NOT NULL CHECK (token_hash ~ '^[0-9a-f]{64}$'),
  platform varchar(16) NOT NULL DEFAULT 'ANDROID' CHECK (platform='ANDROID'),
  package_name varchar(220) NOT NULL CHECK (length(btrim(package_name)) BETWEEN 3 AND 220),
  app_version varchar(80),
  status varchar(16) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','REVOKED')),
  registered_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  revoked_at timestamptz,
  CONSTRAINT ck_notification_device_identity CHECK (
    (identity_kind='STUDENT' AND student_id IS NOT NULL AND user_account_id IS NULL)
    OR (identity_kind='USER_ACCOUNT' AND student_id IS NULL AND user_account_id IS NOT NULL)
  ),
  CONSTRAINT ck_notification_device_revocation CHECK (
    (status='ACTIVE' AND revoked_at IS NULL) OR (status='REVOKED' AND revoked_at IS NOT NULL)
  )
);
CREATE UNIQUE INDEX uq_notification_device_active_installation
  ON notification_device_registration(device_id) WHERE status='ACTIVE';
CREATE UNIQUE INDEX uq_notification_device_active_token
  ON notification_device_registration(token_hash) WHERE status='ACTIVE';
CREATE INDEX idx_notification_device_recipient
  ON notification_device_registration(identity_kind,student_id,user_account_id,institution_id,last_seen_at DESC)
  WHERE status='ACTIVE';

-- Track a separate push attempt per registered installation; retain a null-device status row when
-- no active Android installation exists for a recipient.
ALTER TABLE notification_delivery_attempt
  ADD COLUMN device_registration_id bigint REFERENCES notification_device_registration(id) ON DELETE RESTRICT;
ALTER TABLE notification_delivery_attempt
  ADD COLUMN next_attempt_at timestamptz NOT NULL DEFAULT now();
ALTER TABLE notification_delivery_attempt
  DROP CONSTRAINT IF EXISTS notification_delivery_attempt_recipient_id_channel_attempt_number_key;
CREATE UNIQUE INDEX uq_notification_delivery_attempt_device
  ON notification_delivery_attempt(recipient_id,channel,attempt_number,COALESCE(device_registration_id,0));
CREATE INDEX idx_notification_push_pending
  ON notification_delivery_attempt(next_attempt_at,attempted_at,id)
  WHERE channel='ANDROID_PUSH' AND status IN ('PENDING','RETRYING');

INSERT INTO app_metadata(key,value)
VALUES ('schema','android-push-notification-devices-v146')
ON CONFLICT(key) DO UPDATE SET value=excluded.value;
