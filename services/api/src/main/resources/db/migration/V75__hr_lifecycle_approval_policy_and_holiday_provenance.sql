-- Explicit, organization-scoped approval policy. No transition is silently auto-approved.
create table hr_lifecycle_approval_rule (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references hr_organization(id) on delete cascade,
  transition_key varchar(64) not null,
  from_status varchar(24) not null,
  to_status varchar(24) not null,
  required_permission_key varchar(96) not null references staff_permission_catalog(permission_key) on delete restrict,
  active boolean not null default true,
  updated_by_staff_id bigint references staff_account(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(organization_id,transition_key),
  check(from_status<>to_status)
);
insert into hr_lifecycle_approval_rule(organization_id,transition_key,from_status,to_status,required_permission_key)
select o.id,v.transition_key,v.from_status,v.to_status,'HR_EMPLOYEE_MANAGE'
from hr_organization o
cross join (values
 ('DRAFT_TO_ACTIVE','DRAFT','ACTIVE'),
 ('ACTIVE_TO_ON_LEAVE','ACTIVE','ON_LEAVE'),
 ('ON_LEAVE_TO_ACTIVE','ON_LEAVE','ACTIVE'),
 ('ACTIVE_TO_NOTICE_PERIOD','ACTIVE','NOTICE_PERIOD'),
 ('NOTICE_PERIOD_TO_ACTIVE','NOTICE_PERIOD','ACTIVE'),
 ('NOTICE_PERIOD_TO_SEPARATED','NOTICE_PERIOD','SEPARATED'),
 ('ACTIVE_TO_SEPARATED','ACTIVE','SEPARATED'),
 ('ACTIVE_TO_INACTIVE','ACTIVE','INACTIVE'),
 ('INACTIVE_TO_ACTIVE','INACTIVE','ACTIVE')
) v(transition_key,from_status,to_status)
where o.active
on conflict(organization_id,transition_key) do nothing;

