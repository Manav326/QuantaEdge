-- V127: add audit fields and event ledger for institution course lifecycle.
-- V125 is the canonical release/assignment/offer schema; do not redefine it here.
-- Payments continue to use the single platform/HRMS-configured provider account. Institution
-- offers identify commercial terms and beneficiary institution, not a payment receiver.

DO $assignment_source_check$
DECLARE constraint_name text;
BEGIN
  FOR constraint_name IN
    SELECT c.conname
    FROM pg_constraint c
    WHERE c.conrelid='public.institution_course_assignment'::regclass
      AND c.contype='c'
      AND pg_get_constraintdef(c.oid) ILIKE '%assignment_source%'
  LOOP
    EXECUTE format('ALTER TABLE public.institution_course_assignment DROP CONSTRAINT %I',constraint_name);
  END LOOP;
END
$assignment_source_check$;

ALTER TABLE institution_course_assignment
  ADD CONSTRAINT ck_institution_course_assignment_source
  CHECK (assignment_source IN (
    'ORIGIN','HRMS','LEGACY_ENTITLEMENT_MIGRATION','LEGACY_QUANTAEDGE_CATALOG'
  ));

ALTER TABLE institution_course_release
  ADD COLUMN IF NOT EXISTS origin_rejected_by_admin_id bigint REFERENCES institution_admin_account(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS origin_rejected_at timestamptz,
  ADD COLUMN IF NOT EXISTS origin_rejection_reason varchar(1000);

ALTER TABLE institution_marketplace_offer
  ADD COLUMN IF NOT EXISTS created_by_admin_id bigint REFERENCES institution_admin_account(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS updated_by_admin_id bigint REFERENCES institution_admin_account(id) ON DELETE SET NULL;

CREATE TABLE institution_course_lifecycle_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institution_id bigint NOT NULL REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  course_release_id bigint REFERENCES institution_course_release(id) ON DELETE RESTRICT,
  assignment_id bigint REFERENCES institution_course_assignment(id) ON DELETE RESTRICT,
  offer_id bigint REFERENCES institution_marketplace_offer(id) ON DELETE RESTRICT,
  event_type varchar(48) NOT NULL CHECK (event_type ~ '^[A-Z][A-Z0-9_]{2,47}$'),
  actor_platform_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  actor_institution_admin_id bigint REFERENCES institution_admin_account(id) ON DELETE SET NULL,
  details jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(details)='object'),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_institution_course_lifecycle_event_tenant_time
  ON institution_course_lifecycle_event(institution_id,created_at DESC,id DESC);
CREATE INDEX idx_institution_course_lifecycle_event_release
  ON institution_course_lifecycle_event(course_release_id,created_at DESC,id DESC)
  WHERE course_release_id IS NOT NULL;
CREATE INDEX idx_institution_course_lifecycle_event_offer
  ON institution_course_lifecycle_event(offer_id,created_at DESC,id DESC)
  WHERE offer_id IS NOT NULL;

