-- Leave balances are a ledger, not a mutable total. No employee balances are seeded.
create table hr_leave_balance_transaction (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references hr_organization(id) on delete restrict,
  employee_id bigint not null references hr_employee(id) on delete restrict,
  leave_type_code varchar(32) not null references hr_leave_type(code) on delete restrict,
  transaction_type varchar(16) not null,
  quantity_days numeric(9,2) not null,
  effective_date date not null,
  source_type varchar(32) not null,
  source_reference varchar(160),
  reason varchar(1000) not null,
  reverses_transaction_id bigint references hr_leave_balance_transaction(id) on delete restrict,
  created_by_staff_id bigint references staff_account(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint ck_hr_leave_balance_tx_type check (transaction_type in ('GRANT','ACCRUAL','CONSUMPTION','REVERSAL','ADJUSTMENT')),
  constraint ck_hr_leave_balance_tx_quantity check (quantity_days <> 0 and abs(quantity_days) <= 999999.99),
  constraint ck_hr_leave_balance_tx_sign check (
    (transaction_type in ('GRANT','ACCRUAL') and quantity_days > 0) or
    (transaction_type = 'CONSUMPTION' and quantity_days < 0) or
    transaction_type in ('REVERSAL','ADJUSTMENT')
  ),
  constraint ck_hr_leave_balance_tx_reason check (length(trim(reason)) > 0),
  constraint ck_hr_leave_balance_tx_source check (length(trim(source_type)) > 0)
);
create unique index uq_hr_leave_balance_source on hr_leave_balance_transaction(organization_id,source_type,source_reference,employee_id,leave_type_code)
  where source_reference is not null and transaction_type in ('GRANT','ACCRUAL','CONSUMPTION');
create unique index uq_hr_leave_balance_reversal on hr_leave_balance_transaction(reverses_transaction_id)
  where reverses_transaction_id is not null;
create index idx_hr_leave_balance_employee_type_date on hr_leave_balance_transaction(organization_id,employee_id,leave_type_code,effective_date,id);
create index idx_hr_leave_balance_source on hr_leave_balance_transaction(source_type,source_reference);
insert into staff_permission_catalog(permission_key,display_name,description) values
 ('HR_LEAVE_BALANCE_VIEW','View leave balances','View ledger-derived employee leave balances.'),
 ('HR_LEAVE_BALANCE_MANAGE','Manage leave balances','Grant or adjust employee leave balances with a required reason.')
on conflict(permission_key) do update set display_name=excluded.display_name,description=excluded.description;
