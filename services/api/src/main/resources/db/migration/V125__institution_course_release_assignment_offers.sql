-- V125: institution-owned course releases, explicit cross-institution assignments and local offers.
-- Existing course identities/content remain canonical and are not cloned. The one-time legacy
-- bootstrap scopes pre-existing unassigned learner records and courses to QUANTA-EDGE; it does
-- not auto-join future signups or publish any Marketplace offer.

INSERT INTO institution_tenant(public_id,tenant_code,display_name,status)
VALUES (gen_random_uuid(),'QUANTA-EDGE','QuantaEdge','ACTIVE')
ON CONFLICT (tenant_code) DO NOTHING;

-- Legacy students without a prior institution membership are associated with the QuantaEdge
-- institution at migration time. Existing members of other institutions are deliberately untouched.
INSERT INTO institution_membership(
  institution_id,student_id,status,joined_at,left_at,created_at,updated_at
)
SELECT t.id,st.id,'ACTIVE',now(),NULL,now(),now()
FROM institution_tenant t
CROSS JOIN student st
WHERE t.tenant_code='QUANTA-EDGE'
  AND NOT EXISTS (SELECT 1 FROM institution_membership m WHERE m.student_id=st.id)
ON CONFLICT (institution_id,student_id) DO NOTHING;

ALTER TABLE student_course_access_grant
  ADD COLUMN institution_id bigint REFERENCES institution_tenant(id) ON DELETE RESTRICT;

-- Only map a legacy zero-price access grant to QUANTA-EDGE where the learner was safely
-- backfilled/recorded as a member of that tenant. Ambiguous legacy grants remain null and fail
-- closed until an audited data-reconciliation operation identifies the right institution.
UPDATE student_course_access_grant g
SET institution_id=t.id
FROM institution_tenant t
WHERE t.tenant_code='QUANTA-EDGE'
  AND g.institution_id IS NULL
  AND EXISTS (
    SELECT 1 FROM institution_membership m
    WHERE m.institution_id=t.id AND m.student_id=g.student_id AND m.status='ACTIVE'
  );

CREATE INDEX idx_student_course_access_grant_tenant_student_course
  ON student_course_access_grant(institution_id,student_id,course_id);

-- Institution-created programs need an immutable public ID prefix registered before INSERT.
INSERT INTO public_identity_prefix_registry(prefix,entity_type,description)
VALUES ('INS','PROGRAM','Institution-origin course')
ON CONFLICT (prefix) DO NOTHING;

DO $ins_prefix$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM public_identity_prefix_registry
    WHERE prefix='INS' AND entity_type='PROGRAM' AND active=true
  ) THEN
    RAISE EXCEPTION 'Public identity prefix INS must be registered for PROGRAM before V125 can proceed.';
  END IF;
END;
$ins_prefix$;

CREATE TABLE institution_course_release (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  origin_institution_id bigint NOT NULL REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  program_id bigint NOT NULL REFERENCES curriculum_program(id) ON DELETE RESTRICT,
  release_version integer NOT NULL CHECK (release_version > 0),
  status varchar(28) NOT NULL DEFAULT 'ORIGIN_REVIEW'
    CHECK (status IN ('ORIGIN_REVIEW','SHAREABLE','REJECTED','REVOKED')),
  quality_evidence jsonb NOT NULL CHECK (jsonb_typeof(quality_evidence)='object'),
  content_fingerprint char(32) NOT NULL CHECK (content_fingerprint ~ '^[0-9a-f]{32}$'),
  submitted_by_institution_admin_id bigint NOT NULL,
  submitted_at timestamptz NOT NULL DEFAULT now(),
  origin_approved_by_institution_admin_id bigint,
  origin_approved_at timestamptz,
  rejected_by_institution_admin_id bigint,
  rejected_at timestamptz,
  rejection_reason varchar(500),
  revoked_by_institution_admin_id bigint,
  revoked_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(origin_institution_id,program_id,release_version),
  UNIQUE(id,program_id),
  UNIQUE(id,origin_institution_id,program_id),
  FOREIGN KEY(origin_institution_id,submitted_by_institution_admin_id)
    REFERENCES institution_admin_account(institution_id,id) ON DELETE RESTRICT,
  FOREIGN KEY(origin_institution_id,origin_approved_by_institution_admin_id)
    REFERENCES institution_admin_account(institution_id,id) ON DELETE RESTRICT,
  FOREIGN KEY(origin_institution_id,rejected_by_institution_admin_id)
    REFERENCES institution_admin_account(institution_id,id) ON DELETE RESTRICT,
  FOREIGN KEY(origin_institution_id,revoked_by_institution_admin_id)
    REFERENCES institution_admin_account(institution_id,id) ON DELETE RESTRICT,
  CHECK ((status<>'SHAREABLE') OR
    (origin_approved_by_institution_admin_id IS NOT NULL AND origin_approved_at IS NOT NULL)),
  CHECK ((status<>'REJECTED') OR (rejected_at IS NOT NULL AND rejection_reason IS NOT NULL)),
  CHECK ((status<>'REVOKED') OR (revoked_at IS NOT NULL))
);

CREATE INDEX idx_institution_course_release_origin
  ON institution_course_release(origin_institution_id,status,program_id,release_version DESC);
CREATE INDEX idx_institution_course_release_shareable
  ON institution_course_release(status,program_id,origin_institution_id)
  WHERE status='SHAREABLE';

CREATE TABLE institution_course_assignment (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institution_id bigint NOT NULL REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  program_id bigint NOT NULL REFERENCES curriculum_program(id) ON DELETE RESTRICT,
  course_release_id bigint,
  assignment_source varchar(24) NOT NULL
    CHECK (assignment_source IN ('ORIGIN','PLATFORM','LEGACY_BOOTSTRAP')),
  status varchar(12) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','REVOKED')),
  assigned_by_staff_id bigint REFERENCES staff_account(id) ON DELETE RESTRICT,
  assigned_by_institution_admin_id bigint,
  assigned_at timestamptz NOT NULL DEFAULT now(),
  revoked_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(id,institution_id,course_release_id,program_id),
  FOREIGN KEY(course_release_id,program_id)
    REFERENCES institution_course_release(id,program_id) ON DELETE RESTRICT,
  FOREIGN KEY(institution_id,assigned_by_institution_admin_id)
    REFERENCES institution_admin_account(institution_id,id) ON DELETE RESTRICT,
  CHECK ((status='REVOKED' AND revoked_at IS NOT NULL) OR
         (status='ACTIVE' AND revoked_at IS NULL)),
  CHECK (
    (assignment_source='PLATFORM' AND assigned_by_staff_id IS NOT NULL AND assigned_by_institution_admin_id IS NULL)
    OR (assignment_source='ORIGIN' AND assigned_by_staff_id IS NULL)
    OR (assignment_source='LEGACY_BOOTSTRAP' AND assigned_by_staff_id IS NULL AND assigned_by_institution_admin_id IS NULL)
  )
);

CREATE UNIQUE INDEX uq_institution_course_assignment_release
  ON institution_course_assignment(institution_id,course_release_id)
  WHERE course_release_id IS NOT NULL;
CREATE UNIQUE INDEX uq_institution_course_assignment_legacy
  ON institution_course_assignment(institution_id,program_id)
  WHERE course_release_id IS NULL;
CREATE INDEX idx_institution_course_assignment_active
  ON institution_course_assignment(institution_id,status,program_id);

-- QuantaEdge's pre-existing active course masters are affiliated to its tenant. This migration
-- does not create shareable releases or Marketplace offers; each release still needs explicit
-- origin-institution approval and each offer needs destination review/approval/publication.
INSERT INTO institution_course_assignment(
  institution_id,program_id,course_release_id,assignment_source,status,
  assigned_at,created_at,updated_at
)
SELECT t.id,p.id,NULL,'LEGACY_BOOTSTRAP','ACTIVE',now(),now(),now()
FROM institution_tenant t
JOIN curriculum_program p ON p.status='ACTIVE' AND p.code<>'GENERAL'
WHERE t.tenant_code='QUANTA-EDGE'
ON CONFLICT (institution_id,program_id) WHERE course_release_id IS NULL DO NOTHING;

CREATE TABLE institution_marketplace_offer (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institution_id bigint NOT NULL REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  assignment_id bigint NOT NULL,
  course_release_id bigint NOT NULL,
  program_id bigint NOT NULL,
  title_override varchar(200),
  description text,
  price_paise bigint NOT NULL CHECK (price_paise >= 0),
  currency varchar(3) NOT NULL DEFAULT 'INR' CHECK (currency='INR'),
  status varchar(16) NOT NULL DEFAULT 'DRAFT'
    CHECK (status IN ('DRAFT','IN_REVIEW','APPROVED','PUBLISHED','REJECTED','ARCHIVED')),
  rejection_reason varchar(500),
  created_by_institution_admin_id bigint NOT NULL,
  updated_by_institution_admin_id bigint,
  approved_by_institution_admin_id bigint,
  approved_at timestamptz,
  published_by_institution_admin_id bigint,
  published_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(assignment_id),
  UNIQUE(institution_id,course_release_id),
  FOREIGN KEY(assignment_id,institution_id,course_release_id,program_id)
    REFERENCES institution_course_assignment(id,institution_id,course_release_id,program_id) ON DELETE RESTRICT,
  FOREIGN KEY(course_release_id,program_id)
    REFERENCES institution_course_release(id,program_id) ON DELETE RESTRICT,
  FOREIGN KEY(institution_id,created_by_institution_admin_id)
    REFERENCES institution_admin_account(institution_id,id) ON DELETE RESTRICT,
  FOREIGN KEY(institution_id,updated_by_institution_admin_id)
    REFERENCES institution_admin_account(institution_id,id) ON DELETE RESTRICT,
  FOREIGN KEY(institution_id,approved_by_institution_admin_id)
    REFERENCES institution_admin_account(institution_id,id) ON DELETE RESTRICT,
  FOREIGN KEY(institution_id,published_by_institution_admin_id)
    REFERENCES institution_admin_account(institution_id,id) ON DELETE RESTRICT,
  CHECK ((status NOT IN ('APPROVED','PUBLISHED') OR
          (approved_by_institution_admin_id IS NOT NULL AND approved_at IS NOT NULL))),
  CHECK ((status<>'PUBLISHED') OR
         (published_by_institution_admin_id IS NOT NULL AND published_at IS NOT NULL)),
  CHECK ((status<>'REJECTED') OR rejection_reason IS NOT NULL),
  CHECK (title_override IS NULL OR length(btrim(title_override))>0)
);

CREATE INDEX idx_institution_marketplace_offer_discovery
  ON institution_marketplace_offer(institution_id,status,updated_at DESC)
  WHERE status='PUBLISHED';

CREATE TABLE institution_course_lifecycle_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institution_id bigint NOT NULL REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  course_release_id bigint REFERENCES institution_course_release(id) ON DELETE RESTRICT,
  assignment_id bigint REFERENCES institution_course_assignment(id) ON DELETE RESTRICT,
  offer_id bigint REFERENCES institution_marketplace_offer(id) ON DELETE RESTRICT,
  event_type varchar(40) NOT NULL,
  actor_platform_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  actor_institution_admin_id bigint,
  details jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(details)='object'),
  created_at timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY(institution_id,actor_institution_admin_id)
    REFERENCES institution_admin_account(institution_id,id) ON DELETE RESTRICT
);

CREATE INDEX idx_institution_course_lifecycle_event_tenant_time
  ON institution_course_lifecycle_event(institution_id,created_at DESC,id DESC);

