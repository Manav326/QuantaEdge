-- V175: authoritative HRMS-managed institution binding for Education Admin staff.
-- Employment (hr_employee/hr_organization), technical login identity (staff_account),
-- and institution tenancy remain separate identities. This table is the explicit bridge.
CREATE TABLE institution_staff_binding (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_id bigint NOT NULL REFERENCES staff_account(id) ON DELETE RESTRICT,
  institution_id bigint NOT NULL REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  status varchar(12) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','REVOKED')),
  assigned_by_staff_id bigint NOT NULL REFERENCES staff_account(id) ON DELETE RESTRICT,
  assigned_at timestamptz NOT NULL DEFAULT now(),
  revoked_by_staff_id bigint REFERENCES staff_account(id) ON DELETE RESTRICT,
  revoked_at timestamptz,
  reason varchar(500),
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (
    (status='ACTIVE' AND revoked_by_staff_id IS NULL AND revoked_at IS NULL)
    OR (status='REVOKED' AND revoked_by_staff_id IS NOT NULL AND revoked_at IS NOT NULL)
  )
);

-- A staff login can have at most one active institution. Reassignment is recorded by revoking
-- the old row and adding a new row; history is retained for audit.
CREATE UNIQUE INDEX uq_institution_staff_binding_active_staff
  ON institution_staff_binding(staff_id) WHERE status='ACTIVE';
CREATE INDEX idx_institution_staff_binding_tenant_active
  ON institution_staff_binding(institution_id,status,staff_id,assigned_at DESC);
CREATE INDEX idx_institution_staff_binding_staff_history
  ON institution_staff_binding(staff_id,assigned_at DESC,id DESC);

COMMENT ON TABLE institution_staff_binding IS
  'HRMS-managed binding from a technical Education Admin staff login to exactly one institution. This does not grant a role or permission; staff permissions remain separately checked per request.';
COMMENT ON COLUMN institution_staff_binding.staff_id IS
  'Technical login identity. The associated hr_employee row, when present, remains a separate employment record.';
COMMENT ON COLUMN institution_staff_binding.assigned_by_staff_id IS
  'HRMS platform-owner actor that assigned the staff login to this institution.';
COMMENT ON COLUMN institution_staff_binding.reason IS
  'Reason for assignment or reassignment; never a substitute for permission checks.';

