-- Persist retry progress separately from official assessment attempts and released marks.
CREATE TABLE student_assessment_question_practice_attempt (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_attempt_id BIGINT NOT NULL REFERENCES student_assessment_attempt(id) ON DELETE CASCADE,
  source_attempt_question_id BIGINT NOT NULL REFERENCES student_assessment_attempt_question(id) ON DELETE CASCADE,
  institution_id BIGINT NOT NULL,
  student_id BIGINT NOT NULL REFERENCES student(id),
  course_id BIGINT NOT NULL REFERENCES curriculum_program(id),
  practice_number INTEGER NOT NULL CHECK (practice_number > 0),
  response_payload JSONB NOT NULL,
  is_correct BOOLEAN NOT NULL,
  practiced_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_sa_question_practice_number UNIQUE (source_attempt_question_id, practice_number)
);

CREATE INDEX ix_sa_question_practice_progress
  ON student_assessment_question_practice_attempt
    (source_attempt_id, source_attempt_question_id, institution_id, student_id, course_id, practiced_at DESC);
