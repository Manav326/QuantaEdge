-- Legacy membership backfill is a one-time migration, so it cannot enroll future signups.
-- Never add QUANTA-EDGE membership to a learner who already has an active explicit institution.
INSERT INTO institution_membership(institution_id,student_id,status,joined_at,left_at,created_at,updated_at)
SELECT qe.id,st.id,'ACTIVE',now(),NULL,now(),now()
FROM institution_tenant qe
CROSS JOIN student st
WHERE qe.tenant_code='QUANTA-EDGE' AND st.active=true
  AND NOT EXISTS (
    SELECT 1 FROM institution_membership existing
    WHERE existing.student_id=st.id AND existing.status='ACTIVE'
  )
ON CONFLICT(institution_id,student_id) DO NOTHING;

INSERT INTO institution_membership_event(institution_id,membership_id,student_id,event_type,details)
SELECT m.institution_id,m.id,m.student_id,'MEMBERSHIP_CREATED',
  jsonb_build_object('source','V125_LEGACY_QUANTAEDGE_BACKFILL','actor','SYSTEM_MIGRATION')
FROM institution_membership m
JOIN institution_tenant t ON t.id=m.institution_id AND t.tenant_code='QUANTA-EDGE'
WHERE m.join_code_id IS NULL
  AND NOT EXISTS (
    SELECT 1 FROM institution_membership_event event
    WHERE event.membership_id=m.id AND event.event_type='MEMBERSHIP_CREATED'
  );

