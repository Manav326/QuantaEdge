create table staff_permission_grant (
  staff_id bigint not null references staff_account(id) on delete cascade,
  permission_key varchar(64) not null references staff_permission_catalog(permission_key),
  granted_by_staff_id bigint references staff_account(id) on delete set null,
  granted_at timestamptz not null default now(),
  primary key(staff_id, permission_key)
);

-- Preserve currently configured administrators as staff identities. Parent profiles remain user_account rows.
insert into staff_account(public_id, mobile_e164, display_name, role, active, created_at, updated_at)
select public_id, mobile_e164, coalesce(nullif(trim(display_name),''),'Administrator'), 'ADMIN', active, created_at, updated_at
from user_account
where role='ADMIN'
on conflict(mobile_e164) do nothing;

insert into staff_permission_grant(staff_id, permission_key)
select s.id, p.permission_key
from staff_account s
cross join staff_permission_catalog p
where s.role='ADMIN'
on conflict(staff_id, permission_key) do nothing;

-- Revoke sessions that were issued while an admin identity still used the user_account role.
-- Staff must establish a fresh session from the dedicated staff identity before using the console.
update auth_session s
set revoked_at=now()
where s.revoked_at is null
  and s.user_id in (
    select u.id
    from user_account u
    join staff_account staff on staff.mobile_e164=u.mobile_e164
    where u.role='ADMIN'
  );

-- An administrator identity is no longer also a parent/user role. Its original row is retained
-- for referential integrity and any guardian relations; normal parent authentication won't use it
-- for staff sign-in, which has the dedicated STAFF_LOGIN purpose.
update user_account set role='PARENT', updated_at=now() where role='ADMIN';

create table staff_audit_log (
  id bigint generated by default as identity primary key,
  actor_staff_id bigint references staff_account(id) on delete set null,
  actor_role varchar(32) not null,
  http_method varchar(12) not null,
  request_path varchar(500) not null,
  response_status integer not null,
  remote_address varchar(80),
  user_agent varchar(500),
  created_at timestamptz not null default now()
);

create index idx_staff_audit_created on staff_audit_log(created_at desc);
create index idx_staff_audit_actor_created on staff_audit_log(actor_staff_id, created_at desc);

-- Make the reviewer visible on the question itself as well as in the append-only staff activity trail.
alter table question
  add column if not exists reviewed_by_staff_id bigint references staff_account(id) on delete set null;

create index if not exists idx_question_reviewed_by_staff
  on question(reviewed_by_staff_id, reviewed_at desc)
  where reviewed_by_staff_id is not null;
