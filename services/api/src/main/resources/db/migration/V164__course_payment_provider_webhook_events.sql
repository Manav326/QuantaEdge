-- V164: idempotent, signature-verified Razorpay course payment/refund webhook inbox.
-- Event payloads are never stored raw; the table retains IDs, a SHA-256 digest, safe details and outcome.
CREATE TABLE course_payment_provider_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_event_id varchar(160) NOT NULL UNIQUE,
  event_type varchar(80) NOT NULL,
  course_payment_order_id bigint REFERENCES course_payment_order(id) ON DELETE RESTRICT,
  course_payment_refund_id bigint REFERENCES course_payment_refund(id) ON DELETE RESTRICT,
  provider_order_id varchar(100),
  provider_payment_id varchar(100),
  provider_refund_id varchar(100),
  payload_sha256 char(64) NOT NULL CHECK (payload_sha256 ~ '^[0-9a-f]{64}$'),
  processing_status varchar(32) NOT NULL DEFAULT 'PROCESSING'
    CHECK (processing_status IN ('PROCESSING','PROCESSED','IGNORED','UNMATCHED','RECONCILIATION_REQUIRED')),
  status_message varchar(1200) NOT NULL,
  details jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(details)='object'),
  received_at timestamptz NOT NULL DEFAULT now(),
  processed_at timestamptz,
  CHECK ((processing_status='PROCESSING' AND processed_at IS NULL)
      OR (processing_status<>'PROCESSING' AND processed_at IS NOT NULL))
);
CREATE INDEX idx_course_payment_provider_event_order
  ON course_payment_provider_event(course_payment_order_id,received_at DESC,id DESC);
CREATE INDEX idx_course_payment_provider_event_refund
  ON course_payment_provider_event(course_payment_refund_id,received_at DESC,id DESC);
CREATE INDEX idx_course_payment_provider_event_status
  ON course_payment_provider_event(processing_status,received_at DESC,id DESC);

CREATE OR REPLACE FUNCTION protect_course_payment_provider_event()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP='DELETE' THEN
    RAISE EXCEPTION 'Provider webhook evidence is immutable and cannot be deleted'
      USING ERRCODE='23514';
  END IF;
  IF ROW(NEW.provider_event_id,NEW.event_type,NEW.course_payment_order_id,
      NEW.course_payment_refund_id,NEW.provider_order_id,NEW.provider_payment_id,
      NEW.provider_refund_id,NEW.payload_sha256,NEW.received_at)
    IS DISTINCT FROM
    ROW(OLD.provider_event_id,OLD.event_type,OLD.course_payment_order_id,
      OLD.course_payment_refund_id,OLD.provider_order_id,OLD.provider_payment_id,
      OLD.provider_refund_id,OLD.payload_sha256,OLD.received_at) THEN
    RAISE EXCEPTION 'Provider webhook identity facts are immutable'
      USING ERRCODE='23514';
  END IF;
  IF OLD.processing_status<>'PROCESSING' THEN
    RAISE EXCEPTION 'A terminal provider webhook outcome is immutable'
      USING ERRCODE='23514';
  END IF;
  IF NEW.processing_status='PROCESSING' OR NEW.processed_at IS NULL THEN
    RAISE EXCEPTION 'A processing webhook must transition once to a terminal outcome'
      USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER trg_course_payment_provider_event_immutable
BEFORE UPDATE OR DELETE ON course_payment_provider_event
FOR EACH ROW EXECUTE FUNCTION protect_course_payment_provider_event();

INSERT INTO app_metadata(key,value)
VALUES ('schema','course-payment-provider-webhook-inbox-v164')
ON CONFLICT(key) DO UPDATE SET value=excluded.value;
