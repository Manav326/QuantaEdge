-- V101: additive adult-student account conversion and parent eligibility governance.
-- No DOB or identity-document payload is stored. Trusted staff records only a verification
-- reference hash and the verified-over-18 result; learner history remains keyed by student.id.

DO $role_check$
DECLARE c record;
BEGIN
  FOR c IN
    SELECT conname FROM pg_constraint
    WHERE conrelid='public.user_account'::regclass AND contype='c'
      AND pg_get_constraintdef(oid) ILIKE '%role%'
  LOOP
    EXECUTE format('ALTER TABLE public.user_account DROP CONSTRAINT %I',c.conname);
  END LOOP;
END;
$role_check$;

ALTER TABLE user_account
  ADD CONSTRAINT user_account_role_supported
  CHECK (role IN ('PARENT','ADMIN','LEARNER'));

ALTER TABLE student
  ADD COLUMN user_account_id bigint REFERENCES user_account(id) ON DELETE RESTRICT,
  ADD CONSTRAINT uq_student_user_account_id UNIQUE(user_account_id);

ALTER TABLE guardian_student
  ADD COLUMN access_level varchar(16) NOT NULL DEFAULT 'FULL'
    CHECK (access_level IN ('FULL','LIMITED'));

ALTER TABLE otp_challenge
  ADD COLUMN student_id bigint REFERENCES student(id) ON DELETE RESTRICT;

