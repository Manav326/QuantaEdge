-- V142: durable rich notifications, reusable content templates and recipient delivery state.
-- Content is versioned JSON data, never executable HTML. Media bytes live in private storage.

CREATE TABLE notification_template (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  owner_scope varchar(16) NOT NULL CHECK (owner_scope IN ('PLATFORM','INSTITUTION')),
  institution_id bigint REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  template_name varchar(120) NOT NULL CHECK (length(btrim(template_name)) BETWEEN 2 AND 120),
  description varchar(500),
  content_version integer NOT NULL DEFAULT 1 CHECK (content_version > 0),
  content_document jsonb NOT NULL CHECK (jsonb_typeof(content_document)='object'),
  status varchar(16) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','ACTIVE','ARCHIVED')),
  created_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  created_by_institution_admin_id bigint REFERENCES institution_admin_account(id) ON DELETE SET NULL,
  updated_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  updated_by_institution_admin_id bigint REFERENCES institution_admin_account(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_notification_template_owner CHECK (
    (owner_scope='PLATFORM' AND institution_id IS NULL)
    OR (owner_scope='INSTITUTION' AND institution_id IS NOT NULL)
  ),
  CONSTRAINT ck_notification_template_editor CHECK (
    (created_by_staff_id IS NOT NULL) OR (created_by_institution_admin_id IS NOT NULL)
  )
);

CREATE UNIQUE INDEX uq_notification_template_name_version
  ON notification_template(COALESCE(institution_id,0), lower(template_name), content_version)
  WHERE status<>'ARCHIVED';
CREATE INDEX idx_notification_template_scope
  ON notification_template(owner_scope,institution_id,status,updated_at DESC);

CREATE TABLE notification_media_asset (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  owner_scope varchar(16) NOT NULL CHECK (owner_scope IN ('PLATFORM','INSTITUTION')),
  institution_id bigint REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  storage_key varchar(700) NOT NULL UNIQUE,
  original_file_name varchar(180) NOT NULL,
  content_type varchar(64) NOT NULL CHECK (content_type IN (
    'image/jpeg','image/png','image/webp','image/gif','video/mp4','video/webm'
  )),
  sha256 varchar(64) NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
  byte_length bigint NOT NULL CHECK (byte_length>0 AND byte_length<=104857600),
  width integer CHECK (width IS NULL OR width BETWEEN 1 AND 12000),
  height integer CHECK (height IS NULL OR height BETWEEN 1 AND 12000),
  duration_seconds integer CHECK (duration_seconds IS NULL OR duration_seconds BETWEEN 0 AND 3600),
  status varchar(16) NOT NULL DEFAULT 'READY' CHECK (status IN ('PROCESSING','READY','REJECTED','REMOVED')),
  uploaded_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  uploaded_by_institution_admin_id bigint REFERENCES institution_admin_account(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  removed_at timestamptz,
  CONSTRAINT ck_notification_media_owner CHECK (
    (owner_scope='PLATFORM' AND institution_id IS NULL)
    OR (owner_scope='INSTITUTION' AND institution_id IS NOT NULL)
  ),
  CONSTRAINT ck_notification_media_uploader CHECK (
    uploaded_by_staff_id IS NOT NULL OR uploaded_by_institution_admin_id IS NOT NULL
  )
);
CREATE INDEX idx_notification_media_scope ON notification_media_asset(owner_scope,institution_id,status,created_at DESC);
CREATE INDEX idx_notification_media_sha ON notification_media_asset(sha256);

CREATE TABLE notification_campaign (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  scope varchar(20) NOT NULL CHECK (scope IN ('USER','COURSE','INSTITUTION','HRMS_PLATFORM')),
  institution_id bigint REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  course_id bigint REFERENCES curriculum_program(id) ON DELETE RESTRICT,
  template_id bigint REFERENCES notification_template(id) ON DELETE SET NULL,
  template_version integer,
  title varchar(180) NOT NULL CHECK (length(btrim(title)) BETWEEN 2 AND 180),
  summary varchar(400) NOT NULL CHECK (length(btrim(summary)) BETWEEN 1 AND 400),
  content_document jsonb NOT NULL CHECK (jsonb_typeof(content_document)='object'),
  audience_filter jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(audience_filter)='object'),
  audience_snapshot jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(audience_snapshot)='object'),
  sender_workspace varchar(24) NOT NULL CHECK (sender_workspace IN ('EDUCATION_ADMIN','HRMS','INSTITUTION_ADMIN','SYSTEM')),
  sender_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  sender_institution_admin_id bigint REFERENCES institution_admin_account(id) ON DELETE SET NULL,
  idempotency_key varchar(180) NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN (
    'DRAFT','PREVIEWED','SCHEDULED','QUEUED','PROCESSING','SENT',
    'PARTIALLY_FAILED','FAILED','CANCELLED','EXPIRED'
  )),
  scheduled_at timestamptz,
  expires_at timestamptz,
  resolved_recipient_count integer NOT NULL DEFAULT 0 CHECK (resolved_recipient_count>=0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  dispatched_at timestamptz,
  CONSTRAINT ck_notification_campaign_scope CHECK (
    (scope='USER' AND institution_id IS NOT NULL AND course_id IS NULL)
    OR (scope='COURSE' AND institution_id IS NOT NULL AND course_id IS NOT NULL)
    OR (scope='INSTITUTION' AND institution_id IS NOT NULL AND course_id IS NULL)
    OR (scope='HRMS_PLATFORM' AND course_id IS NULL)
  ),
  CONSTRAINT ck_notification_campaign_sender CHECK (
    sender_staff_id IS NOT NULL OR sender_institution_admin_id IS NOT NULL OR sender_workspace='SYSTEM'
  ),
  CONSTRAINT ck_notification_campaign_expiry CHECK (
    expires_at IS NULL OR scheduled_at IS NULL OR expires_at>scheduled_at
  ),
  UNIQUE(sender_workspace,idempotency_key)
);
CREATE INDEX idx_notification_campaign_scope_time ON notification_campaign(scope,institution_id,created_at DESC,id DESC);
CREATE INDEX idx_notification_campaign_dispatch ON notification_campaign(status,scheduled_at) WHERE status IN ('SCHEDULED','QUEUED','PROCESSING');

CREATE TABLE notification_recipient (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id bigint NOT NULL REFERENCES notification_campaign(id) ON DELETE RESTRICT,
  institution_id bigint REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  recipient_kind varchar(24) NOT NULL CHECK (recipient_kind IN ('STUDENT','USER_ACCOUNT','STAFF_ACCOUNT','INSTITUTION_ADMIN')),
  student_id bigint REFERENCES student(id) ON DELETE RESTRICT,
  user_account_id bigint REFERENCES user_account(id) ON DELETE RESTRICT,
  staff_account_id bigint REFERENCES staff_account(id) ON DELETE RESTRICT,
  institution_admin_id bigint REFERENCES institution_admin_account(id) ON DELETE RESTRICT,
  state varchar(16) NOT NULL DEFAULT 'CREATED' CHECK (state IN ('QUEUED','CREATED','READ','DISMISSED','FAILED')),
  created_at timestamptz NOT NULL DEFAULT now(),
  read_at timestamptz,
  dismissed_at timestamptz,
  failure_code varchar(64),
  CONSTRAINT ck_notification_recipient_identity CHECK (
    (recipient_kind='STUDENT' AND student_id IS NOT NULL AND user_account_id IS NULL AND staff_account_id IS NULL AND institution_admin_id IS NULL)
    OR (recipient_kind='USER_ACCOUNT' AND student_id IS NULL AND user_account_id IS NOT NULL AND staff_account_id IS NULL AND institution_admin_id IS NULL)
    OR (recipient_kind='STAFF_ACCOUNT' AND student_id IS NULL AND user_account_id IS NULL AND staff_account_id IS NOT NULL AND institution_admin_id IS NULL)
    OR (recipient_kind='INSTITUTION_ADMIN' AND student_id IS NULL AND user_account_id IS NULL AND staff_account_id IS NULL AND institution_admin_id IS NOT NULL)
  ),
  CONSTRAINT ck_notification_recipient_read CHECK (
    (state IN ('READ','DISMISSED') AND read_at IS NOT NULL) OR state NOT IN ('READ','DISMISSED')
  )
);
CREATE UNIQUE INDEX uq_notification_recipient_identity ON notification_recipient(
  campaign_id,recipient_kind,COALESCE(student_id,user_account_id,staff_account_id,institution_admin_id)
);
CREATE INDEX idx_notification_recipient_student ON notification_recipient(student_id,state,created_at DESC,id DESC) WHERE student_id IS NOT NULL;
CREATE INDEX idx_notification_recipient_user ON notification_recipient(user_account_id,state,created_at DESC,id DESC) WHERE user_account_id IS NOT NULL;
CREATE INDEX idx_notification_recipient_staff ON notification_recipient(staff_account_id,state,created_at DESC,id DESC) WHERE staff_account_id IS NOT NULL;
CREATE INDEX idx_notification_recipient_institution_admin ON notification_recipient(institution_admin_id,state,created_at DESC,id DESC) WHERE institution_admin_id IS NOT NULL;
CREATE INDEX idx_notification_recipient_tenant ON notification_recipient(institution_id,state,created_at DESC,id DESC);

CREATE TABLE notification_delivery_attempt (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipient_id bigint NOT NULL REFERENCES notification_recipient(id) ON DELETE RESTRICT,
  channel varchar(20) NOT NULL CHECK (channel IN ('IN_APP','ANDROID_PUSH','WEB_PUSH','EMAIL','SMS')),
  attempt_number integer NOT NULL CHECK (attempt_number>0),
  status varchar(16) NOT NULL CHECK (status IN ('PENDING','SENT','ACKNOWLEDGED','RETRYING','FAILED','NOT_CONFIGURED')),
  provider_reference varchar(240),
  failure_code varchar(64),
  attempted_at timestamptz NOT NULL DEFAULT now(),
  acknowledged_at timestamptz,
  UNIQUE(recipient_id,channel,attempt_number)
);
CREATE INDEX idx_notification_delivery_retry ON notification_delivery_attempt(channel,status,attempted_at);

CREATE TABLE notification_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id bigint REFERENCES notification_campaign(id) ON DELETE RESTRICT,
  template_id bigint REFERENCES notification_template(id) ON DELETE RESTRICT,
  institution_id bigint REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  actor_workspace varchar(24) NOT NULL,
  actor_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  actor_institution_admin_id bigint REFERENCES institution_admin_account(id) ON DELETE SET NULL,
  action_code varchar(48) NOT NULL,
  details jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(details)='object'),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_notification_audit_campaign ON notification_audit(campaign_id,created_at DESC,id DESC);
CREATE INDEX idx_notification_audit_tenant ON notification_audit(institution_id,created_at DESC,id DESC);

