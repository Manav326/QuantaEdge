-- V163: HRMS course-payment reconciliation history. The order ledger remains authoritative;
-- this append-only event ledger records operator investigation and recovery outcomes.
CREATE TABLE course_payment_operations_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_payment_order_id bigint NOT NULL
    REFERENCES course_payment_order(id) ON DELETE RESTRICT,
  actor_staff_id bigint NOT NULL REFERENCES staff_account(id) ON DELETE RESTRICT,
  event_type varchar(40) NOT NULL CHECK (event_type IN (
    'RECONCILIATION_REQUESTED','RECONCILIATION_SUCCEEDED','RECONCILIATION_PENDING',
    'RECONCILIATION_RETRYABLE','RECONCILIATION_FAILED','ACTION_BLOCKED')),
  resolution_code varchar(64) NOT NULL,
  message varchar(1200) NOT NULL,
  provider_order_id varchar(100),
  provider_status varchar(40),
  idempotency_key varchar(80) NOT NULL UNIQUE,
  details jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(details)='object'),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_course_payment_operations_order_history
  ON course_payment_operations_event(course_payment_order_id,created_at DESC,id DESC);
CREATE INDEX idx_course_payment_operations_resolution
  ON course_payment_operations_event(event_type,resolution_code,created_at DESC);
CREATE TRIGGER trg_course_payment_operations_event_immutable
BEFORE UPDATE OR DELETE ON course_payment_operations_event
FOR EACH ROW EXECUTE FUNCTION reject_billing_financial_mutation();

INSERT INTO app_metadata(key,value)
VALUES ('schema','course-payment-operations-audit-v163')
ON CONFLICT(key) DO UPDATE SET value=excluded.value;
