-- V9: market-ready learning/content coverage model.
-- This migration deliberately separates source coverage from QuantaEdge-authored pedagogy.
-- Nothing is promoted to SOURCE_BACKED merely because a lesson shell exists.

alter table question add column if not exists source_kind varchar(40) not null default 'AUTHOR_CREATED';
alter table question add column if not exists source_title varchar(300);
alter table question add column if not exists source_ref varchar(200);
alter table question add column if not exists source_year integer;
alter table question add column if not exists board varchar(100);
alter table question add column if not exists marks integer;
alter table question add column if not exists exam_format varchar(60);
alter table question add column if not exists topic varchar(200);
alter table question add column if not exists subtopic varchar(200);
alter table question add column if not exists skill varchar(80);
alter table question add column if not exists tags jsonb not null default '[]'::jsonb;

alter table question drop constraint if exists question_question_type_check;
alter table question add constraint question_question_type_check check (
  question_type in (
    'MCQ','TRUE_FALSE','INPUT','MATCH','ORDER','ASSERTION_REASON',
    'CASE_BASED','SHORT_ANSWER','LONG_ANSWER','NUMERICAL',
    'DIAGRAM','MAP','SOURCE_BASED'
  )
);

create table if not exists content_source (
  id bigint generated by default as identity primary key,
  source_kind varchar(40) not null,
  title varchar(300) not null,
  provider varchar(200) not null,
  source_url varchar(1000),
  edition varchar(120),
  language varchar(40) not null default 'hi',
  source_year integer,
  accessed_at timestamptz not null default now(),
  checksum varchar(128),
  status varchar(30) not null default 'REFERENCE',
  unique(source_kind,title,edition)
);

create table if not exists chapter_source (
  chapter_id bigint not null references curriculum_chapter(id) on delete cascade,
  source_id bigint not null references content_source(id) on delete cascade,
  source_chapter_no integer,
  source_chapter_title varchar(300),
  source_locator varchar(300),
  coverage_type varchar(40) not null default 'CURRICULUM',
  coverage_status varchar(30) not null default 'MAPPED',
  notes text,
  primary key(chapter_id,source_id,coverage_type)
);

create table if not exists chapter_concept (
  id bigint generated by default as identity primary key,
  chapter_id bigint not null references curriculum_chapter(id) on delete cascade,
  code varchar(100) not null,
  title varchar(300) not null,
  description text,
  prerequisite_codes jsonb not null default '[]'::jsonb,
  concept_order integer not null default 0,
  source_refs jsonb not null default '[]'::jsonb,
  status varchar(30) not null default 'AUTHORING_REQUIRED',
  unique(chapter_id,code)
);

create table if not exists lesson_requirement (
  id bigint generated by default as identity primary key,
  chapter_id bigint not null references curriculum_chapter(id) on delete cascade,
  requirement_code varchar(80) not null,
  required boolean not null default true,
  min_count integer not null default 1,
  description varchar(500) not null,
  unique(chapter_id,requirement_code)
);

create table if not exists question_source_tag (
  id bigint generated by default as identity primary key,
  question_id bigint not null references question(id) on delete cascade,
  tag varchar(100) not null,
  unique(question_id,tag)
);

