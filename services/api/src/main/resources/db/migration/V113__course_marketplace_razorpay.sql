-- V113: paid course marketplace and idempotent Razorpay settlement.
-- No listings or prices are seeded: an authorised administrator must explicitly publish each offer.

CREATE TABLE course_marketplace_offer (
  course_id bigint PRIMARY KEY REFERENCES curriculum_program(id) ON DELETE RESTRICT,
  title_override varchar(200),
  description text,
  price_paise bigint NOT NULL CHECK (price_paise >= 0),
  currency varchar(3) NOT NULL DEFAULT 'INR' CHECK (currency ~ '^[A-Z]{3}$'),
  status varchar(16) NOT NULL DEFAULT 'DRAFT'
    CHECK (status IN ('DRAFT','PUBLISHED','ARCHIVED')),
  created_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  updated_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (title_override IS NULL OR length(btrim(title_override)) > 0)
);

CREATE INDEX idx_course_marketplace_offer_status
  ON course_marketplace_offer(status, updated_at DESC);

CREATE TABLE course_payment_order (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id bigint NOT NULL REFERENCES student(id) ON DELETE RESTRICT,
  course_id bigint NOT NULL REFERENCES curriculum_program(id) ON DELETE RESTRICT,
  offer_price_paise bigint NOT NULL CHECK (offer_price_paise > 0),
  currency varchar(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
  receipt varchar(40) NOT NULL UNIQUE,
  provider_order_id varchar(100) UNIQUE,
  provider_payment_id varchar(100) UNIQUE,
  provider_signature varchar(128),
  status varchar(16) NOT NULL DEFAULT 'CREATING'
    CHECK (status IN ('CREATING','PENDING','VERIFIED','FAILED','EXPIRED')),
  failure_code varchar(60),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  verified_at timestamptz
);

-- Avoid two simultaneously payable orders for the same learner/course.
-- A stale pending order is expired before a replacement order is created.
CREATE UNIQUE INDEX uq_course_payment_order_open
  ON course_payment_order(student_id, course_id)
  WHERE status IN ('CREATING','PENDING');

CREATE INDEX idx_course_payment_order_student
  ON course_payment_order(student_id, created_at DESC);

CREATE TABLE course_purchase (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id bigint NOT NULL REFERENCES student(id) ON DELETE RESTRICT,
  course_id bigint NOT NULL REFERENCES curriculum_program(id) ON DELETE RESTRICT,
  order_id bigint NOT NULL UNIQUE REFERENCES course_payment_order(id) ON DELETE RESTRICT,
  provider_payment_id varchar(100) NOT NULL UNIQUE,
  amount_paise bigint NOT NULL CHECK (amount_paise > 0),
  currency varchar(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
  purchased_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (student_id, course_id)
);

CREATE INDEX idx_course_purchase_student
  ON course_purchase(student_id, purchased_at DESC);
