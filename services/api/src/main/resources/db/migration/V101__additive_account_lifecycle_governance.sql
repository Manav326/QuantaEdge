CREATE TABLE student_adult_verification (
  student_id bigint PRIMARY KEY REFERENCES student(id) ON DELETE RESTRICT,
  status varchar(16) NOT NULL DEFAULT 'PENDING'
    CHECK (status IN ('PENDING','VERIFIED','REJECTED','EXPIRED')),
  verification_reference_hash varchar(64),
  reviewed_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  reviewed_at timestamptz,
  expires_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (status='PENDING' OR
    (verification_reference_hash IS NOT NULL AND reviewed_by_staff_id IS NOT NULL AND reviewed_at IS NOT NULL)),
  CHECK (status<>'VERIFIED' OR expires_at IS NOT NULL)
);

CREATE INDEX idx_student_adult_verification_status
  ON student_adult_verification(status,expires_at,student_id);

CREATE TABLE user_parent_eligibility (
  user_id bigint PRIMARY KEY REFERENCES user_account(id) ON DELETE RESTRICT,
  status varchar(16) NOT NULL DEFAULT 'PENDING'
    CHECK (status IN ('PENDING','VERIFIED','REJECTED','EXPIRED')),
  verification_reference_hash varchar(64),
  reviewed_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  reviewed_at timestamptz,
  expires_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (status='PENDING' OR
    (verification_reference_hash IS NOT NULL AND reviewed_by_staff_id IS NOT NULL AND reviewed_at IS NOT NULL)),
  CHECK (status<>'VERIFIED' OR expires_at IS NOT NULL)
);

CREATE INDEX idx_user_parent_eligibility_status
  ON user_parent_eligibility(status,expires_at,user_id);

CREATE TABLE account_lifecycle_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_type varchar(48) NOT NULL CHECK (event_type IN (
    'ADULT_VERIFICATION_UPDATED','STUDENT_BECAME_INDEPENDENT',
    'PARENT_ELIGIBILITY_UPDATED','LEARNER_BECAME_PARENT'
  )),
  student_id bigint REFERENCES student(id) ON DELETE SET NULL,
  user_id bigint REFERENCES user_account(id) ON DELETE SET NULL,
  actor_user_id bigint REFERENCES user_account(id) ON DELETE SET NULL,
  actor_student_id bigint REFERENCES student(id) ON DELETE SET NULL,
  actor_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  old_role varchar(30),
  new_role varchar(30),
  verification_reference_hash varchar(64),
  details jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_account_lifecycle_audit_student
  ON account_lifecycle_audit(student_id,created_at DESC,id DESC);
CREATE INDEX idx_account_lifecycle_audit_user
  ON account_lifecycle_audit(user_id,created_at DESC,id DESC);

CREATE OR REPLACE FUNCTION protect_account_lifecycle_role_transition()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE linked_student_id bigint;
BEGIN
  IF OLD.role='PARENT' AND NEW.role='LEARNER' THEN
    RAISE EXCEPTION 'Parent-to-learner role reversal is prohibited'
      USING ERRCODE='23514';
  END IF;

  IF OLD.role='LEARNER' AND NEW.role='PARENT' THEN
    SELECT st.id INTO linked_student_id
    FROM student st
    WHERE st.user_account_id=OLD.id AND st.active=true
    FOR UPDATE;

    IF linked_student_id IS NULL OR NOT EXISTS (
      SELECT 1 FROM student_adult_verification av
      WHERE av.student_id=linked_student_id AND av.status='VERIFIED' AND av.expires_at>now()
    ) OR NOT EXISTS (
      SELECT 1 FROM user_parent_eligibility pe
      WHERE pe.user_id=OLD.id AND pe.status='VERIFIED' AND pe.expires_at>now()
    ) THEN
      RAISE EXCEPTION 'Verified adult and parent eligibility checks are required before parent conversion'
        USING ERRCODE='23514';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_protect_account_lifecycle_role_transition
BEFORE UPDATE OF role ON user_account
FOR EACH ROW EXECUTE FUNCTION protect_account_lifecycle_role_transition();

