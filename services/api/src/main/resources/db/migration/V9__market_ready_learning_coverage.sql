-- Every canonical chapter gets an explicit audit contract.
insert into lesson_requirement(chapter_id,requirement_code,required,min_count,description)
select ch.id, v.code, true, v.min_count, v.description
from curriculum_chapter ch
join curriculum_subject s on s.id=ch.subject_id
join curriculum_class c on c.id=s.class_id
cross join (values
 ('PREREQUISITE',1,'पूर्व ज्ञान जाँच'),
 ('EXPLANATION',1,'स्पष्ट हिन्दी में अवधारणा व्याख्या'),
 ('WORKED_EXAMPLE',1,'शिक्षक-शैली worked example'),
 ('GUIDED_PRACTICE',1,'Guided practice'),
 ('INDEPENDENT_PRACTICE',1,'Independent practice'),
 ('RECAP',1,'Chapter recap'),
 ('VISUAL_OR_NOT_REQUIRED',1,'Visual decision recorded'),
 ('NCERT_OR_TEXTBOOK_MAPPING',1,'NCERT/SCERT textbook mapping'),
 ('BOARD_FORMAT_COVERAGE',1,'Board-format question coverage'),
 ('SOURCE_TAGGED_QUESTIONS',1,'Source/year/format tagged questions')
) v(code,min_count,description)
where c.code in ('6','7','8') and s.code in ('maths','science') and ch.active=true
on conflict(chapter_id,requirement_code) do update set
 required=excluded.required,min_count=excluded.min_count,description=excluded.description;

