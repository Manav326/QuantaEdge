CREATE TABLE course_expiry_policy (
  course_identity_id bigint PRIMARY KEY
    REFERENCES institution_course_identity(id) ON DELETE RESTRICT,
  policy_mode varchar(24) NOT NULL
    CHECK (policy_mode IN ('CALENDAR_DURATION','FIXED_DAYS')),
  calendar_years integer,
  calendar_months integer,
  calendar_days integer,
  fixed_days integer,
  policy_version bigint NOT NULL DEFAULT 1 CHECK (policy_version > 0),
  updated_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  change_note text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (
    (policy_mode='CALENDAR_DURATION'
      AND calendar_years IS NOT NULL AND calendar_years >= 0
      AND calendar_months IS NOT NULL AND calendar_months >= 0
      AND calendar_days IS NOT NULL AND calendar_days >= 0
      AND (calendar_years + calendar_months + calendar_days) > 0
      AND fixed_days IS NULL)
    OR
    (policy_mode='FIXED_DAYS'
      AND fixed_days IS NOT NULL AND fixed_days BETWEEN 1 AND 36500
      AND calendar_years IS NULL AND calendar_months IS NULL AND calendar_days IS NULL)
  )
);

