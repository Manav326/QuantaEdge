-- V213: one shared expiry policy per logical course identity, per-enrollment access controls,
-- and immutable audit history. Existing enrollments are deliberately grandfathered: no expiry
-- is backfilled and configuring a policy affects only future/reactivated enrollments.
ALTER TABLE student_program_enrollment
  ADD COLUMN course_identity_id bigint REFERENCES institution_course_identity(id) ON DELETE RESTRICT,
  ADD COLUMN course_expires_at timestamptz,
  ADD COLUMN course_access_blocked boolean NOT NULL DEFAULT false,
  ADD COLUMN course_access_blocked_at timestamptz,
  ADD COLUMN course_access_blocked_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  ADD COLUMN course_expiry_policy_version_snapshot bigint,
  ADD COLUMN course_expiry_mode_snapshot varchar(24),
  ADD COLUMN course_expiry_years_snapshot integer,
  ADD COLUMN course_expiry_months_snapshot integer,
  ADD COLUMN course_expiry_days_snapshot integer,
  ADD COLUMN course_expiry_fixed_days_snapshot integer,
  ADD CONSTRAINT ck_student_enrollment_expiry_snapshot_mode
    CHECK (course_expiry_mode_snapshot IS NULL
      OR course_expiry_mode_snapshot IN ('CALENDAR_DURATION','FIXED_DAYS')),
  ADD CONSTRAINT ck_student_enrollment_expiry_snapshot_values
    CHECK (
      (course_expiry_mode_snapshot IS NULL
        AND course_expiry_policy_version_snapshot IS NULL
        AND course_expiry_years_snapshot IS NULL
        AND course_expiry_months_snapshot IS NULL
        AND course_expiry_days_snapshot IS NULL
        AND course_expiry_fixed_days_snapshot IS NULL)
      OR
      (course_expiry_mode_snapshot='CALENDAR_DURATION'
        AND course_expiry_policy_version_snapshot IS NOT NULL
        AND course_expiry_policy_version_snapshot > 0
        AND course_expiry_years_snapshot IS NOT NULL AND course_expiry_years_snapshot >= 0
        AND course_expiry_months_snapshot IS NOT NULL AND course_expiry_months_snapshot >= 0
        AND course_expiry_days_snapshot IS NOT NULL AND course_expiry_days_snapshot >= 0
        AND (course_expiry_years_snapshot + course_expiry_months_snapshot
             + course_expiry_days_snapshot) > 0
        AND course_expiry_fixed_days_snapshot IS NULL)
      OR
      (course_expiry_mode_snapshot='FIXED_DAYS'
        AND course_expiry_policy_version_snapshot IS NOT NULL
        AND course_expiry_policy_version_snapshot > 0
        AND course_expiry_years_snapshot IS NULL
        AND course_expiry_months_snapshot IS NULL
        AND course_expiry_days_snapshot IS NULL
        AND course_expiry_fixed_days_snapshot > 0)
    ),
  ADD CONSTRAINT ck_student_enrollment_access_block_consistent
    CHECK (
      (course_access_blocked=false AND course_access_blocked_at IS NULL
        AND course_access_blocked_by_staff_id IS NULL)
      OR
      (course_access_blocked=true AND course_access_blocked_at IS NOT NULL)
    );

-- Backfill identity only; never infer an expiry for existing learner records.
UPDATE student_program_enrollment e
SET course_identity_id=p.course_identity_id
FROM curriculum_program p
WHERE p.id=e.program_id
  AND p.course_identity_id IS NOT NULL
  AND e.course_identity_id IS NULL;

CREATE INDEX idx_student_program_enrollment_identity_access
  ON student_program_enrollment(course_identity_id,institution_id,status,course_access_blocked,course_expires_at);

CREATE TABLE course_expiry_policy (
  course_identity_id bigint PRIMARY KEY
    REFERENCES institution_course_identity(id) ON DELETE RESTRICT,
  policy_mode varchar(24) NOT NULL
    CHECK (policy_mode IN ('CALENDAR_DURATION','FIXED_DAYS')),
  calendar_years integer,
  calendar_months integer,
  calendar_days integer,
  fixed_days integer,
  policy_version bigint NOT NULL DEFAULT 1 CHECK (policy_version > 0),
  updated_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  change_note text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (
    (policy_mode='CALENDAR_DURATION'
      AND calendar_years IS NOT NULL AND calendar_years >= 0
      AND calendar_months IS NOT NULL AND calendar_months >= 0
      AND calendar_days IS NOT NULL AND calendar_days >= 0
      AND (calendar_years + calendar_months + calendar_days) > 0
      AND fixed_days IS NULL)
    OR
    (policy_mode='FIXED_DAYS'
      AND fixed_days IS NOT NULL AND fixed_days BETWEEN 1 AND 36500
      AND calendar_years IS NULL AND calendar_months IS NULL AND calendar_days IS NULL)
  )
);

CREATE TABLE course_expiry_policy_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_identity_id bigint NOT NULL
    REFERENCES institution_course_identity(id) ON DELETE RESTRICT,
  event_type varchar(24) NOT NULL CHECK (event_type IN ('POLICY_CREATED','POLICY_UPDATED')),
  policy_version bigint NOT NULL CHECK (policy_version > 0),
  previous_policy jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(previous_policy)='object'),
  new_policy jsonb NOT NULL CHECK (jsonb_typeof(new_policy)='object'),
  notes text NOT NULL CHECK (length(btrim(notes)) BETWEEN 3 AND 1000),
  actor_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_course_expiry_policy_event_identity
  ON course_expiry_policy_event(course_identity_id,created_at DESC,id DESC);

CREATE TABLE course_enrollment_access_event (
