-- V177: establish a type-driven course definition and generic assessment-pack hierarchy.
-- Existing courses are classified from their current curriculum shape; this migration does not
-- rename course IDs or move any legacy learner/assessment history.
CREATE TABLE course_type_registry (
  code varchar(32) PRIMARY KEY CHECK (code ~ '^[A-Z][A-Z0-9_]{1,31}$'),
  display_name varchar(120) NOT NULL CHECK (length(btrim(display_name))>0),
  layout_schema_version varchar(40) NOT NULL,
  hierarchy_schema jsonb NOT NULL CHECK (jsonb_typeof(hierarchy_schema)='object'),
  requires_curriculum_class boolean NOT NULL DEFAULT false,
  status varchar(16) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','DEPRECATED')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

