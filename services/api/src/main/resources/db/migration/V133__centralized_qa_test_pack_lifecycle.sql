-- V133: audited, run-scoped QA test-pack ownership. No fixture data is seeded here.
-- The QA engine uses typed pack builders and exact manifest IDs; no arbitrary SQL is accepted.
CREATE TABLE qa_test_run (
  run_id uuid PRIMARY KEY,
  pack_key varchar(80) NOT NULL,
  pack_version integer NOT NULL CHECK (pack_version > 0),
  idempotency_key varchar(120) NOT NULL,
  state varchar(24) NOT NULL CHECK (state IN (
    'INSTALLING','INSTALLED','INSTALL_FAILED','UNINSTALLING','UNINSTALL_BLOCKED','UNINSTALLED'
  )),
  environment_label varchar(80) NOT NULL,
  target_database_label varchar(120) NOT NULL,
  source_commit_sha varchar(64),
  pack_definition_sha256 char(64) NOT NULL,
  created_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  planned_resource_count integer NOT NULL DEFAULT 0 CHECK (planned_resource_count >= 0),
  created_resource_count integer NOT NULL DEFAULT 0 CHECK (created_resource_count >= 0),
  cleaned_resource_count integer NOT NULL DEFAULT 0 CHECK (cleaned_resource_count >= 0),
  protected_baseline jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(protected_baseline)='object'),
  cleanup_report jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(cleanup_report)='object'),
  error_code varchar(64),
  error_summary varchar(1000),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  installed_at timestamptz,
  uninstalled_at timestamptz,
  UNIQUE(pack_key,pack_version,idempotency_key)
);
CREATE INDEX idx_qa_test_run_recent ON qa_test_run(created_at DESC,run_id);
CREATE INDEX idx_qa_test_run_state_recent ON qa_test_run(state,updated_at DESC);

CREATE TABLE qa_test_run_resource (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id uuid NOT NULL REFERENCES qa_test_run(run_id) ON DELETE RESTRICT,
  resource_key varchar(180) NOT NULL,
  resource_kind varchar(48) NOT NULL CHECK (resource_kind IN (
    'INSTITUTION','INSTITUTION_BRANDING','USER_ACCOUNT','STUDENT','GUARDIAN_STUDENT',
    'INSTITUTION_USER_MEMBERSHIP','INSTITUTION_MEMBERSHIP','STUDENT_LOGIN_CREDENTIAL',
    'STUDENT_TRACK_ENROLLMENT','STUDENT_LESSON_PROGRESS','STUDENT_QUESTION_ATTEMPT'
  )),
  resource_id varchar(160) NOT NULL,
  resource_ref jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(resource_ref)='object'),
  dependency_keys text[] NOT NULL DEFAULT ARRAY[]::text[],
  cleanup_order integer NOT NULL CHECK (cleanup_order >= 0),
  state varchar(20) NOT NULL DEFAULT 'OWNED'
    CHECK (state IN ('OWNED','CLEANUP_PENDING','CLEANED','FAILED')),
  created_at timestamptz NOT NULL DEFAULT now(),
  cleaned_at timestamptz,
  cleanup_detail jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(cleanup_detail)='object'),
  UNIQUE(run_id,resource_key)
);
CREATE INDEX idx_qa_test_run_resource_cleanup
  ON qa_test_run_resource(run_id,state,cleanup_order,id);

CREATE TABLE qa_test_run_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id uuid NOT NULL REFERENCES qa_test_run(run_id) ON DELETE RESTRICT,
  event_type varchar(48) NOT NULL,
  from_state varchar(24),
  to_state varchar(24),
  actor_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  details jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(details)='object'),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_qa_test_run_event_time ON qa_test_run_event(run_id,created_at,id);

