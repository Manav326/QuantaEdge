-- V70: retain prior certificate artifacts and audit safe corrections to the rendered certificate.
ALTER TABLE student_certificate
  ADD COLUMN artifact_version integer NOT NULL DEFAULT 1 CHECK (artifact_version >= 1);

CREATE TABLE student_certificate_artifact_revision (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  certificate_id bigint NOT NULL REFERENCES student_certificate(id) ON DELETE RESTRICT,
  revision integer NOT NULL CHECK (revision >= 1),
  artifact_version integer NOT NULL CHECK (artifact_version >= 1),
  achievement_title varchar(240) NOT NULL,
  achievement_summary varchar(600) NOT NULL,
  achievement_snapshot jsonb NOT NULL,
  pdf_storage_key varchar(80) NOT NULL UNIQUE,
  png_storage_key varchar(80) NOT NULL UNIQUE,
  pdf_sha256 char(64) NOT NULL CHECK (pdf_sha256 ~ '^[a-f0-9]{64}$'),
  png_sha256 char(64) NOT NULL CHECK (png_sha256 ~ '^[a-f0-9]{64}$'),
  pdf_size_bytes bigint NOT NULL CHECK (pdf_size_bytes > 0),
  png_size_bytes bigint NOT NULL CHECK (png_size_bytes > 0),
  correction_reason varchar(500) NOT NULL,
  archived_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(certificate_id, revision)
);
CREATE INDEX idx_certificate_artifact_revision_history
  ON student_certificate_artifact_revision(certificate_id, revision DESC);

ALTER TABLE certificate_audit_log DROP CONSTRAINT certificate_audit_log_action_check;
ALTER TABLE certificate_audit_log
  ADD CONSTRAINT certificate_audit_log_action_check
  CHECK (action IN ('ISSUED','REVOCATION_REQUESTED','REVOKED','ARTIFACT_CORRECTED'));

INSERT INTO app_metadata(key, value)
VALUES ('schema', 'certificate-artifact-revisions-v60')
ON CONFLICT (key) DO UPDATE SET value = excluded.value;
