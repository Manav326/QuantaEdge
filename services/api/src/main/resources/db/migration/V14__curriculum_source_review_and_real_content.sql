-- V14: add source registry, curriculum audit contracts, structured answers,
-- and stop serving generated lesson shells as if they were complete teaching content.

alter table question
  add column if not exists marks integer,
  add column if not exists exam_format varchar(40),
  add column if not exists topic varchar(200),
  add column if not exists subtopic varchar(200),
  add column if not exists skill varchar(200),
  add column if not exists answer_payload jsonb not null default '{}'::jsonb;

alter table question drop constraint if exists question_question_type_check;
alter table question add constraint question_question_type_check
  check (question_type in (
    'MCQ','TRUE_FALSE','INPUT','MATCH','ORDER','ASSERTION_REASON',
    'CASE_BASED','SHORT_ANSWER','LONG_ANSWER','NUMERICAL','SOURCE_BASED'
  ));

create table if not exists content_source (
  id bigint generated by default as identity primary key,
  source_kind varchar(40) not null,
  title varchar(300) not null,
  provider varchar(200),
  source_url text,
  edition varchar(160) not null default 'UNVERIFIED',
  language varchar(20) not null default 'hi',
  source_year integer,
  checksum varchar(64),
  status varchar(30) not null default 'REFERENCE',
  accessed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(source_kind,title,edition)
);

create table if not exists chapter_source (
  id bigint generated by default as identity primary key,
  chapter_id bigint not null references curriculum_chapter(id) on delete cascade,
  source_id bigint not null references content_source(id) on delete restrict,
  source_chapter_no integer,
  coverage_status varchar(30) not null default 'NEEDS_REVIEW',
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(chapter_id,source_id)
);

create table if not exists chapter_concept (
  id bigint generated by default as identity primary key,
  chapter_id bigint not null references curriculum_chapter(id) on delete cascade,
  code varchar(100) not null,
  title varchar(240) not null,
  description text,
  concept_order integer not null default 1,
  status varchar(30) not null default 'AUTHORING_REQUIRED',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(chapter_id,code),
  check(status in ('AUTHORING_REQUIRED','DRAFT','REVIEW','READY_FOR_REVIEW','PUBLISHED','ARCHIVED'))
);

create table if not exists lesson_requirement (
  id bigint generated by default as identity primary key,
  chapter_id bigint not null references curriculum_chapter(id) on delete cascade,
  requirement_code varchar(80) not null,
  description varchar(500) not null,
  min_count integer not null default 1,
  required boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(chapter_id,requirement_code),
  check(min_count >= 0)
);

create index if not exists idx_content_source_status on content_source(status,source_kind);
create index if not exists idx_chapter_source_coverage on chapter_source(chapter_id,coverage_status);
create index if not exists idx_chapter_concept_chapter_status on chapter_concept(chapter_id,status);
create index if not exists idx_lesson_requirement_chapter_required on lesson_requirement(chapter_id,required);

create or replace function strip_answer_keys(value jsonb)
returns jsonb
language sql
immutable
parallel safe
as $$
  select case jsonb_typeof(value)
    when 'object' then (
      select coalesce(jsonb_object_agg(e.key, strip_answer_keys(e.value)), '{}'::jsonb)
      from jsonb_each(value) as e(key,value)
      where e.key not in (
        'correctOption','correct','is_correct','answer','answer_payload',
        'answerKey','correct_answer','solution'
      )
    )
    when 'array' then (
      select coalesce(jsonb_agg(strip_answer_keys(a.value)), '[]'::jsonb)
      from jsonb_array_elements(value) as a(value)
    )
    else value
  end
$$;

