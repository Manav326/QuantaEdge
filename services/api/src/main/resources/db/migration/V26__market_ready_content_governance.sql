-- V26: align the schema with the market-ready features without seeding generic questions as real content.
-- Source entries are candidate references only. Chapter/page coverage stays NEEDS_REVIEW
-- until an editor checks the exact downloaded edition and printed/PDF page references.

alter table chapter_source
  add column if not exists source_chapter_title varchar(300),
  add column if not exists source_locator varchar(300),
  add column if not exists coverage_type varchar(40) not null default 'CURRICULUM_CANDIDATE';

alter table chapter_source
  drop constraint if exists chapter_source_chapter_id_source_id_key;
create unique index if not exists uq_chapter_source_coverage_type
  on chapter_source(chapter_id,source_id,coverage_type);

alter table chapter_concept
  add column if not exists prerequisite_codes jsonb not null default '[]'::jsonb,
  add column if not exists source_refs jsonb not null default '[]'::jsonb;

alter table question
  drop constraint if exists question_question_type_check;
alter table question
  add constraint question_question_type_check check (question_type in (
    'MCQ','TRUE_FALSE','INPUT','MATCH','ORDER','ASSERTION_REASON',
    'CASE_BASED','SHORT_ANSWER','LONG_ANSWER','NUMERICAL','DIAGRAM','MAP','SOURCE_BASED'
  ));

alter table lesson_block
  drop constraint if exists lesson_block_block_type_check;
alter table lesson_block
  add constraint lesson_block_block_type_check check (block_type in (
    'EXPLANATION','IMAGE','DIAGRAM','VIDEO','QUESTION','MCQ','TRUE_FALSE','MATCH','ORDER',
    'INPUT','HINT','AI_HELP','SUMMARY','CHALLENGE','PREREQUISITE','WORKED_EXAMPLE',
    'GUIDED_PRACTICE','INDEPENDENT_PRACTICE','RECAP'
  ));

create table if not exists question_source_tag (
  id bigint generated by default as identity primary key,
  question_id bigint not null references question(id) on delete cascade,
  tag varchar(100) not null,
  unique(question_id,tag)
);

-- Minimum editorial coverage targets, not pre-created questions. Optional formats
-- remain explicitly optional until the chapter editor records that the format fits.
create table if not exists chapter_assessment_requirement (
  id bigint generated by default as identity primary key,
  chapter_id bigint not null references curriculum_chapter(id) on delete cascade,
  question_type varchar(40) not null,
  minimum_count integer not null default 1,
  required boolean not null default true,
  rationale varchar(500) not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(chapter_id,question_type),
  check(minimum_count >= 0),
  check(question_type in (
    'MCQ','TRUE_FALSE','INPUT','MATCH','ORDER','ASSERTION_REASON','CASE_BASED',
    'SHORT_ANSWER','LONG_ANSWER','NUMERICAL','DIAGRAM','MAP','SOURCE_BASED'
  ))
);

