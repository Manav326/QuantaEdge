-- Extended HR: recruitment, configurable performance reviews, asset custody and exit clearance.
-- All records are organisation-scoped and retain history; no employee or candidate data is seeded.
create table hr_vacancy (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references hr_organization(id) on delete restrict,
  title varchar(160) not null,
  department_id bigint references hr_department(id) on delete restrict,
  description text not null,
  employment_type_code varchar(32) references hr_employment_type(code) on delete restrict,
  vacancy_status varchar(20) not null default 'DRAFT' check (vacancy_status in ('DRAFT','OPEN','ON_HOLD','CLOSED','CANCELLED')),
  openings integer not null default 1 check (openings between 1 and 10000),
  published_at timestamptz,
  closes_at timestamptz,
  created_by_staff_id bigint references staff_account(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (closes_at is null or published_at is null or closes_at >= published_at)
);
create index idx_hr_vacancy_org_status on hr_vacancy(organization_id,vacancy_status,created_at desc);

create table hr_candidate (
  id bigint generated by default as identity primary key,
  public_id uuid not null unique default gen_random_uuid(),
  organization_id bigint not null references hr_organization(id) on delete restrict,
  vacancy_id bigint references hr_vacancy(id) on delete restrict,
  full_name varchar(160) not null,
  email varchar(254),
  phone_e164 varchar(24),
  resume_document_ref varchar(500),
  application_notes text,
  pipeline_stage varchar(24) not null default 'APPLIED' check (pipeline_stage in ('APPLIED','SCREENING','INTERVIEW','OFFER','HIRED','REJECTED','WITHDRAWN')),
  hiring_decision varchar(20) not null default 'PENDING' check (hiring_decision in ('PENDING','APPROVED','DECLINED')),
  converted_employee_id bigint unique references hr_employee(id) on delete restrict,
  created_by_staff_id bigint references staff_account(id) on delete set null,
  updated_by_staff_id bigint references staff_account(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (email is null or position('@' in email)>1)
);
create index idx_hr_candidate_org_stage on hr_candidate(organization_id,pipeline_stage,created_at desc);

create table hr_candidate_evaluation (
  id bigint generated by default as identity primary key,
  candidate_id bigint not null references hr_candidate(id) on delete restrict,
  evaluation_type varchar(24) not null check (evaluation_type in ('INTERVIEW','ASSESSMENT','REFERENCE','HIRING_DECISION','NOTE')),
  scheduled_at timestamptz,
  evaluator_staff_id bigint references staff_account(id) on delete set null,
  score numeric(7,2),
  outcome varchar(24),
  notes text,
  created_at timestamptz not null default now()
);
create index idx_hr_candidate_evaluation on hr_candidate_evaluation(candidate_id,created_at desc);

create table hr_performance_cycle (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references hr_organization(id) on delete restrict,
  name varchar(160) not null,
  start_date date not null,
  end_date date not null,
  due_date date,
  cycle_status varchar(20) not null default 'DRAFT' check (cycle_status in ('DRAFT','OPEN','IN_REVIEW','CLOSED','CANCELLED')),
  evaluation_schema jsonb not null default '{"fields":[{"key":"achievements","label":"Achievements","type":"text","required":true},{"key":"development","label":"Development areas","type":"text","required":true}]}'::jsonb,
  created_by_staff_id bigint references staff_account(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (end_date >= start_date),
  check (due_date is null or due_date >= start_date),
  unique(organization_id,name)
);
create table hr_employee_goal (
  id bigint generated by default as identity primary key,
  cycle_id bigint not null references hr_performance_cycle(id) on delete restrict,
  employee_id bigint not null references hr_employee(id) on delete restrict,
  title varchar(200) not null,
  description text,
  success_measure text,
  target_date date,
  goal_status varchar(20) not null default 'ACTIVE' check (goal_status in ('ACTIVE','COMPLETED','CANCELLED')),
  created_by_staff_id bigint references staff_account(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index idx_hr_employee_goal_employee on hr_employee_goal(employee_id,cycle_id,goal_status);
create table hr_performance_review (
  id bigint generated by default as identity primary key,
  cycle_id bigint not null references hr_performance_cycle(id) on delete restrict,
  employee_id bigint not null references hr_employee(id) on delete restrict,
  reviewer_employee_id bigint references hr_employee(id) on delete restrict,
  self_assessment jsonb not null default '{}'::jsonb,
  manager_assessment jsonb not null default '{}'::jsonb,
  rating numeric(5,2),
  review_status varchar(20) not null default 'DRAFT' check (review_status in ('DRAFT','SUBMITTED','ACKNOWLEDGED','APPROVED','RETURNED')),
  submitted_at timestamptz,
  approved_by_staff_id bigint references staff_account(id) on delete set null,
  approved_at timestamptz,
  created_by_staff_id bigint references staff_account(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(cycle_id,employee_id)
);
create index idx_hr_performance_review_reviewer on hr_performance_review(reviewer_employee_id,review_status);

create table hr_asset (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references hr_organization(id) on delete restrict,
  asset_tag varchar(80) not null,
  asset_type varchar(80) not null,
  description varchar(500),
  serial_number varchar(160),
  asset_status varchar(20) not null default 'AVAILABLE' check (asset_status in ('AVAILABLE','ASSIGNED','MAINTENANCE','MISSING','RETIRED')),
  condition_status varchar(20) not null default 'GOOD' check (condition_status in ('NEW','GOOD','FAIR','DAMAGED','UNKNOWN')),
  acquired_on date,
  retired_at timestamptz,
  created_by_staff_id bigint references staff_account(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(organization_id,asset_tag)
);
create table hr_asset_assignment (
  id bigint generated by default as identity primary key,
  asset_id bigint not null references hr_asset(id) on delete restrict,
  employee_id bigint not null references hr_employee(id) on delete restrict,
  assigned_at timestamptz not null default now(),
  assigned_by_staff_id bigint references staff_account(id) on delete set null,
  condition_on_assignment varchar(20) not null default 'GOOD' check (condition_on_assignment in ('NEW','GOOD','FAIR','DAMAGED','UNKNOWN')),
  assignment_note varchar(1000),
  returned_at timestamptz,
  returned_by_staff_id bigint references staff_account(id) on delete set null,
  condition_on_return varchar(20) check (condition_on_return is null or condition_on_return in ('NEW','GOOD','FAIR','DAMAGED','UNKNOWN')),
  return_note varchar(1000),
  created_at timestamptz not null default now(),
  check (returned_at is null or returned_at >= assigned_at)
);
create unique index uq_hr_asset_current_assignment on hr_asset_assignment(asset_id) where returned_at is null;
create index idx_hr_asset_assignment_employee on hr_asset_assignment(employee_id,assigned_at desc);

create table hr_employee_exit (
  id bigint generated by default as identity primary key,
  employee_id bigint not null unique references hr_employee(id) on delete restrict,
  initiated_by_staff_id bigint references staff_account(id) on delete set null,
  initiated_at timestamptz not null default now(),
  exit_type varchar(24) not null check (exit_type in ('RESIGNATION','RETIREMENT','END_OF_CONTRACT','TERMINATION','OTHER')),
  requested_last_working_date date not null,
  approved_last_working_date date,
  notice_period_days integer check (notice_period_days is null or notice_period_days between 0 and 3650),
  exit_status varchar(20) not null default 'REQUESTED' check (exit_status in ('REQUESTED','UNDER_REVIEW','APPROVED','CLEARANCE','READY_FOR_SETTLEMENT','COMPLETED','CANCELLED')),
  reason text,
  hr_notes text,
  final_settlement_status varchar(20) not null default 'NOT_STARTED' check (final_settlement_status in ('NOT_STARTED','INPUTS_READY','IN_PROGRESS','SETTLED','ON_HOLD')),
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (approved_last_working_date is null or approved_last_working_date >= requested_last_working_date - make_interval(days => coalesce(notice_period_days,0)))
);
create table hr_exit_checklist_item (
  id bigint generated by default as identity primary key,
  exit_id bigint not null references hr_employee_exit(id) on delete restrict,
  item_key varchar(80) not null,
  title varchar(200) not null,
  owner_role varchar(40) not null default 'HR',
  item_status varchar(16) not null default 'PENDING' check (item_status in ('PENDING','IN_PROGRESS','CLEARED','WAIVED')),
  notes varchar(1000),
  completed_by_staff_id bigint references staff_account(id) on delete set null,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  unique(exit_id,item_key)
);
create table hr_extended_event (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references hr_organization(id) on delete restrict,
  entity_type varchar(32) not null,
  entity_id bigint not null,
  event_type varchar(48) not null,
  actor_staff_id bigint references staff_account(id) on delete set null,
  reason varchar(1000),
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index idx_hr_extended_event_entity on hr_extended_event(entity_type,entity_id,created_at desc);

