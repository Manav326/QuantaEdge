update question q
set answer_payload=jsonb_build_object(
  'kind','OPTION',
  'value',(select qo.option_key from question_option qo where qo.question_id=q.id and qo.is_correct order by qo.sort_order limit 1)
)
where q.question_type in ('MCQ','TRUE_FALSE')
  and q.answer_payload='{}'::jsonb
  and exists(select 1 from question_option qo where qo.question_id=q.id and qo.is_correct);

