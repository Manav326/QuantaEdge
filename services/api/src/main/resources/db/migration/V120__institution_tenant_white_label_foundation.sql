-- V120: institution tenancy, white-label metadata, client principals and billable enrollment ledger.
-- Institution customers are deliberately separate from hr_employee, staff_account, user_account
-- and student identities. No synthetic institution/student/financial data is seeded.

CREATE TABLE institution_tenant (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id uuid NOT NULL UNIQUE,
  tenant_code varchar(32) NOT NULL UNIQUE
    CHECK (tenant_code ~ '^[A-Z0-9][A-Z0-9_-]{2,31}$'),
  display_name varchar(180) NOT NULL,
  legal_name varchar(220),
  status varchar(16) NOT NULL DEFAULT 'DRAFT'
    CHECK (status IN ('DRAFT','ACTIVE','SUSPENDED','CLOSED')),
  status_reason varchar(500),
  created_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  updated_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  activated_at timestamptz,
  suspended_at timestamptz,
  closed_at timestamptz
);

CREATE INDEX idx_institution_tenant_status
  ON institution_tenant(status, lower(display_name), id);

CREATE TABLE institution_admin_account (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institution_id bigint NOT NULL REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  username varchar(64) NOT NULL
    CHECK (username ~ '^[a-zA-Z0-9][a-zA-Z0-9._-]{2,63}$'),
  display_name varchar(120) NOT NULL,
  password_hash varchar(100) NOT NULL,
  active boolean NOT NULL DEFAULT true,
  must_change_password boolean NOT NULL DEFAULT true,
  created_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  last_login_at timestamptz,
  password_changed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(institution_id, id)
);

CREATE UNIQUE INDEX uq_institution_admin_username_lower
  ON institution_admin_account(lower(username));

CREATE INDEX idx_institution_admin_tenant_active
  ON institution_admin_account(institution_id, active, id);

CREATE TABLE institution_admin_session (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institution_admin_id bigint NOT NULL REFERENCES institution_admin_account(id) ON DELETE CASCADE,
  institution_id bigint NOT NULL REFERENCES institution_tenant(id) ON DELETE CASCADE,
  access_token_hash varchar(128) NOT NULL UNIQUE,
  refresh_token_hash varchar(128) NOT NULL UNIQUE,
  client_type varchar(12) NOT NULL DEFAULT 'WEB' CHECK (client_type IN ('WEB','ANDROID')),
  expires_at timestamptz NOT NULL,
  refresh_expires_at timestamptz NOT NULL,
  absolute_expires_at timestamptz NOT NULL,
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  revoked_at timestamptz,
  CHECK (refresh_expires_at <= absolute_expires_at),
  CHECK (expires_at <= absolute_expires_at)
);

CREATE INDEX idx_institution_admin_session_active
  ON institution_admin_session(institution_id, institution_admin_id, expires_at)
  WHERE revoked_at IS NULL;
CREATE INDEX idx_institution_admin_session_refresh
  ON institution_admin_session(refresh_expires_at, revoked_at)
  WHERE revoked_at IS NULL;

CREATE TABLE institution_branding (
  institution_id bigint PRIMARY KEY REFERENCES institution_tenant(id) ON DELETE CASCADE,
  display_name varchar(180) NOT NULL,
  logo_asset_key varchar(500),
  app_icon_asset_key varchar(500),
  store_listing_url varchar(1000),
  theme_tokens jsonb NOT NULL DEFAULT '{}'::jsonb
    CHECK (jsonb_typeof(theme_tokens) = 'object'),
  version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
  updated_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE institution_course_entitlement (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institution_id bigint NOT NULL REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  program_id bigint NOT NULL REFERENCES curriculum_program(id) ON DELETE RESTRICT,
  status varchar(12) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','REVOKED')),
  valid_from timestamptz NOT NULL DEFAULT now(),
  valid_until timestamptz,
  granted_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  revoked_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (valid_until IS NULL OR valid_until > valid_from),
  UNIQUE(institution_id, program_id)
);

CREATE INDEX idx_institution_course_entitlement_active
  ON institution_course_entitlement(institution_id, status, program_id);

CREATE TABLE institution_join_code (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institution_id bigint NOT NULL REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  code_hash varchar(128) NOT NULL UNIQUE,
  encrypted_code text NOT NULL,
  code_hint varchar(12) NOT NULL,
  status varchar(12) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','REVOKED','EXPIRED')),
  expires_at timestamptz,
  use_limit bigint CHECK (use_limit IS NULL OR use_limit > 0),
  redeemed_count bigint NOT NULL DEFAULT 0 CHECK (redeemed_count >= 0),
  created_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  revoked_at timestamptz,
  CHECK (use_limit IS NULL OR redeemed_count <= use_limit)
);

CREATE UNIQUE INDEX uq_institution_join_code_one_active
  ON institution_join_code(institution_id) WHERE status='ACTIVE';
CREATE INDEX idx_institution_join_code_tenant
  ON institution_join_code(institution_id, status, expires_at);

CREATE TABLE institution_membership (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institution_id bigint NOT NULL REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  student_id bigint NOT NULL REFERENCES student(id) ON DELETE RESTRICT,
  join_code_id bigint REFERENCES institution_join_code(id) ON DELETE SET NULL,
  status varchar(12) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','SUSPENDED','LEFT')),
  joined_at timestamptz NOT NULL DEFAULT now(),
  left_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(institution_id, student_id),
  CHECK ((status='LEFT' AND left_at IS NOT NULL) OR (status<>'LEFT' AND left_at IS NULL))
);

CREATE INDEX idx_institution_membership_roster
  ON institution_membership(institution_id, status, joined_at DESC, id DESC);
CREATE INDEX idx_institution_membership_student
  ON institution_membership(student_id, status, institution_id);

CREATE TABLE institution_membership_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institution_id bigint NOT NULL REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  membership_id bigint REFERENCES institution_membership(id) ON DELETE RESTRICT,
  student_id bigint REFERENCES student(id) ON DELETE RESTRICT,
  join_code_id bigint REFERENCES institution_join_code(id) ON DELETE SET NULL,
  event_type varchar(32) NOT NULL CHECK (event_type IN (
    'MEMBERSHIP_CREATED','MEMBERSHIP_REACTIVATED','MEMBERSHIP_SUSPENDED',
    'MEMBERSHIP_LEFT','JOIN_CODE_REDEEMED','COURSE_ENTITLEMENT_CHANGED',
    'TENANT_STATUS_CHANGED','BRANDING_CHANGED','ADMIN_ACCOUNT_CREATED',
    'ADMIN_ACCOUNT_SUSPENDED','JOIN_CODE_VIEWED','REPORT_VIEWED'
  )),
  actor_platform_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  actor_institution_admin_id bigint REFERENCES institution_admin_account(id) ON DELETE SET NULL,
  actor_student_id bigint REFERENCES student(id) ON DELETE SET NULL,
  details jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(details)='object'),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_institution_membership_event_tenant_time
  ON institution_membership_event(institution_id, created_at DESC, id DESC);
CREATE INDEX idx_institution_membership_event_student_time
  ON institution_membership_event(student_id, created_at DESC, id DESC);

CREATE TABLE institution_billing_contract (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institution_id bigint NOT NULL REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  currency char(3) NOT NULL DEFAULT 'INR' CHECK (currency ~ '^[A-Z]{3}$'),
  unit_price_paise bigint NOT NULL CHECK (unit_price_paise >= 0),
  billing_cadence varchar(12) NOT NULL DEFAULT 'MONTHLY' CHECK (billing_cadence IN ('MONTHLY','ANNUAL')),
  billable_rule varchar(48) NOT NULL DEFAULT 'FIRST_ACTIVE_MEMBERSHIP_PER_PERIOD'
    CHECK (billable_rule IN ('FIRST_ACTIVE_MEMBERSHIP_PER_PERIOD')),
  effective_from date NOT NULL,
  effective_until date,
  active boolean NOT NULL DEFAULT true,
  created_by_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (effective_until IS NULL OR effective_until >= effective_from)
);

CREATE UNIQUE INDEX uq_institution_billing_contract_active
  ON institution_billing_contract(institution_id) WHERE active=true;
CREATE INDEX idx_institution_billing_contract_effective
  ON institution_billing_contract(institution_id, effective_from, effective_until);

CREATE TABLE institution_billable_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institution_id bigint NOT NULL REFERENCES institution_tenant(id) ON DELETE RESTRICT,
  membership_id bigint NOT NULL REFERENCES institution_membership(id) ON DELETE RESTRICT,
  student_id bigint NOT NULL REFERENCES student(id) ON DELETE RESTRICT,
  contract_id bigint NOT NULL REFERENCES institution_billing_contract(id) ON DELETE RESTRICT,
  billing_period_start date NOT NULL,
  billing_period_end date NOT NULL,
  event_type varchar(12) NOT NULL CHECK (event_type IN ('CHARGE','CREDIT')),
  amount_paise bigint NOT NULL CHECK (amount_paise >= 0),
  currency char(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
  idempotency_key varchar(180) NOT NULL UNIQUE,
  reverses_event_id bigint REFERENCES institution_billable_event(id) ON DELETE RESTRICT,
  description varchar(300) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (billing_period_end >= billing_period_start),
  CHECK ((event_type='CHARGE' AND reverses_event_id IS NULL) OR event_type='CREDIT')
);

CREATE UNIQUE INDEX uq_institution_membership_charge_period
  ON institution_billable_event(membership_id, billing_period_start) WHERE event_type='CHARGE';
CREATE INDEX idx_institution_billable_event_period
  ON institution_billable_event(institution_id, billing_period_start, event_type, created_at);

-- Ledger rows are accounting evidence. Corrections must be represented as compensating CREDITs.
CREATE OR REPLACE FUNCTION reject_institution_billable_event_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'Institution billable events are append-only; add a compensating event instead'
    USING ERRCODE='23514';
END;
$$;

CREATE TRIGGER trg_institution_billable_event_immutable
BEFORE UPDATE OR DELETE ON institution_billable_event
FOR EACH ROW EXECUTE FUNCTION reject_institution_billable_event_mutation();

CREATE TABLE institution_auth_failure (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username_hash varchar(128) NOT NULL,
  attempted_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_institution_auth_failure_recent
  ON institution_auth_failure(username_hash, attempted_at DESC);

CREATE TABLE institution_join_attempt (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_hash varchar(128) NOT NULL,
  attempted_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_institution_join_attempt_recent
  ON institution_join_attempt(source_hash, attempted_at DESC);

CREATE TABLE institution_audit_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institution_id bigint REFERENCES institution_tenant(id) ON DELETE SET NULL,
  actor_platform_staff_id bigint REFERENCES staff_account(id) ON DELETE SET NULL,
  actor_institution_admin_id bigint REFERENCES institution_admin_account(id) ON DELETE SET NULL,
  action varchar(80) NOT NULL,
  target_type varchar(48) NOT NULL,
  target_id varchar(120),
  details jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(details)='object'),
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (num_nonnulls(actor_platform_staff_id, actor_institution_admin_id) <= 1)
);

CREATE INDEX idx_institution_audit_log_tenant_time
  ON institution_audit_log(institution_id, created_at DESC, id DESC);

