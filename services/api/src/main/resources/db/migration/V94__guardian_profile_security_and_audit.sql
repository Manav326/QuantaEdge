-- V94: version guardian consent, preserve child-profile lifecycle history, and harden sign-in.
ALTER TABLE guardian_student
  ADD COLUMN IF NOT EXISTS consent_version varchar(80),
  ADD COLUMN IF NOT EXISTS consent_source varchar(40) NOT NULL DEFAULT 'LEGACY',
  ADD COLUMN IF NOT EXISTS consented_by bigint REFERENCES user_account(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS revoked_at timestamptz;

-- Explicitly mark historical consent records as legacy; do not invent an old consent version.
UPDATE guardian_student SET consent_version='legacy-unversioned'
WHERE consent_status='CONSENTED' AND consent_version IS NULL;
UPDATE guardian_student SET consented_by=guardian_user_id
WHERE consent_status='CONSENTED' AND consented_by IS NULL;

CREATE TABLE IF NOT EXISTS guardian_student_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guardian_user_id bigint REFERENCES user_account(id) ON DELETE SET NULL,
  student_id bigint NOT NULL REFERENCES student(id) ON DELETE RESTRICT,
  event_type varchar(40) NOT NULL CHECK (event_type IN (
    'CONSENT_ACCEPTED','CONSENT_REVOKED','PROFILE_UPDATED','CLASS_PROMOTED',
    'CREDENTIALS_CHANGED','TRACKS_UPDATED','CHILD_ARCHIVED','CHILD_RESTORED'
  )),
  consent_version varchar(80),
  actor_user_id bigint REFERENCES user_account(id) ON DELETE SET NULL,
  old_class_code varchar(20),
  new_class_code varchar(20),
  details jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_guardian_student_audit_history
  ON guardian_student_audit(guardian_user_id,student_id,created_at DESC);
CREATE INDEX IF NOT EXISTS idx_guardian_student_audit_events
  ON guardian_student_audit(event_type,created_at DESC);

CREATE TABLE IF NOT EXISTS guardian_child_creation_request (
  guardian_user_id bigint NOT NULL REFERENCES user_account(id) ON DELETE CASCADE,
  request_key uuid NOT NULL,
  student_id bigint NOT NULL REFERENCES student(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(guardian_user_id,request_key)
);
CREATE INDEX IF NOT EXISTS idx_guardian_child_creation_student ON guardian_child_creation_request(student_id);

-- Password-login throttling stores only hashed principal identifiers, never raw identity fields.
CREATE TABLE IF NOT EXISTS account_login_failure (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  principal_hash varchar(64) NOT NULL,
  auth_type varchar(16) NOT NULL CHECK (auth_type IN ('PARENT','STUDENT')),
  attempted_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_account_login_failure_recent
  ON account_login_failure(principal_hash,auth_type,attempted_at DESC);

