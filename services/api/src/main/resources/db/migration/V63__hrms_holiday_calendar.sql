-- HRMS official holiday calendar; dates are organisation-specific and never fabricated.
create table hr_holiday_calendar (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references hr_organization(id) on delete restrict,
  holiday_date date not null,
  name varchar(120) not null,
  description varchar(500),
  region varchar(80),
  active boolean not null default true,
  created_by_staff_id bigint references staff_account(id) on delete set null,
  updated_by_staff_id bigint references staff_account(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (length(trim(name)) > 0)
);
create unique index uq_hr_holiday_active_date on hr_holiday_calendar(organization_id,holiday_date) where active=true;
create index idx_hr_holiday_org_date on hr_holiday_calendar(organization_id,holiday_date) where active=true;
insert into staff_permission_catalog(permission_key,display_name,description) values
 ('HR_HOLIDAY_VIEW','View holiday calendar','View organisation holidays and dates.'),
 ('HR_HOLIDAY_MANAGE','Manage holiday calendar','Add and deactivate official organisation holidays.')
on conflict(permission_key) do update set display_name=excluded.display_name,description=excluded.description;
