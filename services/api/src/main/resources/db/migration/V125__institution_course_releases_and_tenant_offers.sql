-- Give the legacy QuantaEdge institution a deterministic source release for the course masters
-- that existed at migration time. LEGACY_MIGRATED releases are deliberately NOT shareable; an
-- origin admin and content reviewer must run the new approval workflow before HRMS can redistribute.
INSERT INTO institution_course_release(
  source_institution_id,program_id,release_version,release_state,content_fingerprint,
  legacy_migration,legacy_migration_note
)
SELECT qe.id,p.id,1,'LEGACY_MIGRATED',
  md5(concat_ws('|',p.id::text,p.code,p.display_name,p.curriculum_version)),
  true,'Created by V125 from the pre-existing global course master; requires a new approval before sharing.'
FROM institution_tenant qe
JOIN curriculum_program p ON p.code<>'GENERAL'
WHERE qe.tenant_code='QUANTA-EDGE'
  AND (
    p.status='ACTIVE'
    OR EXISTS (SELECT 1 FROM course_marketplace_offer o WHERE o.course_id=p.id)
    OR EXISTS (SELECT 1 FROM course_purchase cp WHERE cp.course_id=p.id)
    OR EXISTS (SELECT 1 FROM student_course_access_grant g WHERE g.course_id=p.id)
    OR EXISTS (SELECT 1 FROM institution_course_entitlement e WHERE e.program_id=p.id)
  )
ON CONFLICT(source_institution_id,program_id,release_version) DO NOTHING;

-- Preserve explicit historical destination assignments; all other current non-GENERAL course
-- masters belong to QUANTA-EDGE's legacy catalogue but remain non-shareable until reviewed.
INSERT INTO institution_course_assignment(institution_id,course_release_id,status,assignment_source,assigned_by_staff_id,revoked_by_staff_id,revoked_at)
SELECT old_entitlement.institution_id,release.id,
  CASE WHEN old_entitlement.status='ACTIVE' THEN 'ASSIGNED' ELSE 'REVOKED' END,
  'LEGACY_ENTITLEMENT_MIGRATION',
  old_entitlement.granted_by_staff_id,
  old_entitlement.revoked_by_staff_id,
  CASE WHEN old_entitlement.status='REVOKED' THEN coalesce(old_entitlement.updated_at,now()) ELSE NULL END
FROM institution_course_entitlement old_entitlement
JOIN institution_tenant qe ON qe.tenant_code='QUANTA-EDGE'
JOIN institution_course_release release
  ON release.source_institution_id=qe.id
  AND release.program_id=old_entitlement.program_id
  AND release.release_version=1
ON CONFLICT(institution_id,course_release_id) DO NOTHING;

INSERT INTO institution_course_entitlement(institution_id,program_id,status,valid_from,granted_by_staff_id)
SELECT qe.id,p.id,'ACTIVE',now(),NULL
FROM institution_tenant qe
JOIN curriculum_program p ON p.status='ACTIVE' AND p.code<>'GENERAL'
WHERE qe.tenant_code='QUANTA-EDGE'
ON CONFLICT(institution_id,program_id) DO NOTHING;

INSERT INTO institution_course_assignment(institution_id,course_release_id,status,assignment_source)
SELECT qe.id,release.id,'ASSIGNED','LEGACY_QUANTAEDGE_CATALOG'
FROM institution_tenant qe
JOIN institution_course_release release ON release.source_institution_id=qe.id AND release.release_version=1
JOIN institution_course_entitlement old_entitlement
  ON old_entitlement.institution_id=qe.id AND old_entitlement.program_id=release.program_id
  AND old_entitlement.status='ACTIVE'
WHERE qe.tenant_code='QUANTA-EDGE'
ON CONFLICT(institution_id,course_release_id) DO NOTHING;

-- Keep only QuantaEdge's pre-existing offers visible in its own tenant. Other tenants receive no
-- new marketplace listing just because a platform-wide offer existed.
INSERT INTO institution_marketplace_offer(
  institution_id,assignment_id,course_release_id,course_id,title_override,description,
  price_paise,currency,status,legacy_migration,legacy_migration_note,published_at
)
SELECT qe.id,assignment.id,release.id,legacy.course_id,legacy.title_override,legacy.description,
  legacy.price_paise,legacy.currency,
  CASE legacy.status WHEN 'PUBLISHED' THEN 'PUBLISHED' WHEN 'ARCHIVED' THEN 'ARCHIVED' ELSE 'DRAFT' END,
  true,'Preserved pre-V125 QUANTA-EDGE global offer state; review local approval on next edit.',
  CASE WHEN legacy.status='PUBLISHED' THEN legacy.updated_at ELSE NULL END
FROM institution_tenant qe
JOIN institution_course_release release ON release.source_institution_id=qe.id AND release.release_version=1
JOIN institution_course_assignment assignment
  ON assignment.institution_id=qe.id AND assignment.course_release_id=release.id AND assignment.status='ASSIGNED'
JOIN course_marketplace_offer legacy ON legacy.course_id=release.program_id
WHERE qe.tenant_code='QUANTA-EDGE'
ON CONFLICT(institution_id,assignment_id) DO NOTHING;

-- Map current pre-existing direct marketplace/payment history to the tenant whose data the
-- deployment was running as. A historical row never grants access to a different institution.
UPDATE student_course_access_grant g
SET institution_id=qe.id
FROM institution_tenant qe
WHERE qe.tenant_code='QUANTA-EDGE' AND g.institution_id IS NULL;

UPDATE course_payment_order o
SET institution_id=qe.id
FROM institution_tenant qe
WHERE qe.tenant_code='QUANTA-EDGE' AND o.institution_id IS NULL;

UPDATE course_purchase cp
SET institution_id=coalesce(
  (SELECT po.institution_id FROM course_payment_order po WHERE po.id=cp.order_id),
  qe.id
)
FROM institution_tenant qe
WHERE qe.tenant_code='QUANTA-EDGE' AND cp.institution_id IS NULL;

UPDATE course_entitlement ce
SET institution_id=coalesce(
  (SELECT cp.institution_id FROM course_purchase cp WHERE cp.id=ce.source_purchase_id),
  qe.id
)
FROM institution_tenant qe
WHERE qe.tenant_code='QUANTA-EDGE' AND ce.institution_id IS NULL;

UPDATE parent_course_purchase_request r
SET institution_id=qe.id
FROM institution_tenant qe
WHERE qe.tenant_code='QUANTA-EDGE' AND r.institution_id IS NULL;

UPDATE course_payment_order o
SET institution_offer_id=offer.id
FROM institution_marketplace_offer offer
WHERE o.institution_offer_id IS NULL AND offer.institution_id=o.institution_id AND offer.course_id=o.course_id;

UPDATE course_purchase cp
SET institution_offer_id=coalesce(cp.institution_offer_id,o.institution_offer_id)
FROM course_payment_order o
WHERE cp.order_id=o.id AND cp.institution_offer_id IS NULL;

UPDATE parent_course_purchase_request r
SET institution_offer_id=offer.id
FROM institution_marketplace_offer offer
WHERE r.institution_offer_id IS NULL AND offer.institution_id=r.institution_id
  AND offer.course_id=r.course_id AND offer.status='PUBLISHED';

