-- V51: bilingual content editions and modular curriculum programs.
-- Existing rows, learner progress, assessment history, and published assets are retained.
-- Translations are immutable source revisions: source_hash + version_no records history.
-- Only APPROVED/PUBLISHED translations with a matching current source hash may be delivered.

ALTER TABLE curriculum_subject
  ADD CONSTRAINT uq_curriculum_subject_id_class UNIQUE (id, class_id);

CREATE TABLE curriculum_program (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_id bigint NOT NULL REFERENCES curriculum_class(id) ON DELETE RESTRICT,
  code varchar(60) NOT NULL,
  display_name varchar(200) NOT NULL,
  stream_code varchar(60),
  curriculum_version varchar(120) NOT NULL DEFAULT 'CURRENT',
  status varchar(20) NOT NULL DEFAULT 'DRAFT'
    CHECK (status IN ('DRAFT','ACTIVE','ARCHIVED')),
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (class_id, code, curriculum_version),
  UNIQUE (id, class_id),
  CHECK (stream_code IS NULL OR length(btrim(stream_code)) > 0)
);

CREATE INDEX idx_curriculum_program_class_status
  ON curriculum_program(class_id, status, code);

CREATE TABLE curriculum_program_subject (
  program_id bigint NOT NULL,
  class_id bigint NOT NULL,
  subject_id bigint NOT NULL,
  is_required boolean NOT NULL DEFAULT true,
  sort_order integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (program_id, subject_id),
  CONSTRAINT fk_program_subject_program_class
    FOREIGN KEY (program_id, class_id)
    REFERENCES curriculum_program(id, class_id) ON DELETE CASCADE,
  CONSTRAINT fk_program_subject_subject_class
    FOREIGN KEY (subject_id, class_id)
    REFERENCES curriculum_subject(id, class_id) ON DELETE RESTRICT
);

CREATE INDEX idx_curriculum_program_subject_subject
  ON curriculum_program_subject(subject_id, program_id);

CREATE TABLE student_program_enrollment (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id bigint NOT NULL REFERENCES student(id) ON DELETE CASCADE,
  program_id bigint NOT NULL REFERENCES curriculum_program(id) ON DELETE RESTRICT,
  status varchar(20) NOT NULL DEFAULT 'ACTIVE'
    CHECK (status IN ('ACTIVE','PAUSED','ENDED')),
  enrolled_at timestamptz NOT NULL DEFAULT now(),
  ended_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (student_id, program_id),
  CHECK ((status <> 'ENDED') OR ended_at IS NOT NULL)
);

CREATE UNIQUE INDEX uq_student_single_active_program
  ON student_program_enrollment(student_id)
  WHERE status = 'ACTIVE';

CREATE INDEX idx_student_program_enrollment_program
  ON student_program_enrollment(program_id, status, student_id);

-- Backward-compatible default programs for existing classes; stream selection remains optional.
INSERT INTO curriculum_program(class_id, code, display_name, stream_code, curriculum_version, status)
SELECT id, 'GENERAL', 'General', NULL, 'CURRENT', 'ACTIVE'
FROM curriculum_class
WHERE active = true
ON CONFLICT(class_id, code, curriculum_version) DO NOTHING;

INSERT INTO curriculum_program_subject(program_id, class_id, subject_id, is_required, sort_order)
SELECT p.id, s.class_id, s.id, true, s.sort_order
FROM curriculum_program p
JOIN curriculum_subject s ON s.class_id = p.class_id AND s.active = true
WHERE p.code = 'GENERAL' AND p.curriculum_version = 'CURRENT'
ON CONFLICT(program_id, subject_id) DO NOTHING;

INSERT INTO student_program_enrollment(student_id, program_id, status)
SELECT st.id, p.id, CASE WHEN st.active THEN 'ACTIVE' ELSE 'PAUSED' END
FROM student st
JOIN curriculum_class c ON c.code = st.class_code
JOIN curriculum_program p ON p.class_id = c.id
  AND p.code = 'GENERAL' AND p.curriculum_version = 'CURRENT'
ON CONFLICT(student_id, program_id) DO NOTHING;

