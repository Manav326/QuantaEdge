-- V156: HRMS-approved, versioned discounts for institution marketplace offers.
-- All monetary values are INR paise. No code or discount value is seeded.
CREATE TABLE course_discount_offer (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  institution_offer_id bigint NOT NULL REFERENCES institution_marketplace_offer(id) ON DELETE RESTRICT,
  code varchar(40) NOT NULL CHECK (code ~ '^[A-Z0-9][A-Z0-9_-]{2,39}$'),
  version integer NOT NULL CHECK (version > 0),
  currency char(3) NOT NULL DEFAULT 'INR' CHECK (currency ~ '^[A-Z]{3}$'),
  discount_type varchar(16) NOT NULL CHECK (discount_type IN ('PERCENTAGE','FLAT')),
  percentage_basis_points integer CHECK (percentage_basis_points IS NULL OR percentage_basis_points BETWEEN 1 AND 10000),
  flat_amount_paise bigint CHECK (flat_amount_paise IS NULL OR flat_amount_paise > 0),
  max_discount_paise bigint CHECK (max_discount_paise IS NULL OR max_discount_paise > 0),
  min_listed_price_paise bigint NOT NULL DEFAULT 0 CHECK (min_listed_price_paise >= 0),
  effective_from timestamptz NOT NULL,
  effective_until timestamptz,
  status varchar(20) NOT NULL DEFAULT 'DRAFT'
    CHECK (status IN ('DRAFT','PENDING_APPROVAL','APPROVED','RETIRED')),
  created_by_staff_id bigint REFERENCES staff_account(id) ON DELETE RESTRICT,
  approved_by_staff_id bigint REFERENCES staff_account(id) ON DELETE RESTRICT,
  approved_at timestamptz,
  retired_by_staff_id bigint REFERENCES staff_account(id) ON DELETE RESTRICT,
  retired_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (effective_until IS NULL OR effective_until > effective_from),
  CHECK ((discount_type='PERCENTAGE' AND percentage_basis_points IS NOT NULL AND flat_amount_paise IS NULL)
      OR (discount_type='FLAT' AND flat_amount_paise IS NOT NULL AND percentage_basis_points IS NULL)),
  CHECK ((status='APPROVED' AND approved_by_staff_id IS NOT NULL AND approved_at IS NOT NULL) OR status<>'APPROVED'),
  CHECK ((status='RETIRED' AND retired_by_staff_id IS NOT NULL AND retired_at IS NOT NULL) OR status<>'RETIRED')
);
CREATE UNIQUE INDEX uq_course_discount_offer_code_version
  ON course_discount_offer(institution_offer_id,upper(code),version);
CREATE INDEX idx_course_discount_offer_effective
  ON course_discount_offer(institution_offer_id,status,effective_from,effective_until);

ALTER TABLE course_payment_order
  ADD COLUMN discount_offer_id bigint REFERENCES course_discount_offer(id) ON DELETE RESTRICT;

CREATE TABLE course_discount_redemption (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  discount_offer_id bigint NOT NULL REFERENCES course_discount_offer(id) ON DELETE RESTRICT,
  course_payment_order_id bigint NOT NULL UNIQUE REFERENCES course_payment_order(id) ON DELETE RESTRICT,
  purchaser_user_account_id bigint NOT NULL REFERENCES user_account(id) ON DELETE RESTRICT,
  institution_offer_id bigint NOT NULL REFERENCES institution_marketplace_offer(id) ON DELETE RESTRICT,
  code_snapshot varchar(40) NOT NULL,
  discount_amount_paise bigint NOT NULL CHECK (discount_amount_paise > 0),
  status varchar(16) NOT NULL DEFAULT 'RESERVED' CHECK (status IN ('RESERVED','REDEEMED','RELEASED')),
  reserved_at timestamptz NOT NULL DEFAULT now(),
  redeemed_at timestamptz,
  released_at timestamptz,
  CHECK ((status='REDEEMED' AND redeemed_at IS NOT NULL) OR status<>'REDEEMED'),
  CHECK ((status='RELEASED' AND released_at IS NOT NULL) OR status<>'RELEASED')
);
CREATE INDEX idx_course_discount_redemption_offer_status
  ON course_discount_redemption(discount_offer_id,status,reserved_at DESC);

CREATE OR REPLACE FUNCTION protect_approved_course_discount_offer()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.status IN ('PENDING_APPROVAL','APPROVED','RETIRED')
      AND ROW(NEW.institution_offer_id,NEW.code,NEW.version,NEW.currency,NEW.discount_type,
          NEW.percentage_basis_points,NEW.flat_amount_paise,NEW.max_discount_paise,
          NEW.min_listed_price_paise,NEW.effective_from,NEW.effective_until)
        IS DISTINCT FROM
        ROW(OLD.institution_offer_id,OLD.code,OLD.version,OLD.currency,OLD.discount_type,
          OLD.percentage_basis_points,OLD.flat_amount_paise,OLD.max_discount_paise,
          OLD.min_listed_price_paise,OLD.effective_from,OLD.effective_until) THEN
    RAISE EXCEPTION 'Submitted discount terms are immutable; create a new version' USING ERRCODE='23514';
  END IF;
  IF OLD.status='APPROVED' AND NEW.status NOT IN ('APPROVED','RETIRED') THEN
    RAISE EXCEPTION 'An approved discount can only remain approved or be retired' USING ERRCODE='23514';
  END IF;
  IF OLD.status='PENDING_APPROVAL' AND NEW.status NOT IN ('PENDING_APPROVAL','APPROVED','RETIRED') THEN
    RAISE EXCEPTION 'A pending discount can only be approved or retired' USING ERRCODE='23514';
  END IF;
  IF OLD.status='RETIRED' AND NEW.status<>'RETIRED' THEN
    RAISE EXCEPTION 'A retired discount cannot be reactivated; create a new version' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER trg_course_discount_offer_terms_immutable
BEFORE UPDATE ON course_discount_offer
FOR EACH ROW EXECUTE FUNCTION protect_approved_course_discount_offer();

-- V151 attached the existing lock trigger; replacing its function extends that same trigger.
CREATE OR REPLACE FUNCTION lock_verified_course_order_financial_snapshot()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.status='VERIFIED' AND ROW(
      NEW.listed_price_paise,NEW.discount_offer_id,NEW.discount_amount_paise,NEW.discount_reference,
      NEW.discount_snapshot,NEW.tax_profile_id,NEW.taxable_value_paise,NEW.output_tax_paise,
      NEW.tax_calculation_snapshot,NEW.buyer_snapshot,NEW.captured_amount_paise,NEW.captured_at,
      NEW.revenue_share_policy_id,NEW.revenue_share_policy_snapshot,NEW.fiscal_document_id
    ) IS DISTINCT FROM ROW(
      OLD.listed_price_paise,OLD.discount_offer_id,OLD.discount_amount_paise,OLD.discount_reference,
      OLD.discount_snapshot,OLD.tax_profile_id,OLD.taxable_value_paise,OLD.output_tax_paise,
      OLD.tax_calculation_snapshot,OLD.buyer_snapshot,OLD.captured_amount_paise,OLD.captured_at,
      OLD.revenue_share_policy_id,OLD.revenue_share_policy_snapshot,OLD.fiscal_document_id
    ) THEN
    RAISE EXCEPTION 'Verified course-order financial facts are immutable; use a fiscal adjustment'
      USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION sync_course_discount_redemption_status()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.status='VERIFIED' AND OLD.status IS DISTINCT FROM NEW.status THEN
    UPDATE course_discount_redemption SET status='REDEEMED',redeemed_at=now(),released_at=NULL
      WHERE course_payment_order_id=NEW.id AND status IN ('RESERVED','RELEASED');
  ELSIF NEW.status IN ('FAILED','EXPIRED') AND OLD.status IS DISTINCT FROM NEW.status THEN
    UPDATE course_discount_redemption SET status='RELEASED',released_at=now()
      WHERE course_payment_order_id=NEW.id AND status='RESERVED';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER trg_course_order_discount_redemption_status
AFTER UPDATE OF status ON course_payment_order
FOR EACH ROW EXECUTE FUNCTION sync_course_discount_redemption_status();

