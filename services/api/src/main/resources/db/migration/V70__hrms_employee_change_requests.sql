-- Employee self-service profile edits are requests, never direct writes to HR-owned records.
create table hr_employee_change_request (
  id bigint generated by default as identity primary key,
  public_id uuid not null unique default gen_random_uuid(),
  employee_id bigint not null references hr_employee(id) on delete restrict,
  requested_by_staff_id bigint not null references staff_account(id) on delete restrict,
  requested_values jsonb not null check (jsonb_typeof(requested_values)='object' and requested_values<>'{}'::jsonb),
  reason varchar(1000) not null check (length(trim(reason))>0),
  request_status varchar(16) not null default 'PENDING'
    check (request_status in ('PENDING','APPROVED','REJECTED','CANCELLED')),
  review_note varchar(1000),
  reviewed_by_staff_id bigint references staff_account(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((request_status in ('PENDING','CANCELLED') and reviewed_at is null)
      or (request_status in ('APPROVED','REJECTED') and reviewed_at is not null))
);
create index idx_hr_employee_change_request_employee on hr_employee_change_request(employee_id,created_at desc,id desc);
create index idx_hr_employee_change_request_status on hr_employee_change_request(request_status,created_at) where request_status='PENDING';
create unique index uq_hr_employee_change_request_pending_employee
  on hr_employee_change_request(employee_id) where request_status='PENDING';

insert into staff_permission_catalog(permission_key,display_name,description) values
 ('HR_EMPLOYEE_CHANGE_REVIEW','Review employee self-service profile changes','Approve or reject employee-submitted contact detail changes and record the decision.')
on conflict(permission_key) do update set display_name=excluded.display_name,description=excluded.description;
